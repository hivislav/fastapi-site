"""Pydantic-схемы запросов и ответов API."""

from typing import List, Literal, Optional

from pydantic import BaseModel, Field

# Доступные форматы ответа бота.
# "free" — ИИ отвечает свободным текстом; "json" — ответ представляется в JSON.
ResponseFormat = Literal["free", "json"]

# Режимы экспертного поведения модели (выбираются радиокнопками в эксперте).
# "direct" — максимально сухой прямой ответ; "stepwise" — решение по шагам;
# "prompt" — составление промпта и ответ на него; "group" — группа экспертов.
ExpertModeType = Literal["direct", "stepwise", "prompt", "group"]

# Стратегии работы «AI-агента» с контекстом (выпадающий список «Стратегия» в
# панели режима агента):
# "summary"   — вся история видна в чате, а в контекст идут последние N
#               сообщений «как есть» + резюме старой части;
# "sliding"   — в контекст идут последние N сообщений переписки (окно);
# "facts"     — блок фактов (ключ-значение, обновляется каждый запрос) +
#               последние N сообщений;
# "branching" — план из 3–5 ветвей и независимый диалог в выбранной ветке.
AgentStrategy = Literal["summary", "sliding", "facts", "branching"]


class ChatMessage(BaseModel):
    """Сообщение, отправляемое пользователем в чат."""

    content: str
    format: ResponseFormat = "free"
    # Ограничение длины ответа в токенах. Если не задано — используется
    # значение по умолчанию из конфигурации (LLM_MAX_TOKENS).
    max_tokens: Optional[int] = Field(default=None, ge=1)
    # Условие завершения: одна или несколько (через запятую) строк, на которых
    # LLM остановит генерацию (stop-последовательности).
    stop: Optional[str] = Field(default=None, max_length=200)
    # Экспертный режим: когда включён, применяется только выбранный
    # экспертный_mode, а format/max_tokens/stop не учитываются.
    expert_mode: bool = False
    expert_mode_type: ExpertModeType = "direct"
    # Роли экспертов для режима "group". Пустой список — ошибка.
    expert_roles: Optional[List[str]] = Field(default=None)
    # Настройка «Температура» (обычный режим). Каждое непустое значение —
    # отдельный запрос к LLM. Пустой/None — параметр не используется
    # (выполняется один запрос как обычно). Заполненные значения — числа.
    temperatures: Optional[List[float]] = Field(default=None)
    # Настройка «Тест моделей» (обычный режим): список ключей моделей, в каждую
    # из которых отправляется запрос. Пустой/None — параметр не используется.
    models: Optional[List[str]] = Field(default=None)
    # Режим «AI-агент», выпадающий список «Стратегия» в панели справа: как
    # агент работает с контекстом диалога (см. AgentStrategy выше). По умолчанию
    # «sliding» — окно последних сообщений.
    agent_strategy: AgentStrategy = "sliding"
    # Стратегия «summary»: поле «summary» — сколько последних сообщений агент
    # держит в контексте «как есть» (один запрос юзера = 2 сообщения: запрос +
    # ответ), а всё, что старше, сжимает в резюме. История в чате при этом не
    # затирается. None — значение по умолчанию агента. Минимум 2: пара
    # «запрос + ответ» должна оставаться в контексте целиком.
    summary: Optional[int] = Field(default=None, ge=2, le=200)
    # Стратегии «sliding» (sliding window) и «facts» (sticky facts): поле
    # «Количество сообщений в окне» — сколько последних сообщений переписки
    # (и юзера, и модели) уходит в контекст вместе с новым запросом.
    # None — значение по умолчанию агента (10).
    window: Optional[int] = Field(default=None, ge=1, le=200)
    # Стратегия «branching»: id ветки плана, в которой пользователь ведёт
    # диалог (интерфейс, список «Ветка»). None — корневой запрос: агент строит
    # план ветвления по всей истории чата и текущему запросу.
    branch: Optional[str] = Field(default=None, max_length=40)


# ---------------------------------------------------------------------------
# Задачи и сессии (Workspace режима «AI-агент»)
# ---------------------------------------------------------------------------
class TaskCreate(BaseModel):
    """Создание задачи (кнопка «Новая задача» в панели Workspace).

    Задача — «контейнер» для диалогов: у каждой свой список сессий, и диалог
    нельзя начать, пока задача не создана.
    """

    name: str = Field(default="", max_length=120)


class NameUpdate(BaseModel):
    """Переименование задачи или сессии (карандаш в панели Workspace)."""

    name: str = Field(default="", max_length=200)


# Слои памяти, которые наполняет пользователь кнопками под сообщениями:
# "work" — рабочая память текущей задачи, "long" — долговременная (глобальная).
MemoryLayer = Literal["work", "long"]


class MemoryEntryCreate(BaseModel):
    """Запись в слой памяти агента («добавить в рабочую/долговременную память»)."""

    layer: MemoryLayer = "work"
    text: str = Field(default="", max_length=4000)
    # Откуда запись: "user" (сообщение пользователя) или "assistant" (ответ агента).
    source: str = Field(default="", max_length=20)