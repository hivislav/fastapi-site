"""РЕЖИМ ТЕХНИЧЕСКОЙ ПОДДЕРЖКИ: команда `/support` — ответ по выбранному обращению.

ЧТО ЭТО. Человек пишет в чат `/support <номер обращения> <вопрос>` (номер — из
своей системы поддержки; в примерах ниже встречается `TCK-1041` — это номер из
ДЕМОНСТРАЦИОННЫХ данных проекта, а не «правильный» номер) — и
получает ответ ПОДДЕРЖКИ: что случилось у клиента (по данным обращения и
переписке), что уже сделали и что делать дальше, а механика продукта берётся из
документации со ссылками на фрагменты. Ответ строится по трём источникам:

* **ВЫБРАННОЕ ОБРАЩЕНИЕ И ЕГО КЛИЕНТ** — через MCP (сервер `support`,
  mcp_servers/tickets.mjs). Номер обращения называет САМ ЧЕЛОВЕК в команде, а не
  модель: она ищет обращение по словам, значит может найти не то;
* **ДОКУМЕНТАЦИЯ ПРОДУКТА** — включённые базы знаний проекта и тот же поиск
  (`rag_search.search`) с теми же настройками, что у агента; под ответом карточки
  источников с цитатой и переходом к чанку;
* **ЗАПРОС ОБРАЩЕНИЙ БЕЗ НОМЕРА** — когда номер не назван, но вопрос про
  обращения («что у клиента в работе?», «заведи обращение по жалобе»), набор
  вызовов выбирает диспетчер MCP — но ТОЛЬКО среди инструментов сервера
  поддержки (`filter_calls`).

ПОЧЕМУ ОТДЕЛЬНАЯ КОМАНДА, А НЕ ОБЫЧНЫЙ ЗАПРОС. Данные обращений — это данные
КОНКРЕТНОГО человека, и подмешивать их в каждый ответ агента нельзя: обычный
вопрос «почему не работает авторизация?» уходил бы в переписку случайного
клиента. Поэтому сервер поддержки помечен в реестре как командный (`command` в
записи `SERVERS`): в запросах агента его инструментов нет вовсе
(`mcp_store.agent_enabled`), и открыть их можно ТОЛЬКО командой. То же и с
изменениями: обращение заводится и дописывается лишь здесь, и лишь по прямой
просьбе (`writes_allowed`).

ЧЕГО ЗДЕСЬ НЕТ (и это осознанно). Ни истории разговора, ни памяти задачи:
ответ поддержки — про конкретное обращение, и прошлые реплики его исказили бы.
Профиль клиента, наоборот, УЧИТЫВАЕТСЯ: его стиль общения, формат ответа и
ограничения уходят в промпт отдельным блоком (решение 15.10). Команда идёт МИМО пайплайна задачи (ни
плана, ни подтверждения, ни шагов, ни автомата), пишет только в журнал чата —
как `/help` и `/test_rag` (§5.11в, §5.13.2).

ЧТО МОДУЛЬ НЕ ДЕЛАЕТ. Он не ходит ни в модели, ни в MCP, ни в файлы: разбор
команды, признаки, набор вызовов, промпты и сборка сообщений — чистые функции.
Выполняет вызовы и зовёт модель веб-слой (`app/routers/chat.py`, маршрут
`POST /api/agent/support`), поэтому правила режима проверяются без сети и без
сервера (tools/check_support_mcp.py).
"""

import re
from typing import Any, Dict, List, Tuple

# Команда чата. Разбирается в интерфейсе (app/web/chat.html, как /help) и на
# сервере — сервер обязан отказать, если команда пришла не целиком: иначе
# «/support …» ушёл бы в модель обычным вопросом по документам.
COMMAND = "/support"

# Сервер MCP, из которого берутся данные поддержки (реестр — app/ai/mcp.py).
SERVER_ID = "support"
TICKET_TOOL = "get_ticket"
SEARCH_TOOL = "search_tickets"
CREATE_TOOL = "create_ticket"
COMMENT_TOOL = "add_comment"

# В РЕЖИМЕ ПОДДЕРЖКИ РАБОТАЕТ ТОЛЬКО ЭТОТ СЕРВЕР. Погода, курсы или репозиторий
# в ответе поддержки смысла не имеют, а вот лишние данные в контексте — вполне
# реальная цена: каждое обращение к чужому серверу это процесс, время и место в
# промпте.
MODE_SERVERS = (SERVER_ID,)

# Сколько вызовов допускает один запрос режима, когда номер не назван: поиск
# обращения, чтение выбранного, одна запись. Выбранное обращение по номеру
# читается ВСЕГДА одним вызовом и диспетчера не спрашивает.
MAX_MODE_CALLS = 3
MAX_TICKET_CALLS = 1

# Предел ответа поддержки: разбор обращения — несколько абзацев или список, а не
# документ (предел проекта и «Длина» из шапки чата его перебивают).
ANSWER_MAX_TOKENS = 1600

# Номер обращения в команде: «TCK-1041». Буквы, дефис, цифры — так номер
# отличается и от даты («2026-10-14»), и от номера версии.
TICKET_ID_RE = re.compile(r"\b[A-Za-z]{2,10}-\d{2,10}\b")
# И «1041» без префикса: в команде человек называет номер как помнит, а сервер
# разрешает неполный номер, если он ОДНОЗНАЧЕН (иначе он честно откажет).
BARE_ID_RE = re.compile(r"^\d{3,10}$")

# Вопрос по умолчанию: команду набирают и с одним номером («/support TCK-1041»),
# и тогда человек ждёт разбор этого обращения.
DEFAULT_QUESTION = ("Что известно по этому обращению, что уже сделала поддержка и "
                    "что делать дальше?")

# ПРИЗНАКИ ПРЯМОЙ ПРОСЬБЫ ЧТО-ТО ИЗМЕНИТЬ. Заводить обращение и писать в переписку
# режим вправе только тогда, когда человек об этом ПОПРОСИЛ: иначе модель на
# вопросе «что с обращением TCK-1041?» могла бы «на всякий случай» дописать
# клиенту ответ, которого никто не поручал. Слова нейтральны к формулировке, но
# предметны: «заведи», «создай», «запиши», «ответь клиенту».
WRITE_MARKERS = (
    "завед", "созда", "зарегистр", "оформ", "открой обращ", "новое обращ",
    "новый тикет", "новое тикет", "запиши", "записать", "внеси", "добавь коммент",
    "оставь коммент", "допиши", "ответь клиент", "ответ клиент", "напиши клиент",
    "отправь ответ", "сообщи клиент",
)

# ГДЕ КАКОЙ АРГУМЕНТ ОГРАНИЧИВАЕТ ДАННЫЕ ТЕКУЩИМ КЛИЕНТОМ. Решает КОД, а не
# модель: она не должна выбирать, чьи обращения показывать (живой случай 15.10 —
# на вопрос «не получается найти файл через rag» в ответ попали обращения ДРУГИХ
# клиентов: TCK-1039 Дмитрия и TCK-1042 Анны). Ключ — имя инструмента, значение —
# имя аргумента, в который подставляется клиент.
CLIENT_ARGUMENTS = {
    "search_tickets": "user",
    "list_tickets": "user",
    "get_ticket": "client",
}

# Инструменты «про клиентов вообще»: в ответе поддержки они дают только чужие
# имена и другие обращения, поэтому в режиме отбрасываются (причина — в журнал).
CLIENT_DIRECTORY_TOOLS = ("list_users", "get_user")

# Инструменты, которые ЧТО-ТО МЕНЯЮТ (по префиксу имени — та же договорённость,
# что у клиента агента, см. mcp.RESULT_RE).
WRITE_PREFIXES = ("create_", "add_", "save_", "update_", "set_", "delete_", "remove_")

# Сколько символов вопроса уходит в поиск по базе знаний.
QUERY_CHARS = 300


def is_command(text: Any) -> bool:
    """Команда ли это `/support` (в том числе с номером и вопросом)."""
    value = str(text or "").strip()
    if not value.lower().startswith(COMMAND):
        return False
    rest = value[len(COMMAND):]
    # «/supporter» и «/support-me» — НЕ наша команда: после неё должен идти конец
    # строки или пробел, иначе обычный текст уходил бы в режим поддержки.
    return not rest or rest[0].isspace()


def ticket_id(text: Any) -> str:
    """Номер обращения из строки: «TCK-1041» или «1041» (иначе пусто).

    Номер берётся из ПЕРВОГО слова: в команде он стоит сразу после `/support`, а
    дальше идёт вопрос, в котором номер может упоминаться уже по смыслу («а что с
    TCK-9999?») — выбирать обращение по упоминанию в вопросе значило бы отвечать
    не по тому, которое человек назвал.
    """
    first = str(text or "").strip().split(" ")[0] if str(text or "").strip() else ""
    if not first:
        return ""
    if BARE_ID_RE.match(first):
        return first
    match = TICKET_ID_RE.match(first)
    if match and match.group(0).split("-", 1)[0].isupper():
        return match.group(0)
    return ""


def parse(text: Any) -> Tuple[bool, str, str]:
    """Разбор команды: (это команда, номер обращения, вопрос).

    Формы, которые понимает режим:

      * `/support TCK-1041 почему не работает вход?` — выбранное обращение и
        вопрос по нему (основная форма: так работает референс);
      * `/support TCK-1041` — вопроса нет: отвечаем разбором обращения
        (`DEFAULT_QUESTION`);
      * `/support заведи обращение по жалобе на выгрузку` — номера нет: вопрос
        пойдёт диспетчеру, и он вправе выбрать чтение или создание.

    Пустой вопрос без номера (`/support`) — тоже законный разбор: `question()`
    подставит вопрос по умолчанию, и это честнее отказа: человек набрал команду
    без аргументов и ждёт, что она расскажет о режиме.
    """
    value = str(text or "").strip()
    if not is_command(value):
        return False, "", ""
    rest = value[len(COMMAND):].strip()
    number = ticket_id(rest)
    if number:
        rest = rest[len(number):].strip()
    return True, number, rest


def question(text: Any) -> str:
    """Вопрос режима: из команды, а без вопроса — разбор выбранного обращения."""
    _, _, asked = parse(text)
    return asked or DEFAULT_QUESTION


def writes_allowed(text: Any) -> bool:
    """Просит ли человек ЧТО-ТО ИЗМЕНИТЬ (завести обращение, ответить клиенту).

    Решает КОД по словам просьбы, а не модель: без этого признака изменение
    выполнялось бы «по инициативе» модели — например, на обычном вопросе «что с
    обращением TCK-1041?» клиенту ушёл бы ответ, которого никто не поручал.
    """
    body = str(text or "").lower().replace("ё", "е")
    return any(marker in body for marker in WRITE_MARKERS)


def is_write(call: Any) -> bool:
    """Меняет ли вызов данные (по префиксу имени инструмента)."""
    tool = str((call or {}).get("tool") or "")
    return tool.startswith(WRITE_PREFIXES)


def scope_calls(calls: Any, client: str = "") -> List[Dict[str, Any]]:
    """Ограничить вызовы ТЕКУЩИМ клиентом: (вызовы, пояснения для журнала).

    Что делает: подставляет клиента в аргумент-фильтр (см. `CLIENT_ARGUMENTS`) и
    выбрасывает инструменты «про клиентов вообще». Пустой клиент (профиль не
    заполнен) ничего не меняет: тогда и ограничивать нечем — сервер сам откажет в
    чтении чужого обращения, если номер назван.

    Возвращает (вызовы, строки-пояснения): отброшенное называется словами, иначе
    молча сузившаяся выдача выглядела бы как «обращений нет».
    """
    who = str(client or "").strip()
    kept: List[Dict[str, Any]] = []
    notes: List[str] = []
    for call in calls or []:
        if not isinstance(call, dict):
            continue
        tool = str(call.get("tool") or "").strip()
        if who and tool in CLIENT_DIRECTORY_TOOLS:
            notes.append("вызов %s отброшен: в режиме поддержки показываются "
                         "только обращения текущего клиента" % tool)
            continue
        argument = CLIENT_ARGUMENTS.get(tool)
        if who and argument:
            arguments = call.get("arguments")
            if not isinstance(arguments, dict):
                arguments = {}
                call["arguments"] = arguments
            arguments[argument] = who
        kept.append(call)
    return kept, notes


def fetch_calls(ticket: str, client: str = "") -> List[Dict[str, Any]]:
    """Вызов чтения ВЫБРАННОГО обращения — по номеру из команды.

    Вызов задан кодом, а не диспетчером: номер уже назван человеком, и
    спрашивать модель «какой инструмент тут нужен» — это платный служебный вызов
    за предсказуемый ответ. Обращение приходит вместе с карточкой клиента
    (имя и id), поэтому второго вызова не нужно.
    """
    number = str(ticket or "").strip()
    if not number:
        return []
    arguments: Dict[str, Any] = {"id": number}
    if str(client or "").strip():
        # Принадлежность проверит СЕРВЕР (аргумент `client`): чужое обращение он
        # не отдаст, и запрос остановится до вызова модели.
        arguments["client"] = str(client).strip()
    return [{"server": SERVER_ID, "tool": TICKET_TOOL, "arguments": arguments}]


def filter_calls(calls: Any, allow_writes: bool = False
                 ) -> Tuple[List[Dict[str, Any]], List[str]]:
    """Оставить только вызовы режима поддержки: (вызовы, строки-пояснения).

    Две отсечки, и обе называют себя словами (молча выброшенный вызов выглядел бы
    как «инструмент не сработал», а не как решение кода):

      * сервер не из режима (`MODE_SERVERS`) — погода и репозиторий в ответе
        поддержки не нужны;
      * изменение без прямой просьбы человека (`allow_writes`) — заводить
        обращение и писать клиенту режим вправе только по просьбе.
    """
    kept: List[Dict[str, Any]] = []
    notes: List[str] = []
    for call in calls or []:
        if not isinstance(call, dict):
            continue
        server = str(call.get("server") or "").strip()
        tool = str(call.get("tool") or "").strip()
        if not server or not tool:
            continue
        if server not in MODE_SERVERS:
            notes.append("вызов %s · %s отброшен: в режиме поддержки работает "
                         "только сервер «%s»" % (server, tool, SERVER_ID))
            continue
        if is_write(call) and not allow_writes:
            notes.append("изменение %s · %s отложено: в запросе нет прямой просьбы "
                         "что-то менять (нет слов «заведи», «запиши», «ответь "
                         "клиенту»)" % (server, tool))
            continue
        kept.append(call)
    return kept[:MAX_MODE_CALLS], notes


