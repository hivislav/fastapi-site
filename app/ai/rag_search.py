# ---------------------------------------------------------------------------
# Подпись данных: тот же запрос — те же фрагменты
# ---------------------------------------------------------------------------
def corpus_stamp(base_ids: Any, profile: Optional[str] = None) -> str:
    """Отпечаток содержимого баз: идентификатор + время последнего изменения.

    Нужен, чтобы сохранённые фрагменты не пережили ПЕРЕИНДЕКСАЦИЮ: база та же,
    запрос тот же, а документы внутри уже другие. Без отпечатка агент отвечал бы
    по фрагментам прежней версии документа, пока пользователь не напишет запрос
    заново. Читается из паспорта базы (`updated`), то есть с диска и без индекса.
    """
    parts: List[str] = []
    for base_id in (base_ids if isinstance(base_ids, list) else []):
        if not rag_store.valid_id(base_id):
            continue
        meta = rag_store.get_base(base_id, profile=profile) or {}
        parts.append("%s@%s" % (str(base_id).lower(),
                                str(meta.get("updated") or meta.get("created") or "")))
    return ",".join(parts)[:600]


def signature(base_ids: Any, request: str, stamp: str = "") -> str:
    """Подпись данных RAG: включённые базы + их отпечаток + запрос задачи."""
    ids = [str(item).strip().lower() for item in (base_ids if isinstance(base_ids, list) else [])
           if str(item or "").strip()]
    flat = " ".join(str(request or "").split())[:QUERY_CHARS]
    return "|".join(ids + [str(stamp or "")[:600], flat])[:1200]


# ---------------------------------------------------------------------------
# Поиск
# ---------------------------------------------------------------------------
def search(base_ids: Any, query: Any, *, profile: Optional[str] = None,
           limit: Optional[int] = None,
           threshold: Optional[float] = None,
           settings: Any = None,
           rewrite: Any = None,
           also: Any = None) -> Dict[str, Any]:
    """Ищет фрагменты во ВСЕХ указанных базах. Возвращает данные RAG.

    Результат: `{"query", "bases", "hits", "notes", "stages", "rewrite"}`:

      * `bases` — что стало с каждой базой (сколько фрагментов дала, почему
        пропущена): это диагностика для чата, а не данные для модели;
      * `hits` — отобранные фрагменты, от лучшего к худшему;
      * `notes` — причины отказов человеческим языком;
      * `stages` — счётчики ДВУХ ЭТАПОВ (сколько кандидатов взял первый, сколько
        осталось после реранкинга и порога): по ним строка дебага говорит, что
        именно произошло, а не только «нашлось столько-то»;
      * `rewrite` — сведения о переформулировке запроса (её делает веб-слой ДО
        поиска, см. app/ai/rag_query.py): поиск только переносит их в результат,
        чтобы диагностика и интерфейс видели, по какому запросу искали.

    ДВА ЭТАПА. Первый — `rag_store.search` по всей базе: он обязан быть дешёвым,
    поэтому считает только косинус и долю слов запроса, и берёт ШИРОКИЙ пул
    кандидатов (`top_k_before`). Второй — `rag_rerank.rerank` по пулу: порядок слов,
    заголовок и раздел, штраф коротким чанкам без слов запроса; после него
    остаётся `top_k_after` фрагментов (и только те, что прошли порог, если
    фильтрация включена). Выключатели и размеры приходят из `settings`
    (`search_settings`), а `limit`/`threshold` остаются для прямых вызовов и
    проверок: они перекрывают настройки выборки и порога.

    Сбой одной базы НЕ отменяет поиск по остальным: у пользователя может быть
    десять баз, собранных разными бэкендами, и отказ одной из них не повод
    оставить ответ без знаний из других.
    """
    text = " ".join(str(query or "").split())[:QUERY_CHARS]
    # ВТОРОЙ ЗАПРОС (обычно исходный текст пользователя, когда первый — его
    # переформулировка): ищем по ОБОИМ и объединяем пулы. Переформулировка тогда
    # ничего не теряет: неверная или слишком буквальная (живой случай — опечатка
    # «ьестия», которую модель переписала как есть, и нужный чанк не нашёлся)
    # может только ДОБАВИТЬ кандидатов, но не отнять то, что нашёл исходный текст.
    second = " ".join(str(also or "").split())[:QUERY_CHARS]
    if second and second == text:
        second = ""
    options = search_settings(settings)
    result: Dict[str, Any] = {
        "query": text,
        "bases": [],
        "hits": [],
        "notes": [],
        "rewrite": _rewrite_view(rewrite),
        # Оба запроса, по которым искали: переформулированный (если он был) и
        # исходный текст пользователя. Диагностика обязана называть оба — иначе
        # непонятно, почему нашлось то, чего в переформулировке нет.
        "queries": [item for item in (text, second) if item],
        "stages": _stages_view(options),
        # Чем продолжить, если ответа в документах нет. Веб-слой заменит это
        # списком, дополненным внешними инструментами проекта.
        "alternatives": list(DEFAULT_ALTERNATIVES),
        # По умолчанию считаем, что спрашивать некого (прямые вызовы поиска,
        # проверки): веб-слой ставит "ask"/"allowed" там, где знает пользователя.
        "general": "",
    }
    if not text:
        return result
    ids = [str(item or "").strip().lower() for item in
           (base_ids if isinstance(base_ids, list) else [])]
    ids = [item for item in dict.fromkeys(ids) if rag_store.valid_id(item)][:rag_store.MAX_BASES]
    if not ids:
        return result

    per_base = max(1, int(limit or options["top_k_after"]))
    # ДВЕ РАЗНЫЕ НАСТРОЙКИ, ДВЕ РАЗНЫЕ ШКАЛЫ — и путать их нельзя (правка 03.10):
    #
    #   * ФИЛЬТРАЦИЯ — порог ПЕРВИЧНОЙ РЕЛЕВАНТНОСТИ (`min_score`, шкала 0…2):
    #     косинус + доля слов запроса, ровно то число, которое человек видит в
    #     карточке источника («релевантность 0,73»). Считается БЕЗ модели и
    #     работает ВСЕГДА, независимо от реранкинга: отсекает мусор ещё до второго
    #     этапа, поэтому и пул реранкинга получается чище.
    #   * РЕРАНКИНГ — второй этап: широкий пул, перестановка и порог УВЕРЕННОСТИ
    #     МОДЕЛИ (`min_ce`, шкала 0…1, вероятность cross-encoder). Это настройка
    #     ВТОРОГО ЭТАПА: без реранкинга пула нет, и вероятностей тоже нет.
    #
    # Живой случай, ради которого правило разделено: в панели стоял «порог модели
    # 0,85», а в ответ уходили фрагменты с релевантностью 0,63…0,73. Человек
    # сравнивал порог с ПЕРВИЧНОЙ релевантностью (она и была видна в диалоге), а
    # порог относился ко второму этапу, которого в той конфигурации не было вовсе.
    # Никакой скрытой связи между настройками нет: реранкинг выключен — вероятностей
    # нет и порог уверенности НЕ применяется (об этом прямо говорит диагностика), а
    # первичная релевантность фильтруется своим ползунком и своим порогом.
    min_ce = float(options.get("min_ce") or 0.0)
    min_score = float(options.get("min_score") or 0.0)
    # Порог первичной релевантности — часть фильтрации; порог уверенности — часть
    # ВТОРОГО этапа, поэтому он требуется только при включённом реранкинге.
    score_required = bool(options["filter"]) and min_score > 0
    ce_required = bool(options["filter"]) and bool(options["rerank"]) and min_ce > 0
    # ШИРОКИЙ ПУЛ НУЖЕН ТОЛЬКО ВТОРОМУ ЭТАПУ: переставлять и отсеивать можно лишь
    # то, что уже нашлось. Выключенный реранкинг означает, что переставлять нечем —
    # тогда с базы берётся ровно то, что уйдёт в ответ (иначе в дебаге честно
    # писалось «берётся 20 кандидатов», а реранкинга не было вовсе).
    pool_size = (max(per_base, int(options["top_k_before"])) if options["rerank"]
                 else per_base)
    # ЧЕМ ОТСЕКАЕМ: явный порог вызова (прямые вызовы и проверки) главнее всего;
    # дальше — порог ПРОЕКТА, но только при включённой галочке «Фильтрация по
    # порогу»; снятая галочка оставляет БАЗОВЫЙ ОТСЕВ ШУМА (он был и в прежней
    # реализации). Поэтому «все галочки сняты» — это прежний поиск, а не поиск
    # без порога вовсе: фрагмент с оценкой около нуля в модель не пойдёт никогда.
    # Чем отсекаем — решается ПО КАЖДОЙ БАЗЕ, потому что реранкер может откатиться
    # с модели на признаки (модель упала, счёт не уложился в предел ожидания):
    #   * явный порог вызова (проверки, инструменты) главнее всего;
    #   * модель считала пул → фильтр это УВЕРЕННОСТЬ (`min_ce`, шкала 0…1),
    #     а оценка поиска не фильтруется вовсе: она СУММА (доходит до 3), и порог
    #     по ней человеку непонятен (живой случай: 2,49 у хорошего фрагмента);
    #   * работают признаки → вероятности нет, и порог по оценке поиска остаётся;
    #   * выключенная фильтрация → только базовый отсев шума.
    explicit_floor = None if threshold is None else float(threshold)
    found: List[Dict[str, Any]] = []
    for base_id in ids:
        meta = rag_store.get_base(base_id, profile=profile)
        if meta is None:
            result["notes"].append("база %s недоступна (удалена или чужая)" % base_id)
            continue
        name = str(meta.get("name") or "База знаний")
        entry: Dict[str, Any] = {"id": base_id, "name": name[:120], "hits": 0, "error": ""}
        chunks = int((meta.get("stats") or {}).get("chunks") or 0)
        reason = ""
        if not chunks:
            reason = "в базе нет чанков"
        if not reason:
            # Векторы разных бэкендов несравнимы: чужую базу пропускаем честно.
            reason = rag_embedding.check_compatible(meta)
        vector: List[float] = []
        if not reason:
            backend = str((meta.get("embedding") or {}).get("backend") or "")
            for probe in (text, second):
                if not probe:
                    continue
                try:
                    encoded, _info = rag_embedding.embed_query(probe, backend=backend)
                except Exception as exc:
                    reason = "вектор запроса не посчитан: %s" % str(exc)[:200]
                    logger.warning("RAG: запрос не закодирован для базы %s — %s",
                                   base_id, str(exc)[:200])
                    break
                if probe == text:
                    vector = encoded
        if not reason and not vector:
            reason = "вектор запроса пуст"
        if reason:
            entry["error"] = reason
            result["bases"].append(entry)
            result["notes"].append("база «%s» пропущена: %s" % (name, reason))
            continue
        try:
            # ПЕРВЫЙ ЭТАП: широкий пул кандидатов по всей базе. По КАЖДОМУ запросу
            # свой пул, затем объединение с квотами: половина мест — лучшим по
            # переформулированному, половина — лучшим по исходному.
            candidates = _merged_pool(base_id, profile, [(text, vector)],
                                      second, pool_size, backend)
        except Exception as exc:                    # pragma: no cover - защита
            entry["error"] = "поиск не удался: %s" % str(exc)[:200]
            result["bases"].append(entry)
            result["notes"].append("база «%s» пропущена: %s" % (name, entry["error"]))
            logger.warning("RAG: поиск по базе %s не удался — %s", base_id, str(exc)[:200])
            continue
        # ФИЛЬТРАЦИЯ ПО ПЕРВИЧНОЙ РЕЛЕВАНТНОСТИ — ДО ВТОРОГО ЭТАПА. Это порог по
        # косинусу и словам запроса: он не требует модели, работает всегда и
        # отсекает мусор раньше реранкинга (тому достаётся более чистый пул).
        # Явный аргумент `threshold` (прямые вызовы и проверки) главнее настройки.
        floor = explicit_floor if explicit_floor is not None else noise_floor()
        result["stages"]["threshold"] = round(float(floor), 6)
        # Базовый отсев шума действует ВСЕГДА (даже со снятой галочкой фильтрации):
        # фрагмент с оценкой около нуля не уходит в модель ни при какой настройке.
        before_score = len(candidates)
        raw_best = round(float(candidates[0].get("score") or 0.0), 6) if candidates else 0.0
        candidates = [hit for hit in candidates
                      if float(hit.get("score") or 0.0) >= floor]
        # БАЗОВЫЙ ОТСЕВ ШУМА (и явный порог вызова) — своим счётчиком: путать его
        # с порогом первичной релевантности нельзя, это разные причины.
        result["stages"]["floor_dropped"] += before_score - len(candidates)
        # СКОЛЬКО ОСТАЛОСЬ ПОСЛЕ БАЗОВОГО ОТСЕВА ШУМА: по этому диагностика
        # отличает «ничего близкого и не было» от «было, но отсеял порог».
        found_above_floor = len(candidates)
        score_floor = min_score if score_required else 0.0
        if score_floor > 0:
            cut_score = [float(hit.get("score") or 0.0) for hit in candidates
                         if float(hit.get("score") or 0.0) < score_floor]
            if cut_score:
                # ЛУЧШАЯ ОТСЕЧЁННАЯ ОЦЕНКА: из неё собирается КОНКРЕТНОЕ
                # предложение «снизить порог первичной релевантности до …».
                result["stages"]["cut_best_score"] = round(max(cut_score), 6)
            candidates = [hit for hit in candidates
                          if float(hit.get("score") or 0.0) >= score_floor]
            result["stages"]["score_applied"] = True
        result["stages"]["score_dropped"] += before_score - len(candidates) - (
            before_score - found_above_floor)
        # ВТОРОЙ ЭТАП: реранкинг пула и порог уверенности — уже по небольшому числу
        # чанков. ЧЕМ реранкить, решает модуль `rag_rerank`: признаки (без модели)
        # или cross-encoder; недоступная модель НЕ ломает поиск — модуль честно
        # откатывается на признаки и называет причину (она уходит в диагностику).
        rank_info: Dict[str, Any] = {}
        if options["rerank"]:
            ranked, rank_info = rag_rerank.rerank(candidates, text, options)
            if rank_info.get("backend"):
                result["stages"]["rerank_backend"] = str(rank_info["backend"])
                result["stages"]["rerank_model"] = str(rank_info.get("model") or "")
                if rank_info.get("reason") and not result["stages"]["rerank_reason"]:
                    result["stages"]["rerank_reason"] = str(rank_info["reason"])[:300]
        else:
            ranked = candidates
        result["stages"]["candidates"] += len(ranked)
        kept = ranked[:per_base]
        # «Рассмотрено» — сколько фрагментов дошло до порога: выборка после
        # реранкинга. По нему считается, сколько отсеял порог (иначе знаменатель
        # в диагностике был бы больше числителя и строка выглядела бы враньём).
        result["stages"]["considered"] += len(kept)
        ce_mode = str(rank_info.get("backend") or "") == "cross-encoder"
        result["stages"]["ce_required"] = ce_required
        if ce_required and not ce_mode:
            # ПОРОГ ВТОРОГО ЭТАПА ЗАДАН, А ВЕРОЯТНОСТЕЙ НЕТ (признаковый реранкинг,
            # модель не скачана, счёт не удался). Молчать об этом нельзя:
            # пользователь выставил порог и вправе считать, что он действует.
            # Причина уходит в данные и в блок: релевантность фрагментов модель
            # оценивает сама (BLOCK_THRESHOLD_NOTE). Второй этап при этом не
            # подменяется первым: это РАЗНЫЕ шкалы, и порог первичной релевантности
            # живёт своим ползунком.
            result["stages"]["ce_skipped"] = str(
                rank_info.get("reason")
                or rag_rerank.filter_reason(options.get("rerank_backend")))[:300]
        passed = kept
        # ПОРОГ УВЕРЕННОСТИ МОДЕЛИ (0…1) — по вероятности cross-encoder и ТОЛЬКО
        # когда модель действительно считала этот пул: у признакового реранкинга
        # вероятности нет, и подменять её смешанной оценкой нельзя (это разные
        # шкалы, а молчаливая подмена означала бы «порог применён не так»).
        if ce_required and min_ce > 0 and ce_mode:
            cut_ce = [float(hit.get("ce") or 0.0) for hit in passed
                      if float(hit.get("ce") or 0.0) < min_ce]
            if cut_ce:
                # ЛУЧШАЯ ВЕРОЯТНОСТЬ СРЕДИ ОТСЕЧЁННЫХ: по ней пользователю можно
                # предложить КОНКРЕТНЫЙ порог («снизить до 0,72 и повторить
                # поиск») — вариант решения, который действительно что-то делает.
                result["stages"]["cut_best_ce"] = round(max(cut_ce), 6)
            passed = [hit for hit in passed
                      if float(hit.get("ce") or 0.0) >= min_ce]
            result["stages"]["ce_applied"] = True
        result["stages"]["dropped"] += len(kept) - len(passed)
        kept = passed
        entry["pool"] = len(ranked)
        # ЛУЧШАЯ ОЦЕНКА ДО ПОРОГА: по ней диагностика отличает «в документах
        # ничего нет» от «нашлось, но всё ниже порога» — это разные ответы
        # пользователю (см. BELOW_THRESHOLD_NOTE и results_note).
        entry["considered_best"] = round(float(ranked[0].get("score") or 0.0), 6) if ranked else 0.0
        # Лучшая ПЕРВИЧНАЯ оценка ДО ПОРОГА: она нужна отдельно, потому что порог
        # первичной релевантности срабатывает РАНЬШЕ реранкинга и в
        # `considered_best` (уже после второго этапа) её бы не было видно. Именно по
        # ней диагностика отличает «порог отсёк близкое» от «близкого не было».
        entry["considered_score"] = raw_best
        entry["raw"] = before_score
        for hit in kept:
            found.append(_hit_view(hit, meta))
        entry["hits"] = len(kept)
        entry["best"] = round(float(kept[0].get("score") or 0.0), 6) if kept else 0.0
        # `found` — сколько база дала ВЫШЕ базового отсева шума: по этому видно,
        # «ничего не нашлось» или «нашлось, но всё ниже порога» (см. _base_outcome).
        entry["found"] = found_above_floor
        # Состояние базы в отчёте — ПОСЛЕ обоих этапов: по нему диагностика
        # говорит, что стало с каждой базой (сколько дала, сколько отсеяно).
        result["bases"].append(entry)

    picked = _pick(found, max_hits())
    result["hits"] = _with_neighbours(picked, ids, profile, max_hits())
    result["stages"]["kept"] = len([hit for hit in result["hits"]
                                    if not hit.get("neighbour")])
    return result


def _merged_pool(base_id: str, profile: Optional[str], first: List[Any],
                 second: str, pool_size: int, backend: str) -> List[Dict[str, Any]]:
    """Пул кандидатов из ОДНОГО ИЛИ ДВУХ запросов: объединение с квотами.

    Зачем два: переформулировка может быть неточной (живой случай — опечатка
    «ьестия», которую модель переписала как есть, и нужного чанка в пуле не
    оказалось). Поэтому поиск идёт по обоим запросам, а места в пуле делятся
    ПОРОВНУ: неверная переформулировка может добавить лишних кандидатов, но не
    отнимает то, что нашёл исходный текст. Размер пула при этом не растёт —
    значит, и цена второго этапа (реранкинг, у модели — пары) та же.
    """
    chunks: List[Dict[str, Any]] = []
    seen: Dict[str, int] = {}
    quota = max(1, int(pool_size) // 2)
    for query_text, vector in first:
        if vector:
            chunks.extend(rag_store.search(base_id, vector, top_k=pool_size,
                                           profile=profile, query_text=query_text))
    if second:
        try:
            encoded, _info = rag_embedding.embed_query(second, backend=backend)
        except Exception as exc:                      # второй запрос не обязателен
            logger.warning("RAG: второй запрос не закодирован — %s", str(exc)[:150])
            encoded = []
        if encoded:
            for hit in rag_store.search(base_id, encoded, top_k=quota,
                                        profile=profile, query_text=second):
                chunks.append(hit)
    picked: List[Dict[str, Any]] = []
    for hit in sorted(chunks, key=lambda item: float(item.get("score") or 0.0),
                      reverse=True):
        key = str(hit.get("chunk_id") or hit.get("index") or "")
        if key in seen:
            continue
        seen[key] = len(picked)
        picked.append(hit)
        if len(picked) >= pool_size:
            break
    return picked


def _stages_view(options: Dict[str, Any]) -> Dict[str, Any]:
    """Счётчики двух этапов: чем настраивался поиск и что с ним стало.

    Живут в данных RAG, потому что ими подписывается строка дебага в чате («было
    кандидатов 20, после отбора 4, порог отсеял 12»): без них пользователь видит
    только «нашлось фрагментов: 4» и не понимает, что порог или реранкинг что-то
    изменили. Значения пересчитываются на каждом поиске заново.
    """
    return {
        "rewrite": bool(options["rewrite"]),
        "rerank": bool(options["rerank"]),
        # `rerank_backend` здесь — ЗАПРОШЕННЫЙ бэкенд, `rerank_model`/`rerank_reason`
        # заполняет сам поиск: он один знает, чем реранкинг кончился (модель
        # посчитала, не скачана, упала).
        "rerank_backend": str(options.get("rerank_backend") or rag_rerank.backend()),
        "rerank_model": "",
        "rerank_reason": "",
        "filter": bool(options["filter"]),
        "top_k_before": int(options["top_k_before"]),
        "top_k_after": int(options["top_k_after"]),
        # ДВЕ РАЗНЫЕ ШКАЛЫ, и в данных они лежат рядом намеренно:
        #   * `min_score` — порог ПЕРВИЧНОЙ РЕЛЕВАНТНОСТИ (фильтрация, 0…2);
        #   * `min_ce` — порог УВЕРЕННОСТИ МОДЕЛИ (второй этап, 0…1).
        # `threshold` — фактически действующий отсев первого этапа (явный порог
        # вызова или базовый отсев шума).
        "threshold": round(noise_floor(), 4),
        "min_score": round(float(options.get("min_score") or 0.0), 4),
        "score_applied": False,
        "score_dropped": 0,
        # Сколько убрал БАЗОВЫЙ ОТСЕВ ШУМА (и явный порог вызова): отдельно от
        # порога первичной релевантности — это разные причины, и в диагностике они
        # названы раздельно.
        "floor_dropped": 0,
        # Лучшая ПЕРВИЧНАЯ оценка среди отсечённых порогом релевантности: из неё
        # получается конкретное предложение «снизить порог до …».
        "cut_best_score": 0.0,
        "min_ce": round(float(options["min_ce"]), 4),
        "ce_applied": False,
        # Порог ВТОРОГО этапа: `ce_required` — он задан (фильтрация + реранкинг +
        # порог), `ce_skipped` — вероятностей взять негде (причина здесь).
        # Скрытой связи с галочкой реранкинга нет: реранкинг выключен — порог
        # уверенности просто не применяется, и диагностика говорит это прямо.
        "ce_required": False,
        "ce_skipped": "",
        # Лучшая вероятность среди отсечённых порогом второго этапа.
        "cut_best_ce": 0.0,
        # Базовый отсев шума: действует всегда, даже со снятой галочкой.
        "floor": round(noise_floor(), 4),
        "candidates": 0,
        "considered": 0,
        "kept": 0,
        "dropped": 0,
    }


def _rewrite_view(raw: Any) -> Dict[str, Any]:
    """Сведения о переформулировке запроса к короткому виду (пусто — её не было)."""
    data = raw if isinstance(raw, dict) else {}
    query = " ".join(str(data.get("query") or "").split())[:QUERY_CHARS]
    if not query:
        return {}
    return {
        # Чем получен поисковый запрос: "model" — ответ модели, "local" — разбор
        # без модели, "none" — переформулировка не удалась, ищем по исходному.
        "by": str(data.get("by") or "")[:20],
        "query": query,
        "reason": str(data.get("reason") or "")[:200],
    }


def _hit_view(chunk: Dict[str, Any], meta: Dict[str, Any]) -> Dict[str, Any]:
    """Попадание поиска в том виде, в каком оно живёт дальше (диалог, блок, UI)."""
    text = str(chunk.get("text") or "")
    return {
        "base_id": str(meta.get("id") or ""),
        "base": str(meta.get("name") or "База знаний")[:120],
        "chunk_id": str(chunk.get("chunk_id") or ""),
        # НОМЕР чанка — тот же, что видит пользователь в просмотре чанков
        # («№ 1081»): по нему фрагмент из карточки источников находится глазами.
        "number": int(chunk.get("index") or 0) + 1,
        "source": str(chunk.get("source") or "")[:SOURCE_CHARS],
        "title": str(chunk.get("title") or "")[:SECTION_CHARS],
        "section": str(chunk.get("section") or "")[:SECTION_CHARS],
        "doc_index": int(chunk.get("doc_index") or 0),
        "position": int(chunk.get("position") or 0),
        # Сосед найденного фрагмента (продолжение таблицы/списка): не попадание,
        # а дополнение — помечается, чтобы и модель, и человек видели это.
        "neighbour": bool(chunk.get("neighbour")),
        "parent_chunk": int(chunk.get("parent_chunk") or 0),
        # Итоговая релевантность и её слагаемые: по ним видно, ПОЧЕМУ фрагмент
        # оказался вверху, — и это же показывает интерфейс. `vector_score` и
        # `lexical` считает первый этап, `phrase`/`address`/`penalty` — второй
        # (реранкинг; нули, если он выключен, — тогда и добавок нет).
        "score": round(float(chunk.get("score") or 0.0), 6),
        "vector_score": round(float(chunk.get("vector_score") or 0.0), 6),
        "lexical": round(float(chunk.get("lexical") or 0.0), 6),
        # РЕЛЕВАНТНОСТЬ ПЕРВИЧНОГО ПОИСКА: косинус + доля слов запроса, без
        # добавок второго этапа. Показывается человеку рядом с оценкой модели.
        "base_score": round(float(chunk.get("base_score")
                                  if chunk.get("base_score") is not None
                                  else (chunk.get("score") or 0.0)), 6),
        # `ce` — вероятность CROSS-ENCODER (второй этап моделью), ноль у
        # признакового реранкинга: по ней видно, что решила именно модель.
        "ce": round(float(chunk.get("ce") or 0.0), 6),
        "phrase": round(float(chunk.get("phrase") or 0.0), 6),
        "address": round(float(chunk.get("address") or 0.0), 6),
        "penalty": round(float(chunk.get("penalty") or 0.0), 6),
        "chars": len(text),
        "text": text[:chunk_chars()],
    }


def _with_neighbours(hits: List[Dict[str, Any]], base_ids: List[str],
                     profile: Optional[str], limit: int) -> List[Dict[str, Any]]:
    """Дополняет найденные фрагменты СОСЕДНИМИ по базе (продолжение таблиц и списков).

    Сосед не попадание: он не проходил отбор по релевантности и приходит БЕЗ
    оценки, с пометкой `neighbour` и номером того фрагмента, продолжением
    которого он является. В модель он уходит отдельной строкой с этой пометкой —
    «вот кусок той же таблицы», а не «вот ещё что-то похожее».

    Бюджет тот же (`limit`): сначала идут сами попадания, соседи занимают
    оставшееся место. Сосед берётся только у лучших попаданий (порядок — по
    релевантности) и только из ТОГО ЖЕ документа: чанк на границе файла иначе
    притащил бы продолжение чужого файла.
    """
    span = neighbours_span()
    if not span or not hits or len(hits) >= limit:
        return hits
    by_base: Dict[str, List[Dict[str, Any]]] = {}
    for hit in hits:
        by_base.setdefault(str(hit.get("base_id") or ""), []).append(hit)
    out = list(hits)
    present = {_chunk_number(hit) for hit in out}
    for base_id in base_ids:
        group = by_base.get(base_id) or []
        if not group or len(out) >= limit:
            continue
        # Номер соседа -> номер того попадания, продолжением которого он является.
        wanted: Dict[int, int] = {}
        for hit in group[:NEIGHBOUR_PARENT_HITS]:
            number = _chunk_number(hit)
            for step in range(1, span + 1):
                for other in (number - step, number + step):
                    if other > 0 and other not in wanted:
                        wanted[other] = number
        if not wanted:
            continue
        rows = rag_store.neighbours(base_id, [number - 1 for number in wanted],
                                    profile=profile)
        for row in rows:
            if len(out) >= limit:
                break
            number = _int(row.get("index")) + 1
            parent = wanted.get(number)
            if not parent or number in present:
                continue
            # Границы документов не смешиваются: сосед — только из того же файла.
            parent_hit = next((item for item in group
                               if _chunk_number(item) == parent), None)
            if parent_hit is None or row.get("doc_index") != parent_hit.get("doc_index"):
                continue
            view = _hit_view(row, {"id": base_id, "name": parent_hit.get("base") or ""})
            view["score"] = 0.0
            view["vector_score"] = 0.0
            view["lexical"] = 0.0
            view["neighbour"] = True
            view["parent_chunk"] = parent
            out.append(view)
            present.add(number)
    return out


def _chunk_number(hit: Dict[str, Any]) -> int:
    """Номер чанка попадания в базе (1-based, как в окне «чанки»)."""
    return max(1, _int(hit.get("number")))


def _pick(hits: List[Dict[str, Any]], limit: int) -> List[Dict[str, Any]]:
    """Отбор фрагментов: лучшие первыми, вложенные повторы — прочь, не больше лимита.

    Соседние чанки одного раздела перекрываются (перекрытие задано при
    индексации), поэтому в топ легко попадают два фрагмента, один из которых
    целиком содержится в другом. Модели такой повтор не добавляет ничего, а
    бюджет контекста занимает: оставляем только более полный (он и оценён выше,
    так как содержит запрос целиком).
    """
    ordered = sorted(hits, key=lambda item: float(item.get("score") or 0.0), reverse=True)
    picked: List[Dict[str, Any]] = []
    for hit in ordered:
        body = _comparable(hit.get("text"))
        dup = False
        for other in picked:
            if other["base_id"] != hit["base_id"] or other["doc_index"] != hit["doc_index"]:
                continue
            wider = _comparable(other.get("text"))
            if body and (body in wider or wider in body):
                dup = True
                break
        if dup:
            continue
        picked.append(hit)
        if len(picked) >= limit:
            break
    return picked


def _comparable(text: Any) -> str:
    """Текст фрагмента для СРАВНЕНИЯ: пробелы схлопнуты, концевая пунктуация убрана.

    Граница чанка может добавить или убрать точку в конце абзаца: без этой мелочи
    один и тот же текст считался бы двумя разными фрагментами и уходил в блок
    модели дважды, занимая бюджет контекста.
    """
    return " ".join(str(text or "").split()).strip(" .,;:!?…—-")


