def search_settings(raw: Any = None) -> Dict[str, Any]:
    """Настройки ПОИСКА к рабочему виду: настройка проекта поверх значений окружения.

    Сюда сводится вся панель «Поиск и ответы» диалога «База знаний»: три
    выключателя (переформулировка запроса, реранкинг, фильтрация по порогу), два
    размера выборки (до и после второго этапа) и ДВА порога, у каждого своя шкала:

      * `min_score` — порог ПЕРВИЧНОЙ РЕЛЕВАНТНОСТИ (фильтрация; косинус + слова
        запроса, 0…2) — то же число, что человек видит в карточке источника;
      * `min_ce` — порог УВЕРЕННОСТИ МОДЕЛИ (второй этап, реранкинг; 0…1).

    Незаданное (проект ещё не настраивали, поле битое, значение вне границ) берётся
    из окружения — так поведение поиска можно поменять и без интерфейса, а
    «настройка из файла» не может дать отрицательный порог или пул меньше топ-K.

    Один словарь на всё нужен потому, что им пользуются ТРИ места: сам поиск,
    снимок для интерфейса и дебаг в чате — и все три обязаны видеть одно и то же.
    """
    data = raw if isinstance(raw, dict) else {}
    rerank_defaults = rag_rerank.settings(data)
    settings = {
        "rewrite": _pick_flag(data.get("rewrite"), rewrite_enabled()),
        "rerank": _pick_flag(data.get("rerank"), rerank_enabled()),
        # ЧЕМ реранкить: признаки (без модели) или cross-encoder. Значение
        # проверяется по списку бэкендов — «настройка из файла» не может выбрать
        # несуществующий реранкер.
        "rerank_backend": rerank_defaults["rerank_backend"],
        "filter": _pick_flag(data.get("filter"), filter_enabled()),
        "top_k_before": _pick_int(data.get("top_k_before"), top_k_before(), 1, MAX_TOP_K),
        "top_k_after": _pick_int(data.get("top_k_after"), top_k(), 1, MAX_TOP_K),
        # ПОРОГ ПЕРВИЧНОЙ РЕЛЕВАНТНОСТИ (0…2): косинус + доля слов запроса — то
        # самое число, которое показывает карточка источника. Считается без
        # модели, работает всегда и режет ДО второго этапа.
        "min_score": _pick_float(data.get("min_score"), min_score(), 0.0,
                                 MIN_SCORE_LIMIT),
        # ПОРОГ УВЕРЕННОСТИ МОДЕЛИ (0…1): вероятность cross-encoder, часть ВТОРОГО
        # этапа. Ноль — не отсекать.
        "min_ce": _pick_float(data.get("min_ce"), min_ce(), 0.0, 1.0),
        "ask_when_empty": _pick_flag(data.get("ask_when_empty"), ask_when_empty()),
    }
    # Пул не может быть МЕНЬШЕ выборки: реранкинг переставляет и отсеивает уже
    # найденное, и «до» меньше «после» означало бы, что второй этап добирает
    # фрагменты из ничего.
    settings["top_k_before"] = max(settings["top_k_before"], settings["top_k_after"])
    # МИГРАЦИЯ ПРЕЖНЕГО УМОЛЧАНИЯ (20/5) — см. LEGACY_DEFAULTS выше.
    if (settings["top_k_before"], settings["top_k_after"]) == LEGACY_DEFAULTS:
        settings["top_k_before"] = _pick_int(None, top_k_before(), 1, MAX_TOP_K)
        settings["top_k_after"] = _pick_int(None, top_k(), 1, MAX_TOP_K)
    return settings


def _pick_flag(value: Any, default: bool) -> bool:
    """Значение-переключатель: None — по умолчанию, иначе по правилам _env_flag."""
    if value is None or value == "":
        return bool(default)
    if isinstance(value, str):
        return _env_flag_value(value, bool(default))
    return bool(value)


def _env_flag_value(raw: str, default: bool) -> bool:
    """Строка-переключатель (та же логика, что у _env_flag, но без окружения)."""
