"""Поиск по базам знаний (RAG) для ответа агента — от вопроса до фрагментов.

ЧТО ЗДЕСЬ ПРОИСХОДИТ (и почему модуль отдельный):

    вопрос пользователя (при включённой переформулировке — уточнённый запрос)
    → вектор запроса → ПЕРВЫЙ ЭТАП: широкий пул кандидатов по КАЖДОЙ базе
    → ВТОРОЙ ЭТАП: реранкинг пула и отсечение по порогу
    → системный блок для модели (ответ, план, проверка)
    + список источников для интерфейса

Оба этапа управляются настройками ПРОЕКТА (панель «Поиск и ответы»): переформулировать
запрос или нет, реранкинг (и ЧЕМ реранкить — признаки или cross-encoder),
фильтрация по порогу, сколько кандидатов берёт первый этап (top_k_before) и
сколько фрагментов уходит в модель после второго (top_k_after), каков порог
релевантности. Настройки хранятся в задаче-workspace
(`task["rag"]`), значения по умолчанию берутся из переменных окружения
(RAG_REWRITE, RAG_RERANK, RAG_FILTER, RAG_TOP_K_BEFORE, RAG_TOP_K, RAG_MIN_SCORE):
`search_settings` сводит их в один словарь, который и передаётся в `search`.

Индексацией занимается `rag.py` (файлы → чанки → эмбеддинги → индекс),
хранилищем — `rag_store.py`, векторами — `rag_embedding.py`, переформулировкой
запроса — `rag_query.py`. Этот модуль ничего не индексирует и не пишет: он ЧИТАЕТ
готовые индексы и превращает попадание поиска в то, что видит модель и пользователь.

ТРИ ПРАВИЛА, БЕЗ КОТОРЫХ RAG ВРЕДЕН:

1. **Вектор запроса считается ТЕМ ЖЕ бэкендом, что и база.** Векторы разных
   моделей и размерностей геометрически несравнимы: поиск по «чужой» базе выдал
   бы случайные фрагменты, и модель уверенно отвечала бы по ним. Поэтому перед
   поиском идёт `rag_embedding.check_compatible`, а несовместимая база честно
   пропускается с причиной (причина уходит в диагностику чата).

2. **Фрагмент — ДАННЫЕ, а не инструкция.** Документы пользователя могут
   содержать что угодно, в том числе «игнорируй предыдущие указания»: в блоке
   это сказано прямо, а правила блока запрещают выдавать общие знания за
   содержимое документов и придумывать источники.

3. **«Не нашлось» — это тоже результат.** Базы включены, поиск прошёл, а
   подходящих фрагментов нет (или все базы отказали): модель получает блок с
   честным «по этому запросу в документах ничего не нашлось», а не молчание —
   иначе она либо выдумает содержимое базы, либо объявит, что документов нет
   вовсе. Второй этап (`rag_rerank.rerank` + порог) отсекает шум: у
   встроенного офлайн-бэкенда нерелевантные фрагменты дают близость около нуля.

ЧТО ДАЁТ ВТОРОЙ ЭТАП (и почему он отдельный, а не «ещё один слагаемое в счёте»).
Первый этап ищет по ВСЕЙ базе и потому обязан быть дешёвым: косинус плюс доля слов
запроса (см. `rag_store.search`). Второй этап работает уже с небольшим пулом и
может позволить себе дорогие признаки: ПОРЯДОК слов (фраза «резервное копирование»
против тех же слов вразброс), совпадение с ЗАГОЛОВКОМ И РАЗДЕЛОМ (документ про это
вообще) и штраф коротким чанкам без слов запроса (та самая hubness: заголовок из
141 символа «похож на любой запрос»). Замер сравнения — `tools/check_rag_quality.py`.

СОХРАНЕНИЕ МЕЖДУ ЗАПРОСАМИ. Шаг плана и проверка результата приходят
ОТДЕЛЬНЫМИ HTTP-запросами, а поиск стоит времени (вектор запроса + перебор
индекса). Поэтому найденные фрагменты живут в диалоге (`dialog["rag"]`) под
подписью «базы + запрос + отпечаток индексов» (см. `signature`): тот же запрос
берёт готовые фрагменты, а переиндексация базы меняет отпечаток и заставляет
искать заново.
"""

