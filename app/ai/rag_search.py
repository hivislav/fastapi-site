def normalize(raw: Any) -> Dict[str, Any]:
    """Данные RAG к безопасному виду (битые/чужие значения — прочь).

    Хранится ровно то, что уже найдено: подпись (когда эти фрагменты годны),
    запрос, сами фрагменты, состояние баз и причины отказов. Тексты фрагментов
    обрезаются: файл диалога не должен расти вместе с базой знаний.

    Подпись здесь НЕ обязательна: этой же нормализацией пользуются блок для
    модели и карточки источников — они собираются из свежего результата поиска,
    у которого подписи ещё нет (её выдаёт веб-слой, см. `signature`). Данные БЕЗ
    подписи в диалог не пишутся — это проверяет `_normalize_dialog_rag`.
    """
    if not isinstance(raw, dict):
        # Голый список фрагментов — тоже законный вход (агент хранит hits, а не
        # всю запись поиска): оборачиваем, чтобы блок и карточки собирались из
        # одного кода.
        raw = {"hits": raw} if isinstance(raw, list) else {}
    hits: List[Dict[str, Any]] = []
    for item in (raw.get("hits") if isinstance(raw.get("hits"), list) else [])[:MAX_HITS]:
        if not isinstance(item, dict):
            continue
        text = str(item.get("text") or "")
        if not text.strip():
            continue
        try:
            score = round(float(item.get("score") or 0.0), 6)
        except (TypeError, ValueError):
            score = 0.0
        hits.append({
            "base_id": str(item.get("base_id") or "")[:40],
            "base": str(item.get("base") or "")[:120],
            "chunk_id": str(item.get("chunk_id") or "")[:120],
            "number": _int(item.get("number")),
            "source": str(item.get("source") or "")[:SOURCE_CHARS],
            "title": str(item.get("title") or "")[:SECTION_CHARS],
            "section": str(item.get("section") or "")[:SECTION_CHARS],
            "doc_index": _int(item.get("doc_index")),
            "position": _int(item.get("position")),
            "neighbour": bool(item.get("neighbour")),
            "parent_chunk": _int(item.get("parent_chunk")),
            "score": score,
            # Релевантность первичного поиска: у старых записей её нет — тогда
            # берётся итоговая (до второго этапа они совпадали).
            "base_score": _float(item.get("base_score")) or score,
            "vector_score": _float(item.get("vector_score")),
            "lexical": _float(item.get("lexical")),
            # Слагаемые ВТОРОГО этапа: по ним видно, что дал реранкинг (и что
            # снял штраф). Ноль — «реранкинг выключен» либо признак не сработал.
            "phrase": _float(item.get("phrase")),
            "address": _float(item.get("address")),
            "penalty": _float(item.get("penalty")),
            "ce": _float(item.get("ce")),
            "chars": _int(item.get("chars")) or len(text),
            "text": text[:chunk_chars()],
        })
    bases: List[Dict[str, Any]] = []
    for item in (raw.get("bases") if isinstance(raw.get("bases"), list) else [])[:rag_store.MAX_BASES]:
        if not isinstance(item, dict):
            continue
        bases.append({
            "id": str(item.get("id") or "")[:40],
            "name": str(item.get("name") or "")[:120],
            "hits": _int(item.get("hits")),
            # Сколько попаданий база дала ДО порога близости: по этому видно,
            # «ничего не нашлось» или «нашлось, но слишком далёкое».
            "found": _int(item.get("found")),
            # Сколько кандидатов база отдала ПЕРВЫМ этапом (пул для реранкинга) и
            # сколько вообще вернул первый этап до базового отсева шума.
            "pool": _int(item.get("pool")),
            "raw": _int(item.get("raw")),
            # Лучшая оценка ДО порога: по ней понятно, «ничего не нашлось» или
            # «нашлось, но порог всё отсёк».
            "considered_best": _float(item.get("considered_best")),
            # Лучшая ПЕРВИЧНАЯ оценка до порога: по ней видно, чем отсекал порог
            # первичной релевантности (он срабатывает РАНЬШЕ второго этапа).
            "considered_score": _float(item.get("considered_score")),
            "error": str(item.get("error") or "")[:300],
        })
    notes = [str(item)[:300] for item in (raw.get("notes") or []) if str(item or "").strip()]
    signature = str(raw.get("signature") or "").strip()[:1200]
    query = str(raw.get("query") or "")[:QUERY_CHARS]
    stages = _stages_view(search_settings(None))
    stored_stages = raw.get("stages") if isinstance(raw.get("stages"), dict) else {}
    if stored_stages:
        # Свежий результат поиска: счётчики и настройки в нём уже есть, и брать
        # их из окружения нельзя — проект мог быть настроен иначе.
        stages["rewrite"] = bool(stored_stages.get("rewrite"))
        stages["rerank"] = bool(stored_stages.get("rerank"))
        stages["filter"] = bool(stored_stages.get("filter"))
        stages["top_k_before"] = _int(stored_stages.get("top_k_before")) \
            or stages["top_k_before"]
        stages["top_k_after"] = _int(stored_stages.get("top_k_after")) \
            or stages["top_k_after"]
        if stored_stages.get("threshold") is not None:
            stages["threshold"] = _float(stored_stages.get("threshold"))
        if stored_stages.get("floor") is not None:
            stages["floor"] = _float(stored_stages.get("floor"))
        if stored_stages.get("min_ce") is not None:
            stages["min_ce"] = _float(stored_stages.get("min_ce"))
        stages["ce_applied"] = bool(stored_stages.get("ce_applied"))
        # ПОРОГ ПЕРВИЧНОЙ РЕЛЕВАНТНОСТИ и порог уверенности — оба обязаны
        # переживать запись файла, иначе после перечитывания журнала строка
        # диагностики врала бы про конкретный поиск (та же потеря, что была у
        # `stages` и `general`).
        if stored_stages.get("min_score") is not None:
            stages["min_score"] = _float(stored_stages.get("min_score"))
        stages["score_applied"] = bool(stored_stages.get("score_applied"))
        stages["score_dropped"] = _int(stored_stages.get("score_dropped"))
        stages["floor_dropped"] = _int(stored_stages.get("floor_dropped"))
        if stored_stages.get("cut_best_score") is not None:
            stages["cut_best_score"] = _float(stored_stages.get("cut_best_score"))
        stages["ce_required"] = bool(stored_stages.get("ce_required"))
        stages["ce_skipped"] = str(stored_stages.get("ce_skipped") or "")[:300]
        if stored_stages.get("cut_best_ce") is not None:
            stages["cut_best_ce"] = _float(stored_stages.get("cut_best_ce"))
        stages["rerank_backend"] = str(stored_stages.get("rerank_backend") or "")[:40]
        stages["rerank_model"] = str(stored_stages.get("rerank_model") or "")[:200]
        stages["rerank_reason"] = str(stored_stages.get("rerank_reason") or "")[:300]
        stages["candidates"] = _int(stored_stages.get("candidates"))
        stages["considered"] = _int(stored_stages.get("considered"))
        stages["kept"] = _int(stored_stages.get("kept"))
        stages["dropped"] = _int(stored_stages.get("dropped"))
    if not hits and not bases and not notes and not signature and not query:
        # Совсем пустая запись — это «поиска не было», а не «ничего не нашлось»:
        # иначе модель получала бы блок «фрагментов не нашлось» на каждый запрос
        # при выключенных базах.
        return {}
    return {
        "signature": signature,
        "request": str(raw.get("request") or "")[:QUERY_CHARS],
        "query": query,
        "bases": bases,
        "hits": hits,
        "notes": notes[:20],
        # Настройки и счётчики ДВУХ ЭТАПОВ + сведения о переформулировке запроса:
        # без них после перечитывания журнала нельзя сказать, что именно сделал
        # поиск («порог отсеял 12 из 16»), и дебаг врал бы умолчанием.
        "stages": stages,
        "rewrite": _rewrite_view(raw.get("rewrite")),
        # ЧЕМ ПРОДОЛЖИТЬ, если ответа в документах нет: список считает веб-слой
        # (`_rag_alternatives` в chat.py) из того, что у проекта РЕАЛЬНО есть, а
        # блок для модели его перечисляет. Хранится вместе с фрагментами: шаг
        # плана и проверка — отдельные запросы, и они обязаны видеть тот же список.
        "alternatives": [str(item)[:300] for item
                         in (raw.get("alternatives") or []) if str(item or "").strip()][:6],
        "queries": [" ".join(str(item).split())[:QUERY_CHARS]
                    for item in (raw.get("queries") or []) if str(item or "").strip()][:2],
        # Можно ли отвечать по общим знаниям по ЭТОМУ запросу: "ask" — ждём
        # решения пользователя, "allowed" — он разрешил, "" — спрашивать некого
        # (автономный прогон) или настройка проекта выключена.
        "general": str(raw.get("general") or "")[:10],
    }


def _int(value: Any) -> int:
    """Целое из значения любого вида (битое — 0)."""
    try:
        return int(value or 0)
    except (TypeError, ValueError):
        return 0


def _float(value: Any) -> float:
    """Число из значения любого вида (битое — 0.0)."""
    try:
        return round(float(value or 0.0), 6)
    except (TypeError, ValueError):
        return 0.0


def hits_of(raw: Any) -> List[Dict[str, Any]]:
    """Фрагменты данных RAG (битое — пусто)."""
    return normalize(raw).get("hits") or []


def has_hits(raw: Any) -> bool:
    """Есть ли найденные фрагменты (по ним решается, показывать ли источники)."""
    return bool(hits_of(raw))


