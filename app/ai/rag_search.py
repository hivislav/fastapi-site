def _env_int(name: str, default: int, low: int, high: int) -> int:
    """Целое из настроек с зажимом в границы (битое значение — по умолчанию)."""
    raw = (os.getenv(name) or "").strip()
    try:
        value = int(raw)
    except (TypeError, ValueError):
        value = default
    return max(low, min(high, value))


def _env_float(name: str, default: float, low: float, high: float) -> float:
    """Число из настроек с зажимом в границы (пусто/битое — по умолчанию)."""
    raw = (os.getenv(name) or "").strip().replace(",", ".")
    if not raw:
        return default
    try:
        value = float(raw)
    except ValueError:
        return default
    return max(low, min(high, value))


def _env_flag(name: str, default: bool) -> bool:
    """Переключатель из настроек: 1/да/on/true — включено, 0/нет/off — выключено.

    Пустое значение — по умолчанию. Так выключатель этапа живёт в окружении рядом
    с остальными настройками, а не отдельным соглашением.
    """
    raw = (os.getenv(name) or "").strip().lower()
    if not raw:
        return default
    if raw in ("0", "off", "no", "нет", "выкл", "false", "disable", "disabled"):
        return False
    if raw in ("1", "on", "yes", "да", "вкл", "true", "enable", "enabled"):
        return True
    return default


