def block(raw: Any) -> str:
    """Системный блок с фрагментами для МОДЕЛИ (пусто — поиска не было).

    Блок собирается в двух случаях: фрагменты есть — с правилами «опирайся и
    ссылайся»; фрагментов нет, но ПОИСК БЫЛ — с честным «не нашлось». Второй
    случай важнее, чем кажется: без него модель на вопрос «что сказано в
    регламенте?» просто сочинила бы регламент. И у него есть ДВА разных вида,
    которые нельзя путать:

      * «в документах этого нет» — поиск ничего не нашёл;
      * «фрагменты нашлись, но не прошли порог» (`BELOW_THRESHOLD_NOTE`) — значит,
        в документах что-то близкое ЕСТЬ, и честный ответ другой: сказать про
        порог и предложить его снизить. Путать это с «документов нет» — прямая
        ложь пользователю (живой случай: порог 1,75 отсекал в базе всё, и агент
        отвечал «в документах этого нет» про статью, которая лежала в базе).

    В обоих видах модель обязана не только сказать про отсутствие, но и
    ПРЕДЛОЖИТЬ, чем продолжить: список вариантов считает код (`alternatives` в
    данных поиска) — из того, что у проекта РЕАЛЬНО есть (внешние инструменты
    MCP, общие знания, уточнение запроса). Обещать «сейчас поищу в интернете»
    нельзя: сбор данных идёт следующим запросом, и это сказано модели прямо.
    """
    data = normalize(raw)
    if not data:
        return ""
    hits = data["hits"]
    lines: List[str] = []
    failed = [item for item in data["bases"] if item.get("error")]
    if not hits:
        cut_all = _cut_by_threshold(data)
        general = str(data.get("general") or "")
        if general == "ask":
            note = NO_HITS_NOTE_ASK
        elif general == "allowed":
            note = NO_HITS_NOTE_ALLOWED
        elif general == "continue":
            note = NO_HITS_NOTE_CONTINUE
        else:
            note = NO_HITS_NOTE
        lines.append(NO_HITS_HEADER)
        lines.append("")
        lines.append(note)
        if cut_all:
            # Порог отсёк найденное — это ещё и повод проверить настройку порога,
            # поэтому предупреждение идёт отдельным абзацем к любому состоянию.
            lines.append("")
            lines.append(BELOW_THRESHOLD_NOTE)
        # ПОРОГ ВТОРОГО ЭТАПА ЗАДАН, А ПРИМЕНИТЬ ЕГО НЕЧЕМ (реранкинг включён,
        # порог уверенности задан, вероятностей нет): об этом обязана знать и
        # модель — иначе выключенный порог выглядел бы работающим.
        stages_now = data.get("stages") or {}
        if (ce_threshold_requested(stages_now)
                and not stages_now.get("ce_applied")):
            lines.append("")
            lines.append(BLOCK_THRESHOLD_NOTE % (
                float(stages_now.get("min_ce") or 0.0),
                str(stages_now.get("ce_skipped")
                    or "модель-реранкер недоступна")[:200]))
        lines.append("")
        alternatives = data.get("alternatives") or []
        if alternatives:
            lines.append(NO_HITS_ALTERNATIVES_HEADER)
            lines.extend("- " + str(item)[:300] for item in alternatives[:6])
            lines.append("")
        lines.append("ОПРОШЕННЫЕ БАЗЫ: " + (", ".join(
            "%s — %s" % (item["name"], _base_outcome(item))
            for item in data["bases"]) or "нет"))
        if failed:
            lines.append("")
            lines.append(FAILED_NOTE)
        return "\n".join(lines)[:block_chars()]
    lines.append(BLOCK_HEADER)
    lines.append("")
    lines.append(BLOCK_RULES)
    lines.append("")
    # ПОРОГ ВТОРОГО ЭТАПА ЗАДАН, А ПРИМЕНИТЬ ЕГО НЕЧЕМ: фрагменты есть, но слабые
    # не отсеяны — значит решать, отвечают ли они на вопрос, приходится самой
    # модели. Без этого абзаца выключенный порог выглядел бы работающим.
    stages_now = data.get("stages") or {}
    if stages_now.get("ce_required") and not stages_now.get("ce_applied"):
        lines.append(BLOCK_THRESHOLD_NOTE % (
            float(stages_now.get("min_ce") or 0.0),
            str(stages_now.get("ce_skipped") or "модель-реранкер недоступна")[:200]))
        lines.append("")
    if failed:
        lines.append(FAILED_NOTE + " Пропущены: " + "; ".join(
            "%s (%s)" % (item["name"], item["error"]) for item in failed))
        lines.append("")
    used = sum(len(line) + 1 for line in lines)
    limit = block_chars()
    for number, hit in enumerate(hits, 1):
        head = "[%d] %s" % (number, _address(hit))
        room = limit - used - len(head) - 1
        if room < MIN_FRAGMENT_CHARS:
            lines.append("[…] остальные найденные фрагменты не поместились в блок.")
            break
        body = _clip(hit.get("text") or "", min(chunk_chars(), room))
        lines.append(head)
        lines.append(body)
        lines.append("")
        used += len(head) + len(body) + 2
    return "\n".join(lines).strip()[:block_chars()]


def digest(raw: Any) -> str:
    """КОРОТКАЯ сводка фрагментов для ПРИЁМЩИКА (этап validation).

    Приёмщику не нужен текст документов: он проверяет, соответствует ли ответ
    запросу и шагам плана, а ссылки на источники сверяет со списком. Полный
    блок (12 000 символов) на каждом акте проверки стоил дороже самой проверки
    (то же решение, что у блока MCP — см. `mcp_store.review_digest`).
    """
    data = normalize(raw)
    if not data:
        return ""
    hits = data["hits"]
    lines = ["ФРАГМЕНТЫ БАЗ ЗНАНИЙ (что было у модели по этому запросу):"]
    if not hits:
        lines.append("- подходящих фрагментов не нашлось — ссылки на документы "
                     "пользователя в ответе были бы выдуманными.")
        return "\n".join(lines)
    for hit in hits:
        lines.append("- " + _address(hit))
    lines.append("Источники, которых нет в этом списке, в ответе называть нельзя.")
    return "\n".join(lines)[:DIGEST_CHARS]


def score_threshold_requested(stages: Any) -> bool:
    """Задан ли порог ПЕРВИЧНОЙ РЕЛЕВАНТНОСТИ (фильтрация; модель не нужна).

    Признак нужен строке диагностики, блоку для модели и выбору варианта «снизить
    порог»: держать его в одном месте обязательно, иначе «порог включён» в одном
    месте и «порог не применяется» в другом выглядели бы противоречием.
    """
    data = stages if isinstance(stages, dict) else {}
    return bool(data.get("filter")) and float(data.get("min_score") or 0.0) > 0


def ce_threshold_requested(stages: Any) -> bool:
    """Задан ли порог УВЕРЕННОСТИ МОДЕЛИ (фильтрация + реранкинг + порог > 0).

    Порог второго этапа без реранкинга не к чему применять: пула нет и
    вероятностей нет. Это не «скрытая связка», а смысл настройки: она относится к
    реранкингу, и диагностика говорит об этом прямо.
    """
    data = stages if isinstance(stages, dict) else {}
    return (bool(data.get("filter")) and bool(data.get("rerank"))
            and float(data.get("min_ce") or 0.0) > 0)


def cut_kind(data: Any) -> str:
    """ЧЕМ отсекли всё найденное: "score" | "ce" | "" (ничем — «в документах нет»).

    Различать обязательно: у порога первичной релевантности и у порога уверенности
    модели РАЗНЫЕ шкалы и разные ползунки, и совет «снизить порог» без указания,
    какой именно, отправлял бы человека не туда.
    """
    clean = normalize(data)
    if clean.get("hits"):
        return ""
    stages = clean.get("stages") or {}
    if not stages.get("filter"):
        return ""
    # ОТСЕЧЁННОЕ ОБЯЗАНО БЫТЬ ВЫШЕ БАЗОВОГО ОТСЕВА ШУМА: иначе порог ни при чём —
    # фрагменты и без него были мусором, и честный ответ «в документах ничего
    # подходящего нет» (живой замер: нерелевантный запрос давал лучший 0,05 при
    # отсеве шума 0,10, и говорить про «слишком высокий порог» было бы выдумкой).
    floor = float(stages.get("floor") or 0.0)
    best = max([float(item.get("considered_score")
                      if item.get("considered_score") is not None
                      else item.get("considered_best") or 0.0)
                for item in clean.get("bases") or []] or [0.0])
    if best <= floor:
        return ""
    if stages.get("ce_applied") and float(stages.get("min_ce") or 0.0) > 0:
        return "ce"
    if stages.get("score_applied") and float(stages.get("min_score") or 0.0) > 0:
        return "score"
    return ""


def _cut_by_threshold(data: Dict[str, Any]) -> bool:
    """Все ли найденные фрагменты отсечены ПОРОГОМ (а не «в документах нет»).

    Признак: фрагментов у модели нет, но какая-то база их НАШЛА, и порог при этом
    включён. Такой случай обязан звучать иначе — «в документах есть близкое, но
    оно ниже порога», — иначе пользователь получает ложное «в документах этого
    нет» (живой случай: порог 1,75 против статьи, которая в базе есть).
    """
    if data.get("hits"):
        return False
    stages = data.get("stages") or {}
    if not stages.get("filter"):
        return False
    if cut_kind(data):
        return True
    # Порог не сработал, но и отсева шума могло не хватить: смотрим, была ли
    # лучшая оценка ВЫШЕ базового отсева — иначе «порог виноват» было бы выдумкой.
    floor = float(stages.get("floor") or 0.0)
    best = max([float(item.get("considered_best") or 0.0)
                for item in data.get("bases") or []] or [0.0])
    best_score = max([float(item.get("considered_score") or 0.0)
                      for item in data.get("bases") or []] or [0.0])
    return max(best, best_score) > floor


def _base_outcome(item: Dict[str, Any]) -> str:
    """Чем закончился поиск по одной базе — коротко и без догадок."""
    if item.get("error"):
        return "ошибка: " + str(item["error"])
    if item.get("hits"):
        return "фрагментов: %d" % int(item["hits"])
    if item.get("found"):
        # «Все ниже порога» — это про ПОРОГ, а не про «документов нет»: столько
        # фрагментов было ВЫШЕ базового отсева шума, и их убрал порог (первичной
        # релевантности — до второго этапа, уверенности модели — после него).
        best = float(item.get("considered_score")
                     if item.get("considered_score") is not None
                     else item.get("considered_best") or 0.0)
        return ("кандидатов %d, выше отсева шума %d — все ниже порога (лучший %.2f)"
                % (int(item.get("raw") or item.get("pool") or 0),
                   int(item["found"]), best))
    return "подходящих фрагментов нет"


def _address(hit: Dict[str, Any]) -> str:
    """Адрес фрагмента: файл · раздел · номер чанка · база · релевантность.

    Номер чанка — тот же, что виден в просмотре чанков базы («№ 1081»): по нему
    фрагмент из карточки источников находится глазами, а модель называет место
    точно («чанк № 1081»), а не «где-то в документе».
    """
    place = hit.get("section") or hit.get("title") or ""
    number = _int(hit.get("number"))
    tail = ("релевантность %.2f" % float(hit.get("score") or 0.0))
    if hit.get("neighbour"):
        # У соседа оценки нет: он не проходил отбор, а лишь продолжает найденное.
        # СОСЕДНИЙ, а не «продолжение»: сосед берётся и до, и после найденного
        # чанка (№ 873 стоит ПЕРЕД № 874), и называть предыдущий кусок
        # продолжением — неточность, которую видно прямо в карточке.
        tail = "соседний фрагмент № %d" % _int(hit.get("parent_chunk"))
    return "%s%s%s · база «%s» · %s" % (
        hit.get("source") or "документ",
        (" · " + place) if place else "",
        (" · чанк № %d" % number) if number else "",
        hit.get("base") or "База знаний",
        tail)


def _clip(text: Any, limit: int) -> str:
    """Текст фрагмента в пределах лимита (обрезанное помечаем)."""
    body = str(text or "").strip()
    if len(body) <= limit:
        return body
    return body[:max(0, limit - 1)].rstrip() + "…"


# ---------------------------------------------------------------------------
# Что видит пользователь
# ---------------------------------------------------------------------------
def results_note(raw: Any) -> str:
    """Строка диагностики в чате: что именно нашлось и куда это ушло.

    Кроме находок строка называет РАБОТУ ДВУХ ЭТАПОВ: сколько кандидатов взял
    первый, сколько осталось после реранкинга и порога, по какому запросу шёл
    поиск (переформулировка запроса — отдельная строка дебага, см. rag_query) и
    что именно включено у проекта. Без этого пользователь видит «нашлось 4» и не
    понимает, почему не 20 и не 12.
    """
    data = normalize(raw)
    if not data:
        return ""
    hits = data["hits"]
    failed = [item for item in data["bases"] if item.get("error")]
    # Соседние фрагменты — не находки: они дополняют найденное, и в счёте
    # «нашлось столько-то» их быть не должно (иначе отчёт путал бы человека).
    found_hits = [hit for hit in hits if not hit.get("neighbour")]
    neighbours = len(hits) - len(found_hits)
    body = ("нашлось фрагментов: %d (%s)"
            % (len(found_hits), "; ".join(_hit_line(hit) for hit in found_hits[:4]))
            if found_hits else "подходящих фрагментов не нашлось")
    stages = _stages_line(data.get("stages"))
    if stages:
        # Точку снимаем: её ставит конец предложения ниже, иначе в чате
        # появлялось «отобранных..» (строка этапов заканчивается точкой).
        body += ". " + stages.rstrip(".")
    if neighbours:
        body += (". Добавлено соседних фрагментов: %d (продолжение таблиц и "
                 "списков, разрезанных границей чанка)" % neighbours)
    if failed:
        body += ". Не опрошены: " + "; ".join(
            "%s (%s)" % (item["name"], item["error"][:120]) for item in failed)
    if not found_hits:
        if _cut_by_threshold(data):
            # Это НЕ «в документах нет»: поиск нашёл, а отсеял порог. Молчать об
            # этом нельзя — пользователь получит ложное «в документах этого нет»
            # (живой случай: порог 1,75 против статьи, которая в базе есть).
            return ("RAG: поиск по базам знаний — %s. ПОРОГ ОТСЁК ВСЁ НАЙДЕННОЕ: "
                    "в документах есть близкие фрагменты, и в модель уходит указание "
                    "сказать именно это. Если ответ должен быть в документах — снизьте "
                    "порог в панели «Поиск и ответы»." % body)
        tail = ""
        alternatives = data.get("alternatives") or []
        if alternatives:
            tail = (" Вместе с честным «в документах этого нет» модель предложит, чем "
                    "продолжить: %s." % "; ".join(str(item)[:80] for item in alternatives[:4]))
        return ("RAG: поиск по базам знаний — %s. В модель уходит честное «в "
                "документах этого нет» и предложение альтернатив: выдумывать "
                "содержимое базы нельзя, но и объявлять, что документов нет, — тоже.%s"
                % (body, tail))
    return ("RAG: поиск по базам знаний — %s. Фрагменты уходят в модель отдельным "
            "системным блоком: ответ, план и проверка строятся по ним, а "
            "выдумывать источники вместо них нельзя." % body)


def _hit_line(hit: Dict[str, Any]) -> str:
    """Фрагмент одной строкой для диагностики: адрес, оценка поиска и уверенность.

    «Оценка поиска» — это СУММА (косинус + доля слов + уверенность модели), и
    называть её «релевантностью» нельзя: у хорошего фрагмента она доходит до 2,49
    (замер: №887 — 0,50 + 1,00 + 0,997), и человек справедливо не понимает, как
    релевантность может быть больше единицы. Уверенность модели (0…1) — то, что
    читается сразу, поэтому она названа отдельно.
    """
    base = ("%s · %s · №%d"
            % (hit.get("source") or "документ",
               (hit.get("section") or "без раздела")[:80],
               _int(hit.get("number"))))
    # РЕЛЕВАНТНОСТЬ ПЕРВИЧНОГО ПОИСКА показываем ВСЕГДА (это то, с чем фрагмент
    # пришёл из первого этапа), а оценку модели — когда реранкинг её дал.
    relevance = float(hit.get("base_score")
                      if hit.get("base_score") is not None
                      else (hit.get("score") or 0.0))
    line = base + " · релевантность %.2f" % relevance
    ce = float(hit.get("ce") or 0.0)
    if ce > 0:
        line += ", оценка модели %.2f" % ce
    return line


def _stages_line(stages: Any) -> str:
    """Одна строка про два этапа поиска: чем искали и что отсеялось.

    Пусто — данных о этапах нет (запись прежнего поиска): молчать честнее, чем
    подставлять настройки окружения, которые к тому поиску отношения не имеют.
    """
    data = stages if isinstance(stages, dict) else {}
    if not data:
        return ""
    parts: List[str] = [
        "переформулировка запроса "
        + ("включена" if data.get("rewrite") else "выключена")]
    if data.get("rerank"):
        backend = str(data.get("rerank_backend") or "")
        how = "cross-encoder" if backend == "cross-encoder" else "признаки"
        model = str(data.get("rerank_model") or "")
        tail = (" (%s)" % model) if (how == "cross-encoder" and model) else ""
        reason = str(data.get("rerank_reason") or "")
        parts.append("реранкинг %s%s: с базы берётся пул %d кандидатов, в ответ идут %d"
                     % (how, tail, int(data.get("top_k_before") or 0),
                        int(data.get("top_k_after") or 0)))
        if reason:
            parts.append("реранкер: " + reason)
    else:
        # Реранкинг выключен — пула нет: с базы сразу берутся лучшие по вектору и
        # словам (иначе строка обещала бы «20 кандидатов», которых никто не
        # переставляет, и это путало: живое замечание 02.10).
        parts.append("реранкинг выключен: в ответ идут %d лучших по вектору и словам"
                     % int(data.get("top_k_after") or 0))
    # ДВА ПОРОГА, ДВЕ ШКАЛЫ — в строке диагностики они тоже названы раздельно:
    # человек, выставивший «0,85», обязан видеть, о каком именно пороге речь.
    if not data.get("filter"):
        # Галочка снята — это НЕ «порога нет»: базовый отсев шума остаётся (он был
        # и в прежней реализации), и строка говорит об этом прямо.
        parts.append("порог проекта не применяется, работает базовый отсев шума "
                     "%.2f: отсеяно %d из %d"
                     % (float(data.get("floor") or 0.0),
                        (_int(data.get("dropped")) + _int(data.get("score_dropped"))
                         + _int(data.get("floor_dropped"))),
                        _int(data.get("candidates")) + _int(data.get("floor_dropped"))))
        return "Два этапа поиска: " + "; ".join(parts) + "."
    min_score = float(data.get("min_score") or 0.0)
    if data.get("score_applied") and min_score > 0:
        # ПОРОГ ПЕРВИЧНОЙ РЕЛЕВАНТНОСТИ: работает без модели и до реранкинга.
        parts.append("порог первичной релевантности %.2f отсеял %d из %d кандидатов"
                     % (min_score, _int(data.get("score_dropped")),
                        _int(data.get("candidates")) + _int(data.get("score_dropped"))))
    elif min_score > 0:
        parts.append("порог первичной релевантности %.2f ничего не отсеял "
                     "(все кандидаты выше)" % min_score)
    else:
        parts.append("порога первичной релевантности нет (0) — шум убирает базовый "
                     "отсев %.2f" % float(data.get("floor") or 0.0))
    # ПОРОГ ВТОРОГО ЭТАПА: он относится к реранкингу, и без реранкинга не
    # применяется — об этом говорится словами, а не молчанием.
    min_ce = float(data.get("min_ce") or 0.0)
    if min_ce <= 0:
        pass
    elif not data.get("rerank"):
        parts.append("порог уверенности модели %.2f не применяется: реранкинг "
                     "выключен (шкала у него своя — это настройка второго этапа)"
                     % min_ce)
    elif data.get("ce_applied"):
        parts.append("порог уверенности модели %.2f отсеял %d из %d отобранных"
                     % (min_ce, _int(data.get("dropped")),
                        _int(data.get("considered"))))
    else:
        # Реранкинг включён, порог задан, а вероятностей нет (пул считали
        # признаки). Молчать нельзя: порог выглядит включённым.
        parts.append("⚠ порог уверенности %.2f НЕ ПРИМЕНЁН (%s): вероятностей "
                     "модели нет, релевантность фрагментов оценивает сама модель "
                     "ответа" % (min_ce, str(data.get("ce_skipped")
                                             or "модель-реранкер недоступна")[:150]))
    return "Два этапа поиска: " + "; ".join(parts) + "."


def sources(raw: Any) -> List[Dict[str, Any]]:
    """Источники для карточек в интерфейсе (что именно подобрано по запросу).

    Это не «список использованных источников»: подобраны они все, а какие
    попали в ответ — решает модель и видно по тексту. Подпись карточки говорит
    именно это, чтобы интерфейс не приписывал модели лишнего.
    """
    data = normalize(raw)
    stages = data.get("stages") or {}
    by_model = str(stages.get("rerank_backend") or "") == "cross-encoder"
    out: List[Dict[str, Any]] = []
    for hit in data.get("hits") or []:
        body = " ".join(str(hit.get("text") or "").split())
        out.append({
            # ИДЕНТИФИКАТОР БАЗЫ нужен интерфейсу, чтобы открыть ИМЕННО этот
            # фрагмент в просмотре чанков: по имени файла и номеру это сделать
            # нельзя — номер чанка уникален внутри своей базы.
            "base_id": hit.get("base_id") or "",
            "chunk_id": hit.get("chunk_id") or "",
            "base": hit.get("base") or "",
            "source": hit.get("source") or "документ",
            "section": hit.get("section") or hit.get("title") or "",
            # Номер чанка — как в просмотре чанков: по нему видно, ЧТО именно
            # подобрано, и этот же фрагмент можно открыть в базе.
            "number": _int(hit.get("number")),
            "neighbour": bool(hit.get("neighbour")),
            "parent_chunk": _int(hit.get("parent_chunk")),
            # Оценён ли фрагмент МОДЕЛЬЮ: если да, интерфейс показывает только её
            # уверенность (0…1), а служебную сумму не показывает вовсе.
            "by_model": by_model,
            "score": round(float(hit.get("score") or 0.0), 3),
            # Коэффициент релевантности ПЕРВИЧНОГО поиска (косинус + слова) —
            # показывается под ответом вместе с оценкой модели.
            "base_score": round(float(hit.get("base_score")
                                      if hit.get("base_score") is not None
                                      else (hit.get("score") or 0.0)), 3),
            "vector_score": round(float(hit.get("vector_score") or 0.0), 3),
            "lexical": round(float(hit.get("lexical") or 0.0), 3),
            # Слагаемые второго этапа — в подсказке карточки: по ним видно, что
            # дал реранкинг (фраза и адрес) и что снял штраф короткому чанку.
            "phrase": round(float(hit.get("phrase") or 0.0), 3),
            "address": round(float(hit.get("address") or 0.0), 3),
            "penalty": round(float(hit.get("penalty") or 0.0), 3),
            "ce": round(float(hit.get("ce") or 0.0), 3),
            "chars": _int(hit.get("chars")),
            # ЦИТАТА: сам фрагмент (начало) — то, из чего человек проверяет ответ.
            # В карточке он показывается раскрывающимся куском, в подсказке — целиком.
            "snippet": body[:SNIPPET_CHARS],
            # Сколько символов во фрагменте всего: по этому интерфейс понимает,
            # обрезана цитата или показана целиком.
            "full_chars": len(body),
        })
    return out


def address_of(hit: Dict[str, Any]) -> str:
    """Адрес одного фрагмента (файл · раздел · номер чанка · база).

    Нужен тем, кто показывает найденное одной строкой: диагностика в чате и
    тестовый прогон вопросов (`/test_rag`) пишут, какой фрагмент оказался лучшим.
    """
    return _address(hit)


def settings(raw: Any = None) -> Dict[str, Any]:
    """Действующие настройки поиска (для снимка RAG в интерфейсе).

    Снимок подписывает ими строку «поиск включён» и заполняет панель «Поиск и
    ответы»: пользователь видит, что базы не просто лежат списком, а идут в
    ответы — с каким бюджетом фрагментов, каким порогом и какими этапами.
    `raw` — настройка ПРОЕКТА (task["rag"]): незаданное берётся из окружения
    (`search_settings`), поэтому снимок всегда показывает то, чем поиск работает
    на самом деле, а не то, что записано в файле.
    """
    options = search_settings(raw)
    return {
        "top_k": options["top_k_after"],
        "top_k_after": options["top_k_after"],
        "top_k_before": options["top_k_before"],
        "max_hits": max_hits(),
        "rewrite": options["rewrite"],
        "rerank": options["rerank"],
        "filter": options["filter"],
        "block_chars": block_chars(),
        "chunk_chars": chunk_chars(),
        "neighbours": neighbours_span(),
        # Веса второго этапа — для подписи в интерфейсе: видно, из чего состоит
        # оценка («вектор + текст + фраза + адрес − штраф»).
        "noise_floor": noise_floor(),
        # ДВА ПОРОГА И ДВЕ ШКАЛЫ: первичная релевантность (фильтрация, 0…2) и
        # уверенность модели (второй этап, 0…1). Панель показывает оба, и поиск
        # ими пользуется — один словарь, чтобы не разошлись.
        "min_score": options["min_score"],
        "min_score_limit": MIN_SCORE_LIMIT,
        "min_ce": options["min_ce"],
        "ask_when_empty": options["ask_when_empty"],
        "rerank_backend": options["rerank_backend"],
        "rerank_backend_name": rag_rerank.backend_name(options["rerank_backend"]),
        "phrase_weight": rag_rerank.phrase_weight(),
        "address_weight": rag_rerank.address_weight(),
        "short_penalty": rag_rerank.short_penalty(),
        "ce_weight": rag_rerank.ce_weight(),
    }


def limits() -> Dict[str, Any]:
    """Границы панели настроек поиска (интерфейс не выдумывает их сам).

    Пределы те же, что проверяет `search_settings`: топ-K от 1 до MAX_TOP_K,
    порог от 0 до MIN_SCORE_LIMIT. Порог именно от нуля: отрицательный означал бы
    «брать и заведомо нерелевантное», а ноль — законное «не отсекать ничего»
    (галочка «Фильтрация по порогу» для этого и есть).
    """
    return {
        "top_k": {"min": 1, "max": MAX_TOP_K},
        # ДВЕ ШКАЛЫ, и это НЕ одно и то же: первичная релевантность (косинус +
        # слова запроса, 0…2) — её человек видит в карточке источника; уверенность
        # модели (вероятность cross-encoder, 0…1) — оценка второго этапа.
        "min_score": {"min": 0.0, "max": MIN_SCORE_LIMIT, "step": 0.05},
        "min_ce": {"min": 0.0, "max": 1.0, "step": 0.05},
        "max_hits": {"min": 1, "max": MAX_HITS},
    }
