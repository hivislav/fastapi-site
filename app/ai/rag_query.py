"""Переформулировка запроса перед поиском по базам знаний (Query Rewrite).

ЧТО ЭТО И ЗАЧЕМ. Вопрос пользователя и поисковый запрос — НЕ одно и то же. В
вопросе есть обращение, вежливость, служебные слова и разговорная рамка («скажи,
пожалуйста, а как у нас вообще дела с резервным копированием базы?»), а поиск
сравнивает текст с чанками документов: лишние слова размывают и вектор, и
лексическую часть оценки (доля найденных слов запроса считается по ВСЕМ словам,
включая служебные). Переформулировка превращает вопрос в набор ключевых слов и
терминов, которые в документах действительно есть.

ДВА ПУТИ, И ОБА ЧЕСТНЫЕ:

  * МОДЕЛЬ (`rewrite`) — служебный вызов LLM: она умеет добавить синонимы и
    развернуть сокращения, которых в документах может не быть («ТБ» → «техника
    безопасности»). Это стоит токенов, поэтому у проекта есть выключатель.
  * ЛОКАЛЬНО (`local_rewrite`) — без сети и без модели: выкидываются служебные
    слова и разговорная рамка, остаются значимые. Работает всегда: и когда ключа
    нет, и когда вызов не удался, и в проверках без сети.

ПОЧЕМУ РЕЗУЛЬТАТ МОДЕЛИ ПРОВЕРЯЕТСЯ (`accept`). Переформулировка — это ДАННЫЕ,
которые уходят в поиск вместо вопроса пользователя: если модель ответила не тем
(«не могу помочь», объяснением вместо запроса, простыней текста или запросом про
другое), поиск найдёт что угодно, и пользователь получит ответ не на свой вопрос.
Поэтому результат обязан быть коротким, однострочным и сохранять ХОТЯ БЫ ОДНО
значимое слово исходного вопроса. Не прошёл — берём локальный вариант, а если и
он ничего не изменил, ищем по исходному запросу: молча подменять запрос нельзя.

ЧЕГО ЗДЕСЬ НЕТ: обращений к базам знаний и к индексу. Модуль только превращает
одну строку в другую; ищет `rag_search`, а вызов модели делает вызывающий
(веб-слой — через служебный вызов агента, см. `Agent.rewrite_query`).
"""

import json
import logging
import re
from typing import Any, Callable, Dict, List

from app.ai import rag_store

logger = logging.getLogger(__name__)

# Служебный вызов: короткий запрос на выходе, значит и токенов немного.
REWRITE_MAX_TOKENS = 120
REWRITE_TIMEOUT = 20.0

# Предел поискового запроса — тот же, что у самого поиска (rag_search.QUERY_CHARS):
# длиннее он всё равно обрежется, и обещать иное нельзя.
MAX_QUERY_CHARS = 300
# Сколько значимых слов обязано остаться. Одно — минимум: «Исида Бес» это уже
# запрос, а пустая строка означала бы поиск «по ничему».
MIN_SIGNIFICANT = 1
# Слово короче этого значимым не считается (предлоги, союзы, «я», «он»).
MIN_WORD = 3

_WORD_RE = re.compile(r"[0-9a-zа-яё]+", re.IGNORECASE)
# Разговорная рамка вопроса: обращение к собеседнику, а не содержание запроса.
_FRAME_WORDS = {
    "скажи", "скажите", "подскажи", "подскажите", "расскажи", "расскажите",
    "найди", "найдите", "поищи", "поищите", "поискать", "ищи", "ищите",
    "покажи", "покажите", "дай", "дайте", "ответь", "ответьте", "объясни",
    "объясните", "напомни", "напомните", "уточни", "уточните", "перечисли",
    "перечислите", "пожалуйста", "плиз", "будь", "будьте", "добрый", "привет",
    "можно", "нужно", "надо", "хочу", "хотел", "хотела", "можешь", "можете",
    "интересно", "кажется", "вообще", "просто", "давай", "давайте",
}
# Служебные слова. «не» и «без» здесь НАМЕРЕННО отсутствуют: выброшенное
# отрицание переворачивает смысл запроса («не работает» → «работает»).
_STOP_WORDS = {
    "а", "бы", "был", "была", "были", "было", "быть", "в", "вам", "вас", "весь",
    "вся", "всё", "все", "вы", "где", "да", "для", "до", "его", "ее", "её", "ей",
    "ему", "если", "есть", "ещё", "еще", "же", "за", "зачем", "здесь", "и", "из",
    "их", "к", "как", "какая", "какие", "каков", "какой", "ко", "когда", "кто",
    "ли", "мне", "мы", "на", "над", "нам", "нас", "неё", "нее", "него", "них",
    "но", "ну", "о", "об", "он", "она", "они", "оно", "от", "по", "под", "при",
    "про", "с", "сам", "сама", "сами", "самый", "со", "так", "такая", "такие",
    "такой", "там", "те", "тем", "то", "тогда", "того", "той", "только", "том",
    "тот", "тут", "ты", "у", "уже", "хоть", "чего", "чей", "чем", "через", "что",
    "чтобы", "чья", "эта", "эти", "это", "этот", "эту", "я",
}
# Признаки «модель ответила не запросом»: объяснение, отказ, служебная строка.
_META_MARKERS = (
    "не могу", "не удалось", "извин", "как ии", "как языковая модель",
    "as an ai", "i cannot", "sorry", "запрос пользователя", "нет запроса",
    "невозможно", "не знаю",
)

# Промпт служебного вызова. Требования те же, что проверяет `accept`: одна
# строка, только ключевые слова, ничего не выдумывать.
REWRITE_PROMPT = (
    "Ты готовишь ПОИСКОВЫЙ ЗАПРОС по документам пользователя. Вопрос пользователя "
    "нужно превратить в строку для поиска по базе знаний.\n"
    "ПРАВИЛА:\n"
    "1. Оставь ТОЛЬКО ключевые слова и термины: предмет вопроса, имена, названия, "
    "числа. Убери вежливость, обращения и разговорную рамку.\n"
    "2. ИСПРАВЬ ОПЕЧАТКИ и искажённые слова — это НЕ выдумывание, а часть работы: "
    "«ьестия» → «Бестия», «сильверхвыф» → «Сильверхэнд», «кто токой» → «кто такой». "
    "Опирайся на смысл вопроса и на то, как слово должно писаться; если слово уже "
    "написано верно — не трогай его.\n"
    "3. Добавь синонимы и расшифровки, если термин может называться в документах "
    "иначе (например «ТБ» → «техника безопасности»), но НЕ добавляй того, чего в "
    "вопросе нет по смыслу.\n"
    "4. Одна строка, до 200 символов, без пояснений и без кавычек.\n"
    "5. Ничего не выдумывай: если слово непонятно и исправить его нечем — оставь "
    "как есть.\n"
    'Ответ — только JSON: {"query": "поисковый запрос"}'
)

# Резервная (локальная) переформулировка выкидывает то же, что и модель, но без
# синонимов: только рамку вопроса и служебные слова.
LlmCall = Callable[..., Any]


def clean_query(text: Any) -> str:
    """Запрос к рабочему виду: пробелы схлопнуты, кавычки и хвостовая пунктуация сняты."""
    value = " ".join(str(text or "").split())
    value = value.strip("\"'«»“” \t")
    return value[:MAX_QUERY_CHARS].strip()


def words_of(text: Any) -> List[str]:
    """Слова текста (буквы и цифры), без служебных и слишком коротких."""
    out: List[str] = []
    for word in _WORD_RE.findall(str(text or "").lower()):
        if len(word) < MIN_WORD or word in _STOP_WORDS or word in _FRAME_WORDS:
            continue
        out.append(word)
    return out


def significant(text: Any) -> List[str]:
    """Значимые слова БЕЗ повторов и в исходном порядке (основа — 6 символов)."""
    stems: List[str] = []
    for word in words_of(text):
        stem = word[:6]
        if stem not in stems:
            stems.append(stem)
    return stems


def local_rewrite(text: Any) -> str:
    """Переформулировка БЕЗ модели: остаются значимые слова вопроса.

    Зачем она нужна, если есть модель: ключа может не быть, вызов может не
    удаться, а в проверках сети нет вовсе — и тогда поиск обязан работать как
    раньше (или лучше), а не падать и не искать «по пустой строке».
    """
    original = clean_query(text)
    words = words_of(original)
    if len(words) < MIN_SIGNIFICANT:
        return original
    return " ".join(words)[:MAX_QUERY_CHARS]


def rewrite_payload(text: Any) -> str:
    """Сообщение пользователя для служебного вызова (вопрос как есть)."""
    return "Вопрос пользователя: %s" % clean_query(text)


def parse_rewrite(content: Any) -> str:
    """Поисковый запрос из ответа модели: JSON, а если его нет — первая строка.

    Модель отвечает то JSON, то просто строкой (иногда в кавычках, иногда с
    пояснением перед ней), поэтому разбор терпимый: сначала JSON с полем
    «query»/«запрос», затем первая непустая строка.
    """
    raw = str(content or "").strip()
    if not raw:
        return ""
    value = raw
    start = value.find("{")
    if start >= 0:
        try:
            payload = json.loads(value[start:])
        except (ValueError, TypeError):
            payload = None
        if isinstance(payload, dict):
            for key in ("query", "запрос", "search_query", "keywords", "ключевые_слова"):
                if str(payload.get(key) or "").strip():
                    return clean_query(payload[key])
    for line in raw.splitlines():
        line = clean_query(line)
        if line:
            return line
    return ""


def accept(candidate: Any, original: Any) -> bool:
    """Годится ли переформулировка ВМЕСТО исходного запроса (см. правила в шапке).

    Проверка идёт по ДАННЫМ, а не по вере в модель: короткая однострочная строка,
    которая сохранила хотя бы одно значимое слово вопроса. Так «не могу помочь»,
    объяснение на три абзаца и запрос про совсем другое в поиск не уходят.
    """
    text = clean_query(candidate)
    if not text or len(text) > MAX_QUERY_CHARS or "\n" in str(candidate or ""):
        return False
    low = text.lower()
    if any(marker in low for marker in _META_MARKERS):
        return False
    source = significant(original)
    found = significant(text)
    if not source:
        # В самом вопросе значимых слов нет («а как же?») — сверять не с чем, но
        # и подменять такой вопрос осмысленно нечем: берём только непустое.
        return bool(found or text)
    # Совпадение основ — тем же правилом, что у поиска (rag_store.same_stem):
    # «копирование» и «копированием» это одно слово в разных формах.
    if any(rag_store.same_stem(word, other) for word in found for other in source):
        return True
    # ОПЕЧАТКА, А НЕ «ЗАПРОС ПРО ДРУГОЕ»: исправленное слово отличается от
    # исходного на один-два знака и той же длины. Живой случай: на вопрос «кто
    # такая ьестия» модель вернула «Бестия кто такая» — правильный ответ, а
    # проверка его отбрасывала (основы «ьести» и «бести» не совпадают), и поиск
    # уходил с опечаткой. Теперь такое исправление принимается.
    return any(_looks_like_fix(word, other) for word in found for other in source)


def _looks_like_fix(word: str, other: str) -> bool:
    """Похоже ли одно слово на ИСПРАВЛЕНИЕ другого (опечатка, а не другое слово).

    Условие простое и проверяемое: длины отличаются не больше чем на один знак, а
    различий в написании не больше двух (сравнение посимвольное, с учётом сдвига
    на один знак — опечатки бывают вставкой и пропуском буквы). Слова короче
    четырёх знаков не сравниваем: у них «похожесть» ничего не значит.
    """
    if min(len(word), len(other)) < 4 or abs(len(word) - len(other)) > 1:
        return False
    if word == other:
        return True
    if len(word) == len(other):
        return sum(1 for left, right in zip(word, other) if left != right) <= 2
    shorter, longer = (word, other) if len(word) < len(other) else (other, word)
    for shift in range(len(longer)):
        probe = longer[:shift] + longer[shift + 1:]
        if len(probe) != len(shorter):
            continue
        if sum(1 for left, right in zip(probe, shorter) if left != right) <= 1:
            return True
    return False


def debug_line(info: Any) -> str:
    """Строка дебага в чате: по какому запросу пошёл поиск и почему именно по нему.

    Начинается с «запрос после rewriting: » — по этой строке пользователь видит,
    что переформулировка ВООБЩЕ была (и какая), а не догадывается по ответу.
    """
    data = info if isinstance(info, dict) else {}
    query = clean_query(data.get("query"))
    if not query:
        return ""
    by = str(data.get("by") or "")
    if by == "model":
        return "запрос после rewriting: «%s» (переформулировала модель)" % query
    if by == "local":
        reason = str(data.get("reason") or "").strip()
        tail = "модель недоступна: %s" % reason if reason else "без модели"
        return "запрос после rewriting: «%s» (локально, %s)" % (query, tail)
    reason = str(data.get("reason") or "").strip()
    if reason:
        return ("переформулировка не удалась (%s) — ищу по исходному запросу: «%s»"
                % (reason, query))
    return ""


async def rewrite(text: Any, call: Callable[..., Any]) -> Dict[str, Any]:
    """Переформулирует запрос для поиска: модель, а при сбое — локальный разбор.

    Возвращает `{"query", "by", "reason"}`: `by` — чем получен запрос ("model" —
    ответ модели, "local" — локальный разбор, "" — переформулировки не было).
    Сбой вызова НЕ отменяет поиск: без модели работает локальный путь.
    """
    original = clean_query(text)
    if not original:
        return {}
    reason = ""
    try:
        content, _metrics = await call(
            user_text="",
            messages=[
                {"role": "system", "content": REWRITE_PROMPT},
                {"role": "user", "content": rewrite_payload(original)},
            ],
            response_format="free",
            max_tokens=REWRITE_MAX_TOKENS,
            stop=None,
            system_prompt=None,
            temperature=None,
            model=None,
            disable_thinking=True,
            timeout=REWRITE_TIMEOUT,
        )
        candidate = parse_rewrite(content)
        if candidate and accept(candidate, original):
            return {"query": candidate, "by": "model", "reason": ""}
        reason = ("ответ модели не годится для поиска"
                  if str(content or "").strip() else "модель не ответила")
    except Exception as exc:                # сбой вызова не ломает запрос
        reason = "вызов модели не удался: %s" % str(exc)[:120]
        logger.warning("RAG: переформулировка запроса моделью не удалась — %s",
                       str(exc)[:200])
    local = local_rewrite(original)
    if local and local != original and accept(local, original):
        return {"query": local, "by": "local", "reason": reason}
    return {"query": original, "by": "", "reason": reason}
