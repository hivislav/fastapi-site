# ---------------------------------------------------------------------------
# Внешние обязательства: что задача ЗАПУСТИЛА на стороне сервера
# ---------------------------------------------------------------------------
# Инструмент может не только прочитать данные, но и ЗАПУСТИТЬ что-то на сервере:
# сбор наблюдений, подписку, задание. Такое нельзя бросить — иначе на сервере
# останется висеть вечный сбор, о котором задача уже забыла (её отменили или
# удалили). Код НЕ знает имён инструментов: пара «запускающий ↔ отменяющий»
# определяется по ИМЕНИ (общий префикс start_/stop_) и проверяется по списку,
# который объявил сам сервер (`tools/list`). Аргументы отмены (id наблюдения)
# достаются из ТЕКСТА ответа запускающего инструмента — по именам обязательных
# полей схемы отменяющего.
START_PREFIX = "start_"
STOP_PREFIX = "stop_"
# Сколько обязательств помним на задачу (страховка от разрастания диалога).
MAX_STARTED = 20
# Ключи, по которым ищем значение в тексте ответа («id: "abc"», `"id": "abc"`,
# «id=abc», «id abc»). Регистр не важен, кавычки любые.
_VALUE_PATTERNS = (
    r'["\']?{key}["\']?\s*[:=]\s*["\']([^"\'\s,;)]+)["\']',
    r'["\']?{key}["\']?\s*[:=]\s*([^\s,;)]+)',
)


def undo_tool(tool: Any, tool_names: Any) -> str:
    """Имя ОТМЕНЯЮЩЕГО инструмента для запускающего ("" — пары нет).\n"

    Соглашение об именах + проверка по объявленному списку: `start_weather_watch`
    → `stop_weather_watch`. Если сервер такого инструмента не объявлял, отменять
    нечем — и выдумывать вызов нельзя.
    """
    name = str(tool or "").strip()
    if not name.startswith(START_PREFIX):
        return ""
    candidate = STOP_PREFIX + name[len(START_PREFIX):]
    names = {str(item).strip() for item in (tool_names or [])}
    return candidate if candidate in names else ""


def _schema_of(tools: List[Dict[str, Any]], server_id: str, tool: str) -> Dict[str, Any]:
    """Схема аргументов инструмента из объявленного сервером списка."""
    for item in (tools or []):
        if str(item.get("server") or "") != server_id:
            continue
        if str(item.get("tool") or "") != tool:
            continue
        schema = item.get("schema")
        return schema if isinstance(schema, dict) else {}
    return {}


def find_value(text: Any, key: str) -> str:
    """Значение поля `key` из текста ответа инструмента ("" — не нашлось).\n"

    Ответы инструментов — обычный текст (часто с JSON внутри), поэтому значение
    ищем по образцам «ключ: значение», «"ключ": "значение"», «ключ=значение».

    Поле-идентификатор у сервера может называться иначе, чем в схеме отменяющего
    инструмента: например, инструмент отмены требует `collection_id`, а ответ
    называет его просто `id`. Поэтому пробуем не только точное имя, но и его
    «хвосты» (последнее слово, `id`) — от точного к самому общему; первое
    найденное значение побеждает.
    """
    body = str(text or "")
    if not body or not str(key or "").strip():
        return ""
    for candidate in _key_candidates(key):
        for pattern in _VALUE_PATTERNS:
            match = re.search(pattern.format(key=re.escape(candidate)), body,
                              re.IGNORECASE)
            if match:
                value = match.group(1).strip().strip('"\'')
                if value:
                    return value[:200]
    return ""


def _key_candidates(key: Any) -> List[str]:
    """Имена, под которыми значение поля может стоять в тексте ответа.\n"

    «collection_id» → ["collection_id", "id", "collection"]: точное имя первым,
    дальше — «хвосты», которые сервер мог использовать вместо него.
    """
    name = str(key or "").strip()
    if not name:
        return []
    candidates = [name]
    parts = [part for part in re.split(r"[_\-\s]+", name) if part]
    if len(parts) > 1:
        # Последнее слово обычно и есть идентификатор («…_id»).
        if parts[-1].lower() != name.lower():
            candidates.append(parts[-1])
        if parts[0].lower() != name.lower():
            candidates.append(parts[0])
    if name.lower().endswith("id") and name.lower() != "id":
        candidates.append("id")
    out: List[str] = []
    for item in candidates:
        if len(item) >= 2 and item not in out:
            out.append(item)
    return out


def stop_arguments(result: Dict[str, Any], schema: Dict[str, Any]) -> Dict[str, Any]:
    """Аргументы отмены из ответа запускающего инструмента.\n"

    Берём ОБЯЗАТЕЛЬНЫЕ строковые поля схемы отменяющего инструмента (у
    наблюдения это «id») и ищем их значения в тексте ответа. Хотя бы одно
    обязательное поле не нашлось — отменять нечем: пустой словарь.
    """
    required = [str(key) for key in ((schema or {}).get("required") or [])]
    properties = (schema or {}).get("properties") or {}
    if not required:
        # Схема без обязательных полей: отменяющий инструмент самодостаточен
        # (например, «остановить всё») — вызываем его без аргументов.
        return {}
    found: Dict[str, Any] = {}
    for key in required:
        kind = (properties.get(key) or {}).get("type")
        if kind not in (None, "string"):
            return {}
        value = find_value(result.get("text"), key)
        if not value:
            return {}
        found[key] = value
    return found


def started_calls(results: Any, tools: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Что задача ЗАПУСТИЛА на серверах: список обязательств для отмены.\n"

    Смотрим результаты ВЫПОЛНЕННЫХ вызовов: если у вызванного инструмента есть
    отменяющая пара в объявленном списке и из ответа достаются её аргументы,
    обязательство запоминается — потом его отменит отмена/удаление задачи
    (см. cancel_started). Имена инструментов берутся из данных сервера.
    """
    out: List[Dict[str, Any]] = []
    for item in normalize_results(results):
        if not item.get("ok"):
            continue
        server_id = item.get("server") or ""
        tool = item.get("tool") or ""
        names = [entry.get("tool") for entry in (tools or [])
                 if str(entry.get("server") or "") == server_id]
        stop = undo_tool(tool, names)
        if not stop:
            continue
        schema = _schema_of(tools or [], server_id, stop)
        required = [str(key) for key in ((schema or {}).get("required") or [])]
        arguments = stop_arguments(item, schema)
        if required and not arguments:
            # Аргументы отмены (id наблюдения) в ответе не нашлись: запоминать
            # нечего — «отмена» вызвала бы инструмент без нужных аргументов и
            # сбор остался бы висеть, а пользователь думал бы, что он остановлен.
            logger.info(
                "MCP: %s/%s запустил внешний сбор, но аргументы отмены (%s) в "
                "ответе не найдены — задача о сборе не помнит",
                server_id, tool, ", ".join(required))
            continue
        entry = {
            "server": server_id,
            "server_name": item.get("server_name") or server_id,
            "tool": tool,
            "stop_tool": stop,
            "arguments": arguments,
        }
        if entry not in out:
            out.append(entry)
    return out[:MAX_STARTED]


def normalize_calls(raw: Any, limit: Optional[int] = None) -> List[Dict[str, Any]]:
    """Приводит список вызовов к безопасному виду: [{"server","tool","arguments"}].

    `limit` — сколько вызовов оставить. По умолчанию предел ЗАПРОСА
    (MAX_TOTAL_CALLS_PER_REQUEST), а НЕ одного раунда: этот нормализатор
    применяется к ХРАНИМЫМ вызовам задачи (диалог, повтор, чтение журнала), а в
    цепочке их до шести. Предел одного раунда живёт там, где вызовы ВЫБИРАЮТСЯ
    (parse_calls), и молчаливая обрезка здесь теряла бы последний вызов цепочки —
    например выгрузку файла, из-за чего повтор задачи оставался без свежего файла.
    """
    out: List[Dict[str, Any]] = []
    cap = MAX_TOTAL_CALLS_PER_REQUEST if limit is None else max(0, int(limit))
    for item in (raw if isinstance(raw, list) else []):
        if not isinstance(item, dict):
            continue
        server_id = str(item.get("server") or "").strip()[:80]
        tool = str(item.get("tool") or "").strip()[:120]
        if not server_id or not tool:
            continue
        arguments = item.get("arguments") if isinstance(item.get("arguments"), dict) else {}
        call: Dict[str, Any] = {
            "server": server_id, "tool": tool,
            "arguments": {str(key)[:60]: value
                          for key, value in list(arguments.items())[:10]},
        }
        # Признак «вызов что-то ЗАПУСКАЕТ на сервере» ставится при выборе (тогда
        # известен список инструментов) и хранится вместе с вызовом: повтору он
        # нужен, чтобы НЕ повторять запуск сбора и не ходить за списком сервера.
        if item.get("action") is True:
            call["action"] = True
        if call not in out:
            out.append(call)
        if len(out) >= cap:
            break
    return out


def is_action_tool(tool: Any, tools: List[Dict[str, Any]],
                   server_id: str = "") -> bool:
    """True — инструмент ЗАПУСКАЕТ/ОСТАНАВЛИВАЕТ работу на сервере, а не читает.\n"

    Действием считается вызов, у которого есть отменяющая пара в объявленном
    списке (см. undo_tool): регистрация наблюдения, подписка, задание. Такие
    вызовы имеют побочный эффект на сервере, поэтому к ним относимся строже:
    чтение данных безопасно, а брошенный сбор придётся останавливать.
    """
    names = [entry.get("tool") for entry in (tools or [])
             if not server_id or str(entry.get("server") or "") == server_id]
    return bool(undo_tool(tool, names))


def read_calls(calls: Any, tools: Optional[List[Dict[str, Any]]] = None
               ) -> List[Dict[str, Any]]:
    """Только ЧИТАЮЩИЕ вызовы (без запуска/остановки работы на сервере).

    Признак берётся из самого вызова (`action`, ставится при выборе). Список
    инструментов нужен только для старых записей без признака — тогда действие
    определяется по паре start_/stop_ в объявленном списке.
    """
    out: List[Dict[str, Any]] = []
    for call in normalize_calls(calls):
        if call.get("action") is True:
            continue
        if call.get("action") is None and tools is not None \
                and is_action_tool(call.get("tool"), tools,
                                   str(call.get("server") or "")):
            continue
        out.append(call)
    return out


def has_reads(calls: Any, tools: Optional[List[Dict[str, Any]]] = None) -> bool:
    """Есть ли среди вызовов хотя бы один читающий (иначе данных не будет)."""
    return bool(read_calls(calls, tools))


# Просьба о НАКОПЛЕННЫХ данных за промежуток. Нужна ТОЛЬКО как предохранитель
# (см. looks_aggregate): по ней решается, можно ли переспрашивать диспетчера,
# когда он ответил одними запусками сбора. Инструменты по этим словам НЕ
# выбираются — выбор всегда за моделью.
AGGREGATE_MARKERS = (
    "сводк", "итог", "суммарн", "за сутки", "за день", "за недел", "за месяц",
    "за период", "за последн", "за прошл", "минимум", "максимум", "средн",
    "динамик", "тренд", "истори", "накопл", "как менял", "статистик", "за сутки",
)


def looks_aggregate(text: Any) -> bool:
    """Похож ли запрос на просьбу о СВОДКЕ за прошедший промежуток.

    Предохранитель: запрос «сводка за сутки» требует НАКОПЛЕННЫХ данных, поэтому
    вызовы, которые только запускают сбор, для него — правильный ответ, и
    переспрашивать диспетчера не нужно (см. _preflight_mcp). Запрос «проверяй
    погоду раз в минуту» — наоборот, про текущее значение: если диспетчер ответил
    одним запуском сбора, ответ нужно уточнить.
    """
    body = " ".join(str(text or "").lower().split())
    return any(marker in body for marker in AGGREGATE_MARKERS)


# ---------------------------------------------------------------------------
# ЦЕПОЧКА: признаки, дайджест результатов, защита вызовов
# ---------------------------------------------------------------------------
# Пара «ключ: значение» в тексте результата: так из ответа инструмента
# достаются идентификаторы (dataset_id, watch_id, id), которые нужны следующему
# вызову. Значения берём только из САМИХ результатов — ничего не досчитываем.
_ID_PAIR_RE = re.compile(
    r"[\"']?([A-Za-z_][A-Za-z0-9_]{0,40})[\"']?\s*[:=]\s*[\"']?([A-Za-z0-9][A-Za-z0-9._:-]{1,63})[\"']?"
)


def looks_like_chain(text: Any) -> bool:
    """Просит ли запрос СДЕЛАТЬ С ДАННЫМИ что-то ещё (сохранить, выгрузить).

    Дешёвый признак (только текст запроса, без вызовов LLM): «сохрани», «отдай в
    виде эксель таблицы», «затем», «выгрузи файл». Сам по себе он ничего не
    решает — вместе со структурным признаком (см. chain_signals) он означает
    «здесь возможна зависимость по данным».
    """
    body = " ".join(str(text or "").lower().split())
    return any(marker in body for marker in CHAIN_MARKERS)


def result_kind(tool: Any) -> str:
    """ВИД РЕЗУЛЬТАТА, который создаёт инструмент: «save», «export» или пусто.

    Пусто — инструмент ничего не создаёт (чтение, поиск, удаление). Вид нужен,
    чтобы сверять ПРОСЬБУ с ФАКТОМ, а не имена инструментов между собой: просьба
    «запиши» закрывается любым создающим вызовом любого сервера, и наоборот —
    невызванный создающий инструмент ЧУЖОГО сервера не делает просьбу
    невыполненной. Так кросс-серверные цепочки остаются возможными, а чужие
    инструменты не подмешиваются в уточнения.
    """
    name = str(tool or "").strip()
    if not name:
        return ""
    if SAVE_NAME_RE.match(name):
        return "save"
    if EXPORT_NAME_RE.match(name):
        return "export"
    if RESULT_RE.match(name) and FILE_NAME_RE.search(name):
        return "export"
    return ""


def requested_kinds(text: Any) -> List[str]:
    """Какие ВИДЫ результата просит запрос: «save», «export» (в этом порядке).

    Дешёвый признак по тексту запроса, без вызовов LLM. Пустой список — запрос не
    просит ничего создавать (тогда и уточнять нечего). Это то, что отличает
    «запиши данные о пользователе» от «сохрани прогноз и отдай файлом Excel»:
    в первом случае вид ровно один, и закрывает его один вызов.
    """
    body = " ".join(str(text or "").lower().split())
    kinds: List[str] = []
    if any(marker in body for marker in SAVE_MARKERS):
        kinds.append("save")
    if any(marker in body for marker in EXPORT_MARKERS):
        kinds.append("export")
    return kinds


def satisfied_kinds(calls: Any) -> List[str]:
    """Виды результата, которые УЖЕ созданы выполненными вызовами (любых серверов)."""
    kinds: List[str] = []
    for call in (calls or []):
        if not isinstance(call, dict):
            continue
        kind = result_kind(call.get("tool"))
        if kind and kind not in kinds:
            kinds.append(kind)
    return kinds


def unsatisfied_kinds(text: Any, calls: Any) -> List[str]:
    """Виды, которые запрос просит, но выполненные вызовы ещё не создали.

    Именно этот список (а не «все невызванные создающие инструменты набора»)
    решает, о чём уточнять диспетчера: просьба уже закрыта — уточнять не о чем.
    """
    done = satisfied_kinds(calls)
    return [kind for kind in requested_kinds(text) if kind not in done]


def id_required_tools(tools: Optional[List[Dict[str, Any]]]) -> List[Dict[str, Any]]:
    """Инструменты, у которых ЕСТЬ обязательный аргумент-идентификатор.

    Такой аргумент нельзя вывести из запроса: его значение возвращает другой
    инструмент (`dataset_id` приходит из сохранения, `id` наблюдения — из
    запуска сбора). Список строится из схем, объявленных СЕРВЕРОМ, поэтому
    признак не привязан ни к погоде, ни к конкретному серверу.
    """
    out: List[Dict[str, Any]] = []
    for item in (tools or []):
        if not isinstance(item, dict):
            continue
        schema = item.get("schema") if isinstance(item.get("schema"), dict) else {}
        required = [str(key) for key in (schema.get("required") or [])]
        ids = [key for key in required if ID_ARG_RE.search(key)]
        if ids:
            out.append({
                "server": str(item.get("server") or ""),
                "tool": str(item.get("tool") or ""),
                "args": ids,
            })
    return out


def chain_signals(tools: Optional[List[Dict[str, Any]]], text: Any,
                  expected: int = 0) -> Dict[str, Any]:
    """Признаки того, что запрос требует ЦЕПОЧКИ вызовов (а не одного раунда).

    Гибридная схема: разовые запросы идут дешёвым путём (один раунд), а в цикл
    уходят только задачи, где следующий вызов зависит от результата предыдущего.
    Признаки делятся на дешёвые (текст + схемы инструментов, без вызовов LLM) и
    модельный (диспетчер сам объявляет режим — см. parse_decision).

    - `markers`   — в запросе просят сохранить/выгрузить/оформить файл или задан
                    порядок шагов («затем», «после этого»);
    - `id_tools`  — среди объявленных инструментов есть те, чей ОБЯЗАТЕЛЬНЫЙ
                    аргумент — идентификатор (его значение даёт другой вызов);
    - `expected`  — сколько вызовов выбрал диспетчер (веер по нескольким
                    объектам ≠ цепочка, но повышает шанс, что дальше будет шаг).
    """
    markers = looks_like_chain(text)
    id_tools = id_required_tools(tools)
    kinds = requested_kinds(text)
    # ПОПРАВКА НА ВИД: инструмент с обязательным id считается доводом за цепочку
    # только если он создаёт ТОТ вид результата, который просит запрос. Иначе
    # доводом становились наблюдения погоды на запрос «запиши данные в реестр»:
    # маркер «запиши» находился, а id-инструменты брались из всего набора, включая
    # чужие серверы. Виды нет у запроса (просят только «затем», «сравни») —
    # оставляем прежнее поведение и смотрим на весь набор.
    if kinds:
        id_tools_relevant = [item for item in id_tools
                             if result_kind(item.get("tool")) in kinds]
    else:
        id_tools_relevant = list(id_tools)
    return {
        "markers": markers,
        "kinds": kinds,
        "id_tools": id_tools,
        "id_tools_relevant": id_tools_relevant,
        "expected": int(expected or 0),
        # Цепочка оправдана, когда просят «сделать с данными ещё что-то» И в
        # наборе есть подходящий по виду инструмент, которому для этого нужен id
        # из результата.
        "needed": bool(markers and id_tools_relevant),
    }


def unused_tools(tools: Optional[List[Dict[str, Any]]],
                 calls: Any) -> List[Dict[str, Any]]:
    """Объявленные инструменты, которые в этом запросе ЕЩЁ НЕ вызывались.

    Сравнение — по имени инструмента и серверу (аргументы здесь не важны: вопрос
    в том, пробовали ли инструмент вообще).
    """
    used = set()
    for call in (calls or []):
        if isinstance(call, dict):
            used.add((str(call.get("server") or ""), str(call.get("tool") or "")))
    out: List[Dict[str, Any]] = []
    for item in (tools or []):
        if not isinstance(item, dict):
            continue
        name = str(item.get("tool") or "")
        if not name or (str(item.get("server") or ""), name) in used:
            continue
        out.append(item)
    return out


def chain_possible(tools: Optional[List[Dict[str, Any]]], calls: Any) -> bool:
    """Возможен ли СЛЕДУЮЩИЙ шаг: остались невызванные инструменты.

    Это не решение «идём цепочкой» — решение принимает диспетчер, глядя на
    РЕЗУЛЬТАТЫ (см. digest: там перечислены невызванные инструменты и вопрос «не
    закрывает ли один из них оставшуюся часть работы?»). Это признак, что шаг
    вообще возможен, и спросить о нём стоит.

    Зачем понадобился: раньше вход в цикл требовал ТЕКСТОВЫХ маркеров («сохрани»,
    «затем», «выгрузи») или собственного объявления модели. Цепочки, где
    зависимость по данным есть, а слов-подсказок нет, до цикла не доходили:
    «погода у Алёны в городе» — сначала список жителей, потом прогноз по
    найденному городу, и ни одного маркера; модель отвечала по первому вызову
    («погоды в данных нет»). Признак структурный: он смотрит на НАБОР
    инструментов, а не на слова, и ни к какому серверу не привязан.
    """
    return bool(unused_tools(tools, calls))


def chain_reason(signals: Dict[str, Any]) -> str:
    """Понятная причина решения «идём в цепочку» (для чата и отладки).

    Называем инструменты, ПОДХОДЯЩИЕ по виду результата (см. id_tools_relevant):
    иначе причина объясняла цепочку инструментами чужого сервера — например,
    наблюдениями погоды в запросе про реестр городов.
    """
    if not signals.get("needed"):
        return ""
    relevant = signals.get("id_tools_relevant") or signals.get("id_tools") or []
    tools = ", ".join(f"{item['tool']}({', '.join(item['args'])})"
                      for item in relevant[:3])
    kinds = signals.get("kinds") or []
    what = " и ".join({"save": "сохранить", "export": "выгрузить"}[kind]
                      for kind in kinds if kind in ("save", "export")) or \
        "сохранить/выгрузить"
    return (f"запрос просит {what}, а инструменты требуют идентификатор из "
            f"результата: {tools}")


def call_key(call: Any) -> str:
    """Ключ вызова для дедупликации: сервер + инструмент + аргументы как есть.

    Один и тот же вызов в цепочке повторять нельзя: результат уже есть, а второй
    запуск только потратит время (у пишущих инструментов — ещё и создаст дубль).
    """
    if not isinstance(call, dict):
        return ""
    return "|".join((
        str(call.get("server") or ""),
        str(call.get("tool") or ""),
        json.dumps(call.get("arguments") or {}, ensure_ascii=False, sort_keys=True),
    ))


def extract_ids(results: Any) -> Dict[str, str]:
    """Идентификаторы из РЕЗУЛЬТАТОВ: {имя аргумента: значение}.

    Источник значения — только текст ответа сервера. Это то, что разрешено
    подставлять в аргументы-идентификаторы следующего вызова (см. guard_calls):
    выдуманный id сервер отклонит, и цепочка встанет.
    """
    found: Dict[str, str] = {}
    data = normalize_results(results)
    for item in data:
        if not item.get("ok"):
            continue
        text = str(item.get("text") or "")
        for key, value in _ID_PAIR_RE.findall(text):
            if not ID_ARG_RE.search(key):
                continue
            found.setdefault(key, value)
        for ref in item.get("attachments") or []:
            if ref.get("id"):
                found.setdefault("file_id", str(ref["id"]))
    return found


def next_step_hints(tools: Optional[List[Dict[str, Any]]],
                    ids: Dict[str, str]) -> List[str]:
    """Подсказки «что теперь можно вызвать»: инструменты, чьи id-аргументы готовы.

    Строятся из объявленных схем и найденных значений. Нужны, чтобы диспетчер не
    искал зависимость сам: видно, что, например, выгрузка файла требует
    `dataset_id`, а он уже есть в результатах.
    """
    hints: List[str] = []
    for item in id_required_tools(tools):
        ready = {key: ids[key] for key in item["args"] if key in ids}
        if not ready:
            continue
        pairs = ", ".join(f"{key}={value}" for key, value in ready.items())
        hints.append(f"{item['tool']} (сервер {item['server']}) — нужен "
                     f"{', '.join(item['args'])}; готовое значение: {pairs}")
    return hints


def digest(results: Any, ids: Optional[Dict[str, str]] = None,
           hints: Optional[List[str]] = None,
           tools: Optional[List[Dict[str, Any]]] = None) -> str:
    """Дайджест УЖЕ ВЫПОЛНЕННЫХ вызовов — то, что видит диспетчер в цепочке.

    Диспетчер первого раунда результатов не видит (он выбирает вызовы до их
    выполнения). В цикле ему отдают дайджест: что вызвано, чем закончилось,
    короткий текст ответа, найденные идентификаторы, что из этого следует
    (`next_step_hints`) и какие объявленные инструменты ЕЩЁ НЕ вызывались.

    Последний список — не украшение: без него диспетчер видит только сделанное и
    легко решает «данных хватает», хотя пользователь просил, например, сохранить
    набор и выгрузить файл. Результаты при этом обрезаются первыми: списки
    идентификаторов и неиспользованных инструментов обязаны дойти целиком.
    """
    data = normalize_results(results)
    lines: List[str] = []
    for index, item in enumerate(data, 1):
        status = "OK" if item.get("ok") else "ОШИБКА"
        args = arguments_text(item.get("arguments"))
        body = str(item.get("text") if item.get("ok") else item.get("error") or "")
        lines.append(f"{index}) {item['server']} · {item['tool']}"
                     + (f"({args})" if args else "") + f" — {status}\n"
                     + body[:DIGEST_RESULT_CHARS].strip())
        for ref in item.get("attachments") or []:
            lines.append(f"   [файл] {ref['name']} ({ref['size_text']}) — {ref['url']}")
    head = "РЕЗУЛЬТАТЫ УЖЕ ВЫПОЛНЕННЫХ ВЫЗОВОВ:\n" + ("\n\n".join(lines) if lines
                                                      else "(вызовов ещё не было)")
    tail = ""
    found = ids if ids is not None else extract_ids(results)
    if found:
        tail += ("\n\nИДЕНТИФИКАТОРЫ ИЗ РЕЗУЛЬТАТОВ (только эти значения допустимы "
                 "в аргументах-идентификаторах):\n"
                 + "\n".join(f"- {key} = {value}" for key, value in found.items()))
    ready = hints if hints is not None else next_step_hints([], found)
    if ready:
        tail += "\n\nЧТО ТЕПЕРЬ ВОЗМОЖНО:\n" + "\n".join(f"- {line}" for line in ready)
    # Инструменты, которые ЕЩЁ НЕ вызывались — см. пояснение в docstring.
    called = {(item["server"], item["tool"]) for item in data}
    unused = []
    for tool in (tools or []):
        name = str(tool.get("tool") or "")
        server_id = str(tool.get("server") or "")
        if not name or (server_id, name) in called:
            continue
        # Обязательные аргументы показываем рядом с инструментом: без них не
        # видно, ЧТО именно ему нужно подставить, и модель подставляла слово из
        # запроса вместо найденного значения (живой случай 09.10: в аргумент
        # «location» ушло имя человека, хотя в результатах был его город).
        schema = tool.get("schema") if isinstance(tool.get("schema"), dict) else {}
        required = [str(key) for key in (schema.get("required") or [])]
        hint = f" — обязательные аргументы: {', '.join(required)}" if required else ""
        unused.append(f"{name} (сервер {server_id}){hint}")
    # Кандидаты для аргументов: значения, найденные в результатах и НЕ названные
    # в запросе. Без них модель подставляла в аргументы слово из запроса.
    candidates = candidate_values(results)
    if candidates:
        tail += ("\n\nЗНАЧЕНИЯ, НАЙДЕННЫЕ В РЕЗУЛЬТАТАХ (в запросе их не было; "
                 "если инструменту нужен такой аргумент — подставляй именно "
                 "отсюда):\n" + "\n".join(f"- {value}" for value in candidates))
    if unused:
        tail += ("\n\nИНСТРУМЕНТЫ, КОТОРЫЕ ЕЩЁ НЕ ВЫЗЫВАЛИСЬ (сверь с запросом: "
                 "не закрывает ли один из них оставшуюся часть работы?" + 
                 " Если инструменту нужен аргумент, которого в запросе НЕТ, — бери "
                 "его значение из РЕЗУЛЬТАТОВ выше, а не из текста запроса):\n"
                 + "\n".join(f"- {name}" for name in unused))
    budget = max(800, CHAIN_DIGEST_CHARS - len(tail))
    return (head[:budget] + tail)[:CHAIN_DIGEST_CHARS]


# Слова, которые не являются «значением из результата»: служебный шум ответов
# серверов. Список короткий и общий — он не про предметную область, а про текст
# ответов (record, resident, city и подобное).
_VALUE_STOPWORDS = frozenset((
    "record", "records", "resident", "residents", "city", "cities", "total",
    "server", "error", "invalid", "arguments", "ok", "true", "false", "null",
    "the", "and", "for", "with", "from", "first", "saved", "language",
))

_VALUE_TOKEN_RE = re.compile(r"[A-Za-z\u0410-\u042f\u0401][A-Za-z\u0430-\u044f\u0451\-]{2,}")


def candidate_values(results: Any, request_text: str = "",
                    limit: int = 8) -> List[str]:
    """Значения из РЕЗУЛЬТАТОВ, которых нет в запросе: кандидаты для аргументов.

    Нужны затем, чтобы модель подставляла в аргументы НАЙДЕННОЕ, а не слово из
    запроса. Живой случай 09.10: «погода у Алёны в городе» — реестр вернул
    пару «город человека», а модель подставила в аргумент `location` имя
    человека, получила отказ и повторила ошибку в следующем раунде. Список
    строится по ТЕКСТУ результатов (слова с заглавной буквы — имена, города,
    названия) и ни к какому серверу не привязан.
    """
    text = "\n".join(str(item.get("text") or "") for item in normalize_results(results))
    asked = str(request_text or "").lower()
    seen: List[str] = []
    for match in _VALUE_TOKEN_RE.findall(text):
        token = match.strip("-")
        if len(token) < 3 or token.lower() in _VALUE_STOPWORDS:
            continue
        if token.lower() in asked:      # это слово и так есть в запросе
            continue
        if token in seen:
            continue
        seen.append(token)
        if len(seen) >= limit:
            break
    return seen


def chain_note(iteration: int, total: int, remaining: int,
               signals: Optional[Dict[str, Any]] = None) -> str:
    """Условие для диспетчера в раунде цепочки (идёт в блок «ВАЖНОЕ УСЛОВИЕ»).

    Правила жёсткие, потому что цена ошибки — отказ сервера (выдуманный id) или
    дубль данных на сервере (повторное сохранение без перезаписи).
    """
    hint = chain_reason(signals or {}) or "запрос требует нескольких шагов"
    return (
        f"ЭТО ПРОДОЛЖЕНИЕ ЦЕПОЧКИ: раунд {iteration} из {total}, остаток вызовов — "
        f"{remaining}. Причина: {hint}.\n"
        "Смотри на РЕЗУЛЬТАТЫ и на список НЕ ВЫЗВАННЫХ инструментов ниже и реши, "
        "нужен ли СЛЕДУЮЩИЙ вызов.\n"
        "ПРАВИЛА ЦЕПОЧКИ:\n"
        "1) Запрос выполняется ЦЕЛИКОМ, а не только чтением данных. Если пользователь "
        "просил сохранить, записать, экспортировать, выгрузить файлом, сформировать "
        "таблицу-файл, отчёт или приложить файл — это РАБОТА ИНСТРУМЕНТОВ, и пока "
        "соответствующий инструмент не вызван, запрос НЕ выполнен. Общее правило "
        "«вызывай только если без него нельзя ответить» здесь НЕ действует: "
        "сохранение и выгрузка нужны сами по себе.\n"
        "2) Не повторяй вызовы, данные которых уже получены: они есть в результатах.\n"
        "3) ЗНАЧЕНИЯ АРГУМЕНТОВ БЕРИ ИЗ РЕЗУЛЬТАТОВ, А НЕ ИЗ ЗАПРОСА. Это касается "
        "и идентификаторов (dataset_id, watch_id, id, key — они только из блока "
        "«ИДЕНТИФИКАТОРЫ ИЗ РЕЗУЛЬТАТОВ»; выдуманный идентификатор будет отброшен), "
        "и ЛЮБЫХ аргументов, называющих ОБЪЕКТ: места, города, имени, кода, адреса. "
        "Если в запросе названо ОДНО, а инструмент ждёт ДРУГОЕ, которого в запросе "
        "нет (например, назван человек, а нужен его город), — найди нужное значение "
        "в РЕЗУЛЬТАТАХ предыдущих вызовов и подставь ЕГО. Подставлять в такой "
        "аргумент слово из запроса нельзя: сервер его не найдёт и откажет. Если "
        "нужного значения в результатах нет — сначала вызови инструмент, который "
        "его даёт (list_*, search_*, get_*), а уже потом тот, что его принимает.\n"
        "4) Значения данных (числа, даты, тексты), которые надо записать, копируй "
        "из результатов КАК ЕСТЬ, ничего не досчитывая и не округляя.\n"
        "5) Если для записи нужен постоянный ключ (dataset_id/title/name), задай его "
        "сам по смыслу задачи (места и даты) и используй ОДИН И ТОТ ЖЕ ключ во всех "
        "раундах и повторах задачи; при повторной записи того же ключа передавай "
        "флаг перезаписи (replace/overwrite), если он объявлен в схеме.\n"
        "6) Пустой список допустим ТОЛЬКО когда запрос выполнен полностью: данные "
        "получены, всё, о чём просил пользователь, сделано инструментами, и ни один "
        "невызванный инструмент не продвинет работу. Тогда верни "
        "{\"done\": true, \"reason\": \"почему больше нечего делать\", \"calls\": []}.\n"
        "Ответ — ТОЛЬКО JSON: {\"done\": false, \"reason\": \"зачем вызов\", "
        "\"calls\": [...]}."
    )


def delivery_candidates(tools: Optional[List[Dict[str, Any]]],
                        done_pairs: Optional[set] = None,
                        kinds: Optional[List[str]] = None) -> List[Dict[str, Any]]:
    """Невызванные инструменты, которые СОЗДАЮТ результат (сохранить, выгрузить).

    Нужны для принудительного уточнения: диспетчер непостоянен — на один и тот же
    запрос он то строит цепочку, то решает «данных хватает», и задача остаётся
    без сохранения и файла. Если запрос явно просит сохранить/выгрузить (см.
    CHAIN_MARKERS), а вызовов для этого не было, агент спрашивает диспетчера ЕЩЁ
    РАЗ, назвав эти инструменты прямо (см. deliver_note).

    Отбор — по имени инструмента, как пары start_/stop_ выше: схемы MCP описывают
    только вход, и «этот инструмент создаёт результат» из них не видно. Берём
    именно СОЗДАЮЩИЕ префиксы (`RESULT_RE`: save_/export_/create_/…), а не любое
    упоминание слова «report» в имени: читающий `get_weather_watch_report` тоже
    его содержит, и по нему цепочка считала, что результат ещё не выдан, — лишний
    полный раунд диспетчера после выгрузки файла.

    `kinds` — какие ВИДЫ результата запрос ещё ждёт (см. unsatisfied_kinds).
    `None` — не фильтровать по виду (нужно там, где вопрос не «что просил
    запрос», а «остались ли вообще создающие инструменты»). Пустой список —
    запрос не просил ничего создавать, значит и уточнять не о чем: иначе агент
    требовал «сохранить» у сервера, которого запрос не касался.
    """
    done = done_pairs if isinstance(done_pairs, set) else set()
    wanted = None if kinds is None else {str(kind) for kind in kinds}
    out: List[Dict[str, Any]] = []
    for tool in (tools or []):
        name = str(tool.get("tool") or "")
        server_id = str(tool.get("server") or "")
        if not name or (server_id, name) in done:
            continue
        if not RESULT_RE.match(name):
            continue
        if wanted is not None and result_kind(name) not in wanted:
            continue
        out.append({"server": server_id, "tool": name,
                    "kind": result_kind(name),
                    "description": str(tool.get("description") or "")[:200]})
    return out


def auto_followup(tools: Optional[List[Dict[str, Any]]], done_pairs: Optional[set],
                  known_ids: Optional[Dict[str, str]],
                  kinds: Optional[List[str]] = None) -> Optional[Dict[str, Any]]:
    """Очевидная ДОСТРОЙКА без модели: единственный оставшийся шаг результата.

    Если после создающего вызова остался РОВНО ОДИН невызванный инструмент,
    который создаёт результат (например, выгрузка файла по сохранённому набору),
    и все его ОБЯЗАТЕЛЬНЫЕ аргументы — идентификаторы, значения которых уже
    известны (id пришёл из ответа сервера), решение очевидно: его можно вызвать
    без вопроса диспетчеру. Это экономит целый вызов LLM — самую дорогую часть
    задачи (промпт диспетчера: список инструментов, правила, дайджест).

    `kinds` ограничивает достройку тем, что запрос ДЕЙСТВИТЕЛЬНО просил (см.
    unsatisfied_kinds). Без этого «ровно один кандидат» ломалось о любой второй
    включённый сервер: у него находится свой невызванный save-инструмент, и
    очевидная выгрузка переставала выполняться без модели.

    Возвращает готовый вызов либо None (тогда решает модель, как и раньше).
    Консервативно: один кандидат, непустые обязательные аргументы, все значения
    известны. Ничего не выдумывается — иначе вернули бы None.
    """
    candidates = delivery_candidates(tools, done_pairs, kinds=kinds)
    if len(candidates) != 1:
        return None
    candidate = candidates[0]
    schema = _schema_for(str(candidate.get("server") or ""),
                         str(candidate.get("tool") or ""), tools)
    required = [str(key) for key in (schema.get("required") or [])]
    if not required:
        return None
    arguments: Dict[str, str] = {}
    known = known_ids or {}
    for key in required:
        value = str(known.get(key) or "")
        if not value:
            return None
        arguments[key] = value
    return {"server": str(candidate.get("server") or ""),
            "tool": str(candidate.get("tool") or ""), "arguments": arguments}


def deliver_note(candidates: List[Dict[str, Any]], request_text: Any = "",
                 initial: bool = False) -> str:
    """Уточнение диспетчеру: «запрос просил сохранить/выгрузить — вызова не было».

    Перечисляет невызванные инструменты, которые создают результат, и требует
    либо вызвать подходящий, либо объяснить, почему ни один не подходит. Так
    задача не остаётся без файла из-за того, что модель решила «данных хватает».

    `initial` — уточнение ПЕРЕД первым раундом (диспетчер ответил «данные не
    нужны» на запрос, который явно просит сохранение/выгрузку): тогда данных ещё
    нет, и вместо «вызови подходящий» нужно «верни ЧТЕНИЕ и режим chain».
    """
    if not candidates:
        return ""
    lines = [f"- {item['tool']} (сервер {item['server']})"
             + (f" — {item['description']}" if item.get("description") else "")
             for item in candidates[:8]]
    tail = (
        "Вызови подходящий (данные для его аргументов уже есть в результатах выше) "
        "или, если ни один не подходит, верни {\"done\": true} и в поле reason "
        "объясни, почему сохранение/выгрузка невозможны."
        if not initial else
        "Верни в этом раунде ЧИТАЮЩИЕ вызовы, которые нужны для этого шага, и "
        "поставь mode=\"chain\": сохранение и выгрузку выполнишь следующими "
        "раундами по результатам. Если шаг невозможен объявленными инструментами — "
        "верни пустой список и объясни это в reason."
    )
    return (
        "ЗАПРОС ВЫПОЛНЕН НЕ ПОЛНОСТЬЮ. Пользователь просил сделать с данными ещё "
        "шаг (сохранить/записать/выгрузить/отдать файлом), но НИ ОДИН инструмент "
        "для этого не вызван. Ниже инструменты, которые ещё НЕ вызывались и могут "
        "закрыть эту часть работы:\n" + "\n".join(lines) + "\n" + tail
    )


def _schema_for(server_id: str, tool: str,
                tools: Optional[List[Dict[str, Any]]] = None) -> Dict[str, Any]:
    """Схема аргументов инструмента: из переданного списка или из кэша tools/list.

    Нужна там, где список инструментов под рукой не лежит (например, повтор
    периодической задачи выполняется по сохранённым вызовам БЕЗ обнаружения
    инструментов). Сбой сервера не должен ломать вызов: нет схемы — нет и
    решения, которое на неё опирается.
    """
    schema = _schema_of(tools or [], server_id, tool)
    if schema:
        return schema
    try:
        found = discover(server_id)
    except Exception:  # noqa: BLE001 — недоступный сервер не ломает вызов
        return {}
    for item in ((found or {}).get("tools") or []):
        if str(item.get("name") or "") == tool:
            schema = item.get("schema")
            return schema if isinstance(schema, dict) else {}
    return {}


def overwrite_flag(schema: Optional[Dict[str, Any]]) -> str:
    """Имя флага перезаписи в схеме инструмента ("" — такого флага нет).

    Серверы называют его по-разному (`replace`, `overwrite`, `force`…), поэтому
    ищем по списку имён, а не по одному. Флаг есть только у инструментов, которые
    умеют обновлять уже существующее.
    """
    props = (schema or {}).get("properties")
    if not isinstance(props, dict):
        return ""
    for name in OVERWRITE_FLAGS:
        if name in props:
            return name
    return ""


def enforce_overwrite(calls: Any, tools: Optional[List[Dict[str, Any]]] = None,
                      known_ids: Optional[Dict[str, str]] = None) -> List[str]:
    """Ставит флаг перезаписи, когда задача ПОВТОРНО пишет под тем же ключом.

    Живой случай: сервер отказывает в сохранении набора, который уже существует
    («A dataset with id … already exists. Pass replace: true to overwrite it»), а
    в повторе периодической задачи диспетчер не спрашивается вовсе — вызовы
    выполняются как сохранены, и без флага повтор оставался без свежих данных.

    Правило: если у СОЗДАЮЩЕГО инструмента (`save_*`, `create_*`…) есть
    id-аргумент, значение которого задача УЖЕ использовала (known_ids), и в схеме
    объявлен флаг перезаписи — ставим его сами. Так повтор обновляет тот же набор
    (идемпотентность), а не падает и не плодит дубли. Чужие вызовы не трогаем:
    новый ключ флага не получает.

    Возвращает список правок для строки в чате.
    """
    known = {str(value) for value in (known_ids or {}).values()}
    if not known:
        return []
    changed: List[str] = []
    # Правим ИМЕННО те словари, что лежат в списке вызовов: normalize_calls делает
    # копии, и флаг, поставленный копии, до выполнения не дошёл бы (как и в
    # mark_call_kinds, который по этой же причине работает с исходными словарями).
    for call in (calls if isinstance(calls, list) else []):
        if not isinstance(call, dict):
            continue
        tool = str(call.get("tool") or "")
        if not PRODUCER_RE.match(tool):
            continue
        server_id = str(call.get("server") or "")
        schema = _schema_for(server_id, tool, tools)
        flag = overwrite_flag(schema)
        if not flag:
            continue
        arguments = call.get("arguments")
        if not isinstance(arguments, dict) or arguments.get(flag) is True:
            continue
        ids = {str(key): str(value) for key, value in arguments.items()
               if ID_ARG_RE.search(str(key))}
        if not any(value in known for value in ids.values()):
            continue
        arguments[flag] = True
        changed.append(f"{tool}: {flag}=true ({', '.join(f'{k}={v}' for k, v in ids.items())})")
    return changed


def produced_result(results: Any) -> bool:
    """Получен ли по запросу ГОТОВЫЙ РЕЗУЛЬТАТ: файл или сохранённый набор/отчёт.

    Признак успешного РЕЗУЛЬТАТА, а не чтения: среди успешных вызовов есть вложение
    (файл) или вызов, который что-то СОЗДАЛ (`is_deferred_call`: save_/export_/
    create_/report_… — по префиксу имени). Обычное чтение отчёта
    (`get_weather_watch_report`) и запуск сбора результатом не считаются: это лишь
    данные и подготовка к ним.

    Нужен веб-слою: если работа уже сделана инструментами (в гибридной схеме это
    возможно только после подтверждения плана), спрашивать подтверждение не о чем —
    задача висела бы в ожидании при готовом результате.
    """
    for item in normalize_results(results):
        if not item.get("ok"):
            continue
        if item.get("attachments"):
            return True
        if RESULT_RE.match(str(item.get("tool") or "")):
            return True
    return False


def produced_ids(calls: Any) -> Dict[str, str]:
    """Идентификаторы, которые НАЗВАЛИ создающие вызовы (save_/create_/…).

    Их сервер принял (вызов выполнен), значит эти значения существуют и их можно
    переиспользовать в следующих раундах: например, сохранили набор под ключом
    `ekb-kzn-27-09` — этот же ключ потом передаём в выгрузку файла и в повторах
    периодической задачи (иначе каждый повтор заводил бы новый набор).
    """
    out: Dict[str, str] = {}
    for call in normalize_calls(calls, limit=MAX_TOTAL_CALLS_PER_REQUEST):
        tool = str(call.get("tool") or "")
        if not PRODUCER_RE.match(tool):
            continue
        for arg, value in (call.get("arguments") or {}).items():
            if ID_ARG_RE.search(str(arg)) and TOKEN_RE.match(str(value) or ""):
                out.setdefault(str(arg), str(value))
    return out


def guard_calls(calls: Any, results: Any, tools: Optional[List[Dict[str, Any]]],
                user_text: str = "",
                done_keys: Optional[set] = None,
                issued_ids: Optional[Dict[str, str]] = None
                ) -> Tuple[List[Dict[str, Any]], List[Dict[str, str]]]:
    """Отбрасывает недопустимые вызовы цепочки; возвращает (допущенные, отказы).

    Четыре проверки (все — про безопасность и осмысленность, а не про удобство):

    1. **Идентификаторы не выдумывают.** Значение аргумента-идентификатора у
       ЧИТАЮЩЕГО инструмента обязано присутствовать в тексте результатов (или быть
       названным ранее создающим вызовом — см. `issued_ids`): иначе следующий
       вызов гарантированно провалится (сервер не знает такого dataset_id), а
       цепочка сожжёт раунды.
    2. **Создающему инструменту идентификатор задать можно** (`save_*`, `create_*`):
       он этот идентификатор и создаёт. Значение при этом должно быть обычным
       токеном — без путей, пробелов и переводов строк.
    3. **Разрушительное — только по прямой просьбе.** `delete_*`, `stop_*` и
       подобные в автоцикле опасны: их вызывают, лишь если пользователь сам
       просит удалить/остановить.
    4. **Повторов нет.** Тот же вызов с теми же аргументами не выполняется дважды
       (результат уже есть; для пишущих инструментов это ещё и дубль на сервере).
    """
    allowed: List[Dict[str, Any]] = []
    rejected: List[Dict[str, str]] = []
    keys = done_keys if isinstance(done_keys, set) else set()
    # Текст всех результатов — область, в которой ищем «настоящие» значения.
    haystack = "\n".join(str(item.get("text") or "") + " " + str(item.get("error") or "")
                         for item in normalize_results(results))
    known = set(extract_ids(results).values())
    issued = {str(value) for value in (issued_ids or {}).values()}
    body = " ".join(str(user_text or "").lower().split())
    for call in normalize_calls(calls, limit=MAX_TOTAL_CALLS_PER_REQUEST):
        server_id, tool = str(call.get("server") or ""), str(call.get("tool") or "")
        key = call_key(call)
        if key and key in keys:
            rejected.append({"server": server_id, "tool": tool,
                             "reason": "такой вызов уже выполнялся — результат есть"})
            continue
        if DESTRUCTIVE_RE.match(tool) and not any(m in body for m in DESTRUCTIVE_MARKERS):
            rejected.append({"server": server_id, "tool": tool,
                             "reason": "разрушительный вызов без прямой просьбы "
                                       "пользователя — отброшен"})
            continue
        producer = bool(PRODUCER_RE.match(tool))
        bad = ""
        for arg, value in (call.get("arguments") or {}).items():
            if not ID_ARG_RE.search(str(arg)):
                continue
            text = str(value or "")
            if not text:
                continue
            if producer:
                if not TOKEN_RE.match(text):
                    bad = (f"значение {arg} не похоже на идентификатор (нужен короткий "
                           "токен без путей и пробелов)")
                    break
                continue
            if text in known or text in issued or text in haystack:
                continue
            bad = (f"значение {arg}={text} не найдено в результатах — идентификатор "
                   "нельзя выдумывать, сначала вызови инструмент, который его выдаёт "
                   "или перечисляет (list_*)")
            break
        if bad:
            rejected.append({"server": server_id, "tool": tool, "reason": bad})
            continue
        allowed.append(call)
        if key:
            keys.add(key)
        if producer:
            for arg, value in produced_ids([call]).items():
                issued.add(value)
    return allowed, rejected


def attachments_of(results: Any) -> List[Dict[str, Any]]:
    """Все файлы, полученные за запрос (для карточки в чате и системного блока)."""
    out: List[Dict[str, Any]] = []
    for item in normalize_results(results):
        for ref in item.get("attachments") or []:
            clean = attach_store.public(ref)
            if clean and clean not in out:
                out.append(clean)
    return out


def mark_call_kinds(calls: Any, tools: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Помечает вызовы признаком «действие на сервере» (запуск/остановка).

    Вызывается сразу после выбора инструментов: тогда список объявленных
    инструментов под рукой, и повтору достаточно посмотреть на сам вызов.
    """
    for call in (calls if isinstance(calls, list) else []):
        if not isinstance(call, dict):
            continue
        if is_action_tool(call.get("tool"), tools, str(call.get("server") or "")):
            call["action"] = True
        else:
            call.pop("action", None)
    return calls if isinstance(calls, list) else []


def mark_actions(results: Any, tools: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Помечает в результатах ДЕЙСТВИЯ и возвращает удачные сборы для отмены.\n"

    Действие — вызов инструмента, у которого есть отменяющая пара в объявленном
    списке сервера (см. undo_tool): регистрация наблюдения, подписка и т. п.
    Помеченные результаты уходят модели с явной строкой «ДЕЙСТВИЯ В ЭТОМ
    ЗАПРОСЕ» (см. block), поэтому выдумать несостоявшуюся регистрацию нельзя,
    а неудачное действие считается НЕ выполненным.

    Возвращает то же, что started_calls: список обязательств для последующей
    отмены (только успешно запущенные).
    """
    marked: List[Dict[str, Any]] = []
    # Помечаем ИМЕННО те словари, что лежат в dialog["mcp"] (их читает block):
    # копия здесь была бы бесполезна — модель видела бы старые результаты.
    for item in (results if isinstance(results, list) else []):
        if not isinstance(item, dict):
            continue
        server_id = str(item.get("server") or "").strip()
        tool = str(item.get("tool") or "").strip()
        names = [entry.get("tool") for entry in (tools or [])
                 if str(entry.get("server") or "") == server_id]
        if not tool or not undo_tool(tool, names):
            continue
        item["action"] = "started" if item.get("ok") else "failed"
        marked.append(item)
    return marked


def cancel_started(entries: Any) -> List[Dict[str, Any]]:
    """ОТМЕНЯЕТ внешние сборы задачи: вызывает отменяющие инструменты.\n"

    Возвращает отчёты: [{"server", "tool", "ok", "text", "error"}]. Сбои не
    скрываются: их видит пользователь (в чате задачи), потому что незакрытый
    сбор на сервере — это работающий впустую источник и место на диске.
    """
    reports: List[Dict[str, Any]] = []
    for item in (entries if isinstance(entries, list) else []):
        if not isinstance(item, dict):
            continue
        server_id = str(item.get("server") or "").strip()
        tool = str(item.get("stop_tool") or "").strip()
        if not server_id or not tool:
            continue
        arguments = item.get("arguments") if isinstance(item.get("arguments"), dict) else {}
        try:
            result = call_tool(server_id, tool, arguments)
        except Exception as exc:  # noqa: BLE001 — сбой отмены не должен ломать удаление
            logger.warning("MCP: отмена %s/%s не удалась", server_id, tool, exc_info=True)
            reports.append({"server": server_id, "tool": tool, "ok": False,
                            "text": "", "error": str(exc)[:300]})
            continue
        reports.append({
            "server": server_id, "tool": tool,
            "ok": bool(result.get("ok")),
            "text": str(result.get("text") or "")[:400],
            "error": str(result.get("error") or "")[:300],
        })
    return reports


async def async_cancel_started(entries: Any) -> List[Dict[str, Any]]:
    """То же в отдельном потоке: отмена — сетевые вызовы, цикл событий не держим."""
    if not entries:
        return []
    return await asyncio.to_thread(cancel_started, entries)


def cancel_note(reports: List[Dict[str, Any]]) -> str:
    """Строка для чата: что удалось (и не удалось) отменить на серверах."""
    if not reports:
        return ""
    done = [item for item in reports if item.get("ok")]
    failed = [item for item in reports if not item.get("ok")]
    parts: List[str] = []
    if done:
        parts.append("остановлены внешние сборы: " + "; ".join(
            f"{item['server']} · {item['tool']} "
            f"({(item.get('text') or '').splitlines()[0][:80]})" for item in done))
    for item in failed:
        parts.append(f"НЕ удалось остановить {item['server']} · {item['tool']}"
                     + (f": {item['error']}" if item.get("error") else ""))
    return "; ".join(parts)


