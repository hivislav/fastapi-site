def is_command(text: Any) -> bool:
    """Команда ли это `/help` (в том числе с вопросом после неё)."""
    value = str(text or "").strip()
    if not value.lower().startswith(COMMAND):
        return False
    rest = value[len(COMMAND):]
    # «/helper» и «/help-me» — НЕ наша команда: после неё должен идти конец
    # строки или пробел, иначе обычный текст уходил бы в ассистента проекта.
    return not rest or rest[0].isspace()


def parse(text: Any) -> Tuple[bool, str]:
    """Разбор команды: (это команда, вопрос).

    Вопрос — всё, что идёт после `/help`. Пустой вопрос законен: команду набирают
    и одной строкой, и тогда человек ждёт обзор проекта (`question()`).
    """
    value = str(text or "").strip()
    if not is_command(value):
        return False, ""
    rest = value[len(COMMAND):].strip()
    return True, rest


def question(text: Any) -> str:
    """Вопрос для ассистента: из команды, а без вопроса — обзор проекта."""
    _, asked = parse(text)
    return asked or DEFAULT_QUESTION


def prompt_for(with_fragments: bool) -> str:
    """Промпт ответа — ПО ДАННЫМ: есть фрагменты документации или их нет.

    Выбор делает код, а не модель: правила про цитаты и ссылки в ответе, где
    ссылаться не на что, превращают ответ в «в документации этого нет» — на этом
    уже спотыкался мини-чат (§5.13.4).
    """
    return PROMPT if with_fragments else PROMPT_NO_DOCS


# Путь файла в вопросе: «app/ai/mcp.py», «chat.html», «tools/check_rag.py».
# Расширения перечислены явно — так «2.5» и «СЕГОДНЯ» путями не считаются.
_FILE_RE = re.compile(
    r"[A-Za-z0-9_][A-Za-z0-9_./-]*\."
    r"(?:py|mjs|cjs|js|html|css|md|txt|json|sh|swift|ya?ml|toml|cfg|ini|sql)\b",
    re.IGNORECASE,
)


def mentions(text: Any, limit: int = 3) -> List[str]:
    """Пути файлов, названные в вопросе (по порядку упоминания, без повторов).

    Нужны, чтобы показать модели ИМЕННО тот файл, о котором спросили, а не общий
    список: «что делает app/ai/mcp.py» без этого отвечалось бы обзором проекта.
    Существует ли путь на самом деле, проверяет `kind_of`: в вопросе может стоять
    имя файла, которого в репозитории нет, и вызов инструмента с таким путём был
    бы заведомым отказом сервера — человек получил бы ошибку инструмента вместо
    ответа.
    """
    out: List[str] = []
    for match in _FILE_RE.finditer(str(text or "")):
        value = match.group(0).strip("./")
        if not value or value.lower().startswith("http"):
            continue
        if value not in out:
            out.append(value)
        if len(out) >= max(1, int(limit or 1)):
            break
    return out


def kind_of(root: str, question: Any) -> Tuple[str, str]:
    """Первый СУЩЕСТВУЮЩИЙ в репозитории путь из вопроса: (путь, вид).

    Вид решает, что спрашивать у репозитория: файл — его изменения и содержимое,
    каталог — что в нём лежит. Ничего не нашлось — вопрос общий, и контекст
    собирается целиком (состояние, сводка изменений, файлы, история).

    `root` — каталог репозитория, о котором отвечает ассистент: тот же, с которым
    работает сервер `git` (переменная `GIT_REPO_DIR`, иначе корень проекта). Вид
    определяется по ФАЙЛОВОЙ СИСТЕМЕ, а не по словам вопроса: «а как устроен
    rag_helpers.py?» — вопрос о файле, которого в проекте нет, и вызов
    инструмента с таким путём вернул бы отказ вместо ответа.
    """
    base = str(root or "").strip()
    if not base:
        return "", ""
    for candidate in mentions(question):
        target = os.path.join(base, candidate)
        if os.path.isfile(target):
            return candidate, PATH_FILE
        if os.path.isdir(target):
            return candidate, PATH_DIR
    return "", ""


def calls(path: str = "", path_kind: str = "") -> List[Dict[str, Any]]:
    """Какие инструменты git вызвать для этого вопроса (решает КОД).

    Две ветки, и обе всегда начинаются с состояния репозитория:

    * **в вопросе назван файл или каталог проекта** (`path` — путь внутри
      проекта, `path_kind` — файл или каталог) — показываем именно его: что в нём
      изменено и что он содержит (файл) или что в нём лежит (каталог);
    * **путь не назван** — общий контекст работы: состояние, сводка изменений,
      список файлов проекта и последние коммиты.

    Больше `MAX_CONTEXT_CALLS` вызовов не бывает: каждый — отдельный процесс
    сервера, а весь блок уходит в контекст модели.
    """
    calls_list: List[Dict[str, Any]] = [
        {"server": SERVER_ID, "tool": STATUS_TOOL, "arguments": {}},
    ]
    rel = str(path or "").strip().strip("/")
    kind = str(path_kind or "").strip().lower()
    if rel and kind == PATH_DIR:
        calls_list.append({"server": SERVER_ID, "tool": DIFF_TOOL,
                           "arguments": {"path": rel, "scope": "head",
                                         "stat_only": True}})
        calls_list.append({"server": SERVER_ID, "tool": FILES_TOOL,
                           "arguments": {"path": rel, "limit": 60}})
    elif rel and kind == PATH_FILE:
        calls_list.append({"server": SERVER_ID, "tool": DIFF_TOOL,
                           "arguments": {"path": rel, "scope": "head"}})
        calls_list.append({"server": SERVER_ID, "tool": SHOW_TOOL,
                           "arguments": {"path": rel}})
    else:
        calls_list.append({"server": SERVER_ID, "tool": DIFF_TOOL,
                           "arguments": {"scope": "head", "stat_only": True}})
        calls_list.append({"server": SERVER_ID, "tool": FILES_TOOL,
                           "arguments": {"limit": 60}})
        calls_list.append({"server": SERVER_ID, "tool": LOG_TOOL,
                           "arguments": {"limit": 5}})
    return calls_list[:MAX_CONTEXT_CALLS]


def history_from_log(nodes: Any, count: int = HISTORY_NODES,
                     limit: int = HISTORY_CHARS) -> str:
    """История разговора для ассистента — из ЖУРНАЛА чата (что видел человек).

    Почему из журнала, а не из памяти диалога (`dialog["messages"]`): команда
    идёт МИМО пайплайна задачи и в память диалога не пишет (как `/test_rag`), а
    без истории второй вопрос «а как он выбирает инструменты?» остался бы без
    того, о чём он. Журнал же хранит всё, что человек видел в этом диалоге —
    реплики задачи и вопросы с ответами ассистента, — и годится как контекст
    разговора.

    Служебные строки (debug/error/варианты) пропускаются: это не разговор, а
    ход работы. Берём ХВОСТ, как и мини-чат: продолжать можно только по
    последним репликам.
    """
    rows = [item for item in (nodes or []) if isinstance(item, dict)]
    lines: List[str] = []
    total = 0
    for item in reversed(rows[-max(1, int(count or 1)) * 6:]):
        kind = str(item.get("kind") or "")
        if kind not in ("user", "assistant"):
            continue
        text = " ".join(str(item.get("text") or "").split())
        if not text:
            continue
        who = "Пользователь" if kind == "user" else "Ассистент"
        line = "%s: %s" % (who, text[:1500])
        if lines and total + len(line) > limit:
            break
        lines.append(line)
        total += len(line)
        if len(lines) >= max(1, int(count or 1)):
            break
    return "\n".join(reversed(lines))


def messages(question_text: str, *, profile: str = "", doc_block: str = "",
             context_block: str = "", history: str = "") -> List[Dict[str, str]]:
    """Сообщения для вызова модели: промпт, профиль, контекст, история, вопрос.

    Порядок — как у агента и мини-чата: сначала кто отвечает (профиль
    пользователя, если он заполнен), затем КОНТЕКСТ ПРОЕКТА (данные MCP), затем
    ФРАГМЕНТЫ документации, затем история разговора и сам вопрос. Контекст идёт
    ПЕРЕД фрагментами намеренно: состояние рабочей копии отвечает на «что сейчас
    происходит», а документация — на «как это устроено», и путать их нельзя.

    Пустые блоки не добавляются вовсе: пустой блок — это обещание данных,
    которых нет (§5.13.4, «пустая память блока не даёт»).
    """
    system = prompt_for(bool(str(doc_block or "").strip()))
    out: List[Dict[str, str]] = [{"role": "system", "content": system}]
    if str(profile or "").strip():
        out.append({"role": "system", "content": str(profile).strip()})
    if str(context_block or "").strip():
        out.append({"role": "system", "content": (
            "КОНТЕКСТ ПРОЕКТА (состояние репозитория получено через MCP; это "
            "данные на момент запроса, а не документация):\n"
            + str(context_block).strip())})
    if str(doc_block or "").strip():
        out.append({"role": "system", "content": str(doc_block).strip()})
    if str(history or "").strip():
        out.append({"role": "system", "content": (
            "ИСТОРИЯ РАЗГОВОРА (последние реплики, от старых к новым; это "
            "контекст, а не задание):\n" + str(history).strip())})
    out.append({"role": "user", "content": str(question_text or "").strip()})
    return out


def git_hint(reason: str = "") -> str:
    """Что делать, если контекст репозитория не подключён (или сервер отказал).

    Молча отвечать «по документации» нельзя: человек ждёт ветку и diff, а
    получит общие слова и решит, что ассистент их не умеет. Причина называется,
    и вместе с ней — что включить.
    """
    text = ("Контекста репозитория нет: сервер «%s» не подключён к проекту — "
            "ветку, список файлов и diff ассистент не видит. Включите его "
            "кнопкой «MCP» рядом с шестерёнкой проекта." % SERVER_ID)
    if str(reason or "").strip():
        text += " Причина: %s." % str(reason).strip()
    return text
