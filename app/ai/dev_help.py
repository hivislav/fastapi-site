"""Ассистент разработчика: команда `/help` — вопросы о САМОМ проекте.

ЧТО ЭТО. Человек спрашивает о проекте, а не о своих документах: «как устроен
поиск по базам знаний», «что делает app/ai/mcp.py», «что я изменил в этой ветке»,
«с чего начать правку». Ответ строится по источникам того же режима «AI-агент»:

* **ДОКУМЕНТАЦИЯ ПРОЕКТА** — те же базы знаний проекта и тот же поиск
  (`rag_search.search`), что у агента: документация проекта проиндексирована в
  базе «Документация проекта», и по вопросу человека в ней ищутся фрагменты;
* **КОНТЕКСТ ПРОЕКТА, ПОЛУЧЕННЫЙ ЧЕРЕЗ MCP** — состояние репозитория: текущая
  ветка, последний коммит, изменённые файлы, diff, история и содержимое файла
  (сервер `git`, mcp_servers/git.mjs, только чтение).

Данных ОБРАЩЕНИЙ здесь нет и быть не должно: поддержка — отдельная команда
`/support` (app/ai/support.py), и сервер `support` помечен в реестре как
командный, поэтому агенту и этой команде его инструменты недоступны вовсе.

ПОЧЕМУ НАБОР ДАННЫХ ВЫБИРАЕТ КОД, А НЕ МОДЕЛЬ. У остальных запросов агента
инструменты выбирает служебный вызов диспетчера (§5.11): у задачи неизвестно
заранее, что понадобится. Здесь наоборот — команда всегда просит ОДНО И ТО ЖЕ
(«покажи состояние работы»), поэтому вызовы заданы кодом (`calls`):
это дешевле на один вызов модели и предсказуемее — контекст проекта есть в каждом
ответе, а не «когда диспетчер догадается». Рассуждение остаётся модели: что из
этих данных следует для вопроса человека.

ЧТО МОДУЛЬ НЕ ДЕЛАЕТ. Он не ходит ни в модели, ни в файлы, ни в MCP: разбор
команды, промпт, набор вызовов и сборка сообщений — чистые функции. Выполняет
вызовы и зовёт модель веб-слой (`app/routers/chat.py`, маршрут
`POST /api/agent/help`), поэтому модуль проверяется без сети и без сервера
(tools/check_dev_help.py).
"""

