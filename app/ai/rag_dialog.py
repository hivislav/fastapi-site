def sources_line(hits: Any, searched: int = 0,
                 cut: str = "") -> str:
    """Строка источников под ответом: номера фрагментов или честное «нет».

    Номера — те же, что в блоке для модели и в карточках интерфейса (оба места
    перебирают `hits` в одном порядке), поэтому «[1]» в тексте открывает именно
    тот фрагмент, из которого взята цитата.
    """
    items = [hit for hit in (hits or []) if isinstance(hit, dict)]
    if not items:
        if searched <= 0:
            return "%s %s." % (SOURCES_MARK, NO_BASES_TEXT)
        if cut:
            return ("%s поиск по базам проекта выполнен, но подходящие фрагменты "
                    "отсечены порогом (%s)." % (SOURCES_MARK, cut))
        return "%s %s." % (SOURCES_MARK, NO_SOURCES_TEXT)
    parts: List[str] = []
    for index, hit in enumerate(items[:5], 1):
        parts.append("[%d] %s" % (index, _short_address(hit)))
    if len(items) > 5:
        parts.append("и ещё %d" % (len(items) - 5))
    return "%s %s." % (SOURCES_MARK, "; ".join(parts))


def _short_address(hit: Dict[str, Any]) -> str:
    """Короткий адрес фрагмента: файл · раздел · релевантность · чанк №.

    Формат тот же, что у карточек интерфейса (`rag_search.sources`): человек
    видит одни и те же числа в тексте ответа и в карточке.
    """
    parts: List[str] = []
    source = str(hit.get("source") or "").strip()
    if source:
        parts.append(source)
    section = str(hit.get("section") or "").strip()
    if section:
        parts.append(section[:60])
    if hit.get("neighbour"):
        parts.append("соседний фрагмент № %s" % (hit.get("parent_chunk") or "?"))
    else:
        score = hit.get("base_score")
        if score is None:
            score = hit.get("score")
        try:
            parts.append("релевантность %.2f" % float(score))
        except (TypeError, ValueError):
            pass
        if hit.get("number"):
            parts.append("фрагмент № %s" % hit.get("number"))
    return " · ".join(parts) if parts else "фрагмент"


def is_meta_question(text: Any) -> bool:
    """Просят ли СВЕСТИ уже найденное, а не спросить о чём-то новом.

    Проверка по словам, а не по смыслу: она решает только одно — искать ли
    дополнительно по цели задачи (см. `search_query`). Ошибиться в сторону
    «поищем и по цели» безопасно: поиск идёт по ОБОИМ запросам, и неточная
    догадка может только добавить кандидатов.
    """
    value = str(text or "").lower()
    return any(marker in value for marker in META_MARKERS)


def search_query(question: Any, memory: Any = None) -> Tuple[str, str]:
    """(запрос поиска, второй запрос) для мини-чата.

    Второй запрос — ЦЕЛЬ задачи, и только у «сводной» просьбы: у обычного
    вопроса свои слова о теме, а у «собери памятку» их нет вовсе. Цель при этом
    не заменяет вопрос, а ДОПОЛНЯЕТ его: поиск идёт по обоим (см. `also` в
    rag_search.search), поэтому неточная догадка ничего не теряет.
    """
    query = str(question or "").strip()
    goal = memory_store.goal_of(memory) if memory is not None else ""
    if not goal or not is_meta_question(query):
        return query, ""
    if _same_query(goal, query):
        return query, ""
    return query, goal


def _same_query(first: str, second: str) -> bool:
    """Совпадают ли два запроса по смыслу (регистр и знаки не важны)."""
    def key(value: str) -> str:
        return re.sub(r"[^\w\s]", "", str(value or "").lower()).strip()

    return key(first) == key(second)


def has_citation(answer: Any) -> bool:
    """Есть ли в тексте ответа ссылка на фрагмент — «[1]», «[3][4]»."""
    return bool(re.search(r"\[\d{1,3}\]", str(answer or "")))


def citations(answer: Any) -> List[int]:
    """Номера фрагментов, на которые сослался ответ («[1]», «[3][4]» → 1, 3, 4)."""
    return [int(value) for value in
            re.findall(r"\[(\d{1,3})\]", str(answer or ""))]


def bad_citations(answer: Any, count: int) -> List[int]:
    """Ссылки вне диапазона выданных фрагментов — ВЫДУМАННЫЙ ИСТОЧНИК.

    Номера фрагментов обновляются на каждом вопросе мини-чата, и модель иногда
    переносит номер из предыдущего ответа или придумывает его. Такой номер
    указывает на ДРУГОЙ документ, то есть ссылка врёт — проверка называет это
    фактом (в отличие от «цитата не подтверждает слова», что оценивает судья
    прогона: там нужна фраза, а не число).
    """
    limit = int(count or 0)
    if limit <= 0:
        return citations(answer)
    return sorted({value for value in citations(answer)
                   if value < 1 or value > limit})


def strip_bad_citations(answer: Any, count: int) -> str:
    """Убирает из ответа ссылки на фрагменты, КОТОРЫХ НЕ ВЫДАВАЛИ.

    «Промпт — просьба, гарантия — код»: правила цитирования написаны в промпте,
    но модель их нарушает — особенно когда фрагментов нет вовсе (базы знаний не
    подключены). Тогда в ответе появляются ссылки на несуществующие документы
    («[1]…[5]»), и человек видит источники, которых не существует: это хуже, чем
    ответ без ссылок вообще.

    Убираются ТОЛЬКО номера вне диапазона выданных фрагментов (`count`): ссылки
    на настоящие фрагменты остаются как были, а `count = 0` (фрагментов нет)
    убирает все. Квадратные скобки с текстом («[важно]») не трогаются.
    """
    text = str(answer or "")
    limit = int(count or 0)
    if not text or not has_citation(text):
        return text

    def keep(match: "re.Match") -> str:
        number = int(match.group(1))
        return match.group(0) if 1 <= number <= limit else ""

    cleaned = re.sub(r"\[(\d{1,3})\]", keep, text)
    # Ссылка стояла в конце предложения («… [1].») — после её удаления остаётся
    # висячий пробел перед точкой; чистим, чтобы текст выглядел нормально.
    cleaned = re.sub(r"[ \t]+([.,;:!?])", r"\1", cleaned)
    cleaned = re.sub(r"[ \t]{2,}", " ", cleaned)
    return cleaned.strip()


# Блок для модели, когда ФРАГМЕНТОВ НЕТ ВООБЩЕ (базы знаний не подключены):
# правило цитирования из ANSWER_PROMPT на такой ответ не распространяется, и
# сказать об этом надо прямо — иначе модель «ссылается» на несуществующие
# документы, а человек читает ссылки на то, чего нет.
NO_FRAGMENTS_NOTE = (
    "ФРАГМЕНТОВ ДОКУМЕНТОВ НЕТ: базы знаний проекта не подключены (или поиск по "
    "ним не выполнялся). Правило про номера фрагментов к этому ответу НЕ "
    "относится: ссылок вида [1] в ответе быть НЕ ДОЛЖНО, и упоминать документы, "
    "базы знаний, поиск и «источники» не нужно вовсе — отвечай на вопрос по "
    "общим знаниям и не извиняйся за отсутствие документов."
)


def ensure_sources(answer: Any, hits: Any, searched: int = 0,
                   cut: str = "") -> str:
    """Ответ с источниками — гарантия кода: но ТОЛЬКО когда их было где искать.

    Модель просят сослаться на фрагменты, но просьба может быть не выполнена
    (забыла, ответила общими словами). Тогда строка источников дописывается к
    ответу: так человек под ответом видит, откуда взяты факты, а проверка
    (`/test_rag_dialog_*`) может убедиться в этом БЕЗ участия модели.

    ДВА правила, без которых строка превращается в шум и враньё:

    * **Базы знаний не подключены (`searched = 0`, фрагментов нет) — строки НЕТ
      вовсе.** «К проекту не подключено ни одной базы знаний» — это не источник,
      а сообщение о настройке, и в ответе на обычный вопрос ему не место;
    * **Ссылки на невыданные фрагменты убираются** (`strip_bad_citations`):
      выдуманный источник хуже честного отсутствия ссылок.
    """
    count = len([hit for hit in (hits or []) if isinstance(hit, dict)])
    text = strip_bad_citations(str(answer or "").strip(), count)
    items = [hit for hit in (hits or []) if isinstance(hit, dict)]
    if not items and int(searched or 0) <= 0:
        # Искать было негде — источников нет и строки быть не должно.
        return text
    # Фрагменты есть и модель сослалась на них — строка была бы повтором.
    if items and has_citation(text) and SOURCES_MARK in text:
        return text
    line = sources_line(items, searched=searched, cut=cut)
    if items and has_citation(text):
        # Ссылки в ответе есть, но самого перечня нет: добавим его — человек
        # должен видеть адреса фрагментов, а не только их номера.
        return (text + "\n\n" + line).strip()
    if SOURCES_MARK in text:
        return text
    return (text + "\n\n" + line).strip()


