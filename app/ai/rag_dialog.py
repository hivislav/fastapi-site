def judge_payload(sc: Dict[str, Any], rows: List[Dict[str, Any]],
                  memory: Any = None) -> str:
    """Сообщение судье: сценарий, план, память задачи и разговор по шагам.

    ПЛАН РАЗГОВОРА и ПАМЯТЬ ЗАДАЧИ уходят судье не для полноты: без них он
    принимал ЗАДАННЫЙ сценарием вопрос «в сторону» за потерю цели, а найденное
    на прошлых шагах — за выдумку (живой прогон 03.10 — ровно это).
    """
    topics = [step.get("topic") for step in turn_plan(sc) if step.get("topic")]
    lines = [goal_block(sc)]
    if topics:
        lines.append("")
        lines.append("ПЛАН РАЗГОВОРА (эти темы выбраны ЗАРАНЕЕ — вопрос по любой "
                     "из них не является уходом от цели):")
        for index, topic in enumerate(topics, 1):
            lines.append("  %d) %s" % (index, topic))
    if memory is not None and memory_store.has_content(memory):
        lines.append("")
        lines.append("ПАМЯТЬ ЗАДАЧИ В КОНЦЕ РАЗГОВОРА (что агент зафиксировал): "
                     + memory_store.summary_line(memory))
    lines.append("")
    lines.append("РАЗГОВОР ПО ШАГАМ:")
    for row in rows:
        # Фрагменты у агента: берём ИСТОЧНИКИ ответа (у них есть адрес, оценка и
        # выдержка) — по ним судья и проверяет, подтверждаются ли факты ответа.
        placeholders = _placeholders(row.get("sources") or [])
        answer = " ".join(str(row.get("answer") or "").split())[:ANSWER_LIMIT]
        if not answer:
            answer = "(ответа нет — вызов модели не удался: %s)" % (
                str(row.get("error") or "причина неизвестна")[:200])
        lines.append("")
        lines.append("ШАГ %d" % row.get("n"))
        lines.append("ВОПРОС ПОЛЬЗОВАТЕЛЯ: %s" % row.get("question"))
        lines.append("ОТВЕТ АГЕНТА: %s" % answer)
        lines.append("ИСТОЧНИКИ В ОТВЕТЕ: %s" % (
            "названы" if row.get("cited") else "не названы"))
        lines.append("ФРАГМЕНТЫ У АГЕНТА: %s" % (placeholders or "фрагментов не было"))
    lines.append("")
    lines.append("Оцени все %d шагов." % len(rows))
    return "\n".join(lines)


def _placeholders(hits: Any) -> str:
    """Адреса и выдержки фрагментов для судьи (по ним он сверяет факты)."""
    items = [hit for hit in (hits or []) if isinstance(hit, dict)]
    if not items:
        return ""
    parts: List[str] = []
    for index, hit in enumerate(items[:JUDGE_QUOTES_PER_TURN], 1):
        quote = " ".join(str(hit.get("snippet") or "").split())[:JUDGE_QUOTE_CHARS]
        parts.append("[%d] %s — «%s»" % (index, _short_address(hit), quote))
    if len(items) > JUDGE_QUOTES_PER_TURN:
        parts.append("и ещё %d фрагментов" % (len(items) - JUDGE_QUOTES_PER_TURN))
    return "; ".join(parts)


def parse_verdict(content: Any) -> Dict[str, Any]:
    """Разбирает вердикт судьи: {"items", "goal_kept", "summary"}.

    Разбор ТЕРПИМЫЙ (как у приёмщика задачи и `/test_rag`): русские и английские
    ключи, markdown вокруг JSON, обрезанный хвост. Не разобранный ответ не
    теряется — уходит в `summary` как есть.
    """
    text = str(content or "").strip()
    result: Dict[str, Any] = {"items": [], "summary": "", "goal_kept": None}
    if not text:
        return result
    payload = _load_object(text)
    raw_items = None
    if isinstance(payload, dict):
        for key in ("итоги", "items", "результаты", "шаги", "оценки"):
            if isinstance(payload.get(key), list):
                raw_items = payload[key]
                break
        if "цель_удержана" in payload or "goal_kept" in payload:
            result["goal_kept"] = _as_bool(payload.get("цель_удержана",
                                                       payload.get("goal_kept")))
        for key in ("общий_вывод", "вывод", "summary", "итог"):
            value = payload.get(key)
            if isinstance(value, str) and value.strip():
                result["summary"] = value.strip()[:2000]
                break
    elif isinstance(payload, list):
        raw_items = payload
    if raw_items is None:
        result["summary"] = text[:2000]
        return result
    for item in raw_items:
        if not isinstance(item, dict):
            continue
        number = _int(item.get("n") or item.get("номер") or item.get("шаг"))
        if not number:
            continue
        comment = ""
        for key in ("оценка", "комментарий", "comment", "причина", "details"):
            value = item.get(key)
            if isinstance(value, str) and value.strip():
                comment = value.strip()
                break
        result["items"].append({
            "n": number,
            "goal": _as_bool(item.get("цель", item.get("goal"))),
            "sources": _as_bool(item.get("источники", item.get("sources"))),
            "grounded": _as_bool(item.get("по_документам",
                                           item.get("grounded"))),
            # Ссылки: ведут ли номера «[N]» на те фрагменты, где эти цитаты
            # есть. Поле необязательное (модель может его не дать) — тогда
            # замечания по ссылкам не выдумываем.
            "links": _as_bool(item.get("ссылки", item.get("links"))),
            "comment": comment[:600],
        })
    result["items"].sort(key=lambda item: item["n"])
    if result["goal_kept"] is None and result["items"]:
        result["goal_kept"] = all(item["goal"] for item in result["items"])
    if not result["summary"] and not result["items"]:
        result["summary"] = text[:2000]
    return result


def _int(value: Any) -> int:
    """Целое из ответа модели (мусор — 0)."""
    try:
        return int(value or 0)
    except (TypeError, ValueError):
        return 0


def _as_bool(value: Any) -> bool:
    """Булево из ответа модели: True/«да»/«верно»/1 — истина, остальное ложь."""
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        return bool(value)
    return str(value or "").strip().lower() in ("true", "да", "верно", "ok",
                                                "1", "yes")


def _load_object(text: str) -> Any:
    """JSON из ответа модели (markdown, пояснения, обрезанный хвост)."""
    candidates = [text]
    if "```" in text:
        parts = text.split("```")
        candidates = [part.strip().lstrip("json").strip() for part in parts
                      if part.strip()]
        candidates.append(text)
    for candidate in candidates:
        repaired = json_utils.repair_json(candidate)
        if not repaired:
            continue
        try:
            return json.loads(repaired)
        except ValueError:
            continue
    start = text.find("{")
    end = text.rfind("}")
    if 0 <= start < end:
        repaired = json_utils.repair_json(text[start:end + 1])
        if repaired:
            try:
                return json.loads(repaired)
            except ValueError:
                return None
    return None


def verdict_lines(parsed: Dict[str, Any]) -> List[str]:
    """Строки вердикта для чата: по шагу — цель, источники, обоснованность."""
    lines: List[str] = []
    for item in (parsed.get("items") or []):
        marks = []
        marks.append("цель ✅" if item["goal"] else "цель ❌")
        marks.append("источники ✅" if item["sources"] else "источники ❌")
        marks.append("без выдумок ✅" if item["grounded"] else "ВЫДУМКИ ❌")
        if not item["links"]:
            marks.append("ссылки ❌")
        line = "%d. %s" % (item["n"], ", ".join(marks))
        if item["comment"]:
            line += " — " + item["comment"]
        lines.append(line)
    return lines


def summary_text(parsed: Dict[str, Any], stats: Dict[str, Any]) -> str:
    """Итог прогона: удержана ли цель, у всех ли ответов источники, верные шаги.

    ЧАСТЬ ИТОГА СЧИТАЕТ КОД, а не модель: сколько ответов пришло с источниками
    (`stats`), видно по событиям потока, и это факт, а не оценка. Судья отвечает
    только за то, чего код знать не может: служит ли ответ цели и нет ли в нём
    выдуманных фактов.
    """
    lines: List[str] = []
    turns = int(stats.get("turns") or 0)
    with_sources = int(stats.get("with_sources") or 0)
    if turns:
        lines.append("Ответов с источниками: %d из %d%s"
                     % (with_sources, turns,
                        "" if with_sources == turns else " — ⚠ есть ответы БЕЗ источников"))
    goal_kept = parsed.get("goal_kept")
    if goal_kept is not None:
        lines.append("Цель задачи: " + ("удержана ✅" if goal_kept
                                        else "⚠ ПОТЕРЯНА"))
    items = parsed.get("items") or []
    if items:
        good = sum(1 for item in items if item["goal"] and item["sources"]
                   and item["grounded"])
        lines.append("Шагов без замечаний: %d из %d." % (good, len(items)))
    if not lines:
        lines.append("Оценку получить не удалось — смотрите ответ судьи ниже.")
    return "\n".join(lines)


def yield_hint(stats: Dict[str, Any], min_score: Any = None,
               min_ce: Any = None, filter_on: bool = True) -> str:
    """Подсказка, когда фрагментов почти нет: чаще всего виноват ПОРОГ, а не агент.

    Живой случай 03.10: в проекте стоял порог первичной релевантности 0,95–0,96,
    поиск не находил ничего, агент честно отвечал «в документах этого нет» — и
    прогон выглядел провалом («ответов с источниками 0 из 10, цель потеряна»),
    хотя проверял он НАСТРОЙКУ ПОИСКА, а не работу агента. Человеку в этом случае
    нужно не «агент плох», а «снизьте порог: рабочий диапазон 0,3–0,5».
    """
    turns = int((stats or {}).get("turns") or 0)
    with_sources = int((stats or {}).get("with_sources") or 0)
    if not turns or with_sources * 2 >= turns:
        return ""
    try:
        score = float(min_score or 0.0)
    except (TypeError, ValueError):
        score = 0.0
    parts = ["⚠ Ответов с источниками %d из %d: фрагменты почти не находились, "
             "и такой прогон проверяет настройку поиска, а не работу агента."
             % (with_sources, turns)]
    if filter_on and score > 0.5:
        parts.append("Похоже, порог первичной релевантности проекта (%.2f) отсекает "
                     "найденное: рабочий диапазон 0,3–0,5 (панель «Поиск и ответы»)."
                     % score)
    else:
        parts.append("Проверьте, включены ли базы знаний у проекта и есть ли в них "
                     "нужные документы (кнопка «RAG»).")
    return " ".join(parts)


def turn_stats(rows: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Счётчики прогона по данным потока: реплики, ответы, источники, ловушки."""
    answered = [row for row in rows if str(row.get("answer") or "").strip()]
    with_sources = [row for row in answered if row.get("sources")]
    return {
        "turns": len(rows),
        "answers": len(answered),
        "with_sources": len(with_sources),
        "without_sources": len(answered) - len(with_sources),
        "cited": sum(1 for row in answered if row.get("cited")),
        # Ссылки на несуществующие фрагменты — выдуманный источник (проверка КОДА).
        "bad_cites": sum(1 for row in answered if row.get("bad_cites")),
        "bad_cite_numbers": sorted({number for row in answered
                                    for number in (row.get("bad_cites") or [])}),
        "errors": sum(1 for row in rows if row.get("error")),
        "fragments": sum(int(row.get("hits") or 0) for row in rows),
        "trap": next((row.get("n") for row in rows if row.get("trap")), 0),
        "trap_honest": next((bool(row.get("honest")) for row in rows
                             if row.get("trap")), False),
    }


def usage_line(usage: Dict[str, Any], stats: Dict[str, Any]) -> str:
    """Итоговая строка о расходе прогона (в замер задачи он не входит)."""
    calls = int((usage or {}).get("requests") or 0)
    prompt = int((usage or {}).get("input") or 0)
    completion = int((usage or {}).get("output") or 0)
    cost = float((usage or {}).get("cost_rub") or 0.0)
    return ("Расход диалога: вызовов модели %d, входящих токенов %d, исходящих "
            "%d, стоимость %.4f руб. В замер задачи расход теста не входит."
            % (calls, prompt, completion, cost))
