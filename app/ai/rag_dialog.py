def scenarios() -> List[Dict[str, Any]]:
    """Оба сценария по порядку (для проверок и подписи в чате)."""
    return list(SCENARIOS)


def scenario(number: Any) -> Optional[Dict[str, Any]]:
    """Сценарий по номеру (1 или 2); вне диапазона — None."""
    try:
        index = int(number or 0)
    except (TypeError, ValueError):
        index = 0
    for item in SCENARIOS:
        if item["id"] == index:
            return item
    return None


def command(number: Any) -> str:
    """Команда чата для сценария: `/test_rag_dialog_1`."""
    return "/test_rag_dialog_%d" % int(number or 0)


def opening(sc: Dict[str, Any]) -> List[str]:
    """Реплики, заданные хардкодом (старт разговора)."""
    return [str(item) for item in (sc.get("opening") or [])][:OPENING_TURNS]


def roadmap(sc: Dict[str, Any]) -> List[str]:
    """Пункты плана разговора — по одному на каждую реплику имитации."""
    return [str(item) for item in (sc.get("roadmap") or [])]


def turn_plan(sc: Dict[str, Any]) -> List[Dict[str, Any]]:
    """План диалога: что за реплика и откуда она берётся (всего TURNS штук).

    Каждый шаг: {"n", "source": "fixed"|"model", "text"|"topic"}. Проверкам и
    интерфейсу это нужно, чтобы видеть ПОЛНЫЙ план прогона до его начала: какой
    сценарий, сколько реплик, где кончается хардкод и начинается имитация.
    """
    fixed = opening(sc)
    topics = roadmap(sc)
    plan: List[Dict[str, Any]] = []
    for number in range(1, TURNS + 1):
        if number <= len(fixed):
            plan.append({"n": number, "source": "fixed", "text": fixed[number - 1],
                         "topic": ""})
            continue
        index = number - len(fixed) - 1
        topic = topics[index] if 0 <= index < len(topics) else ""
        plan.append({"n": number, "source": "model", "text": "", "topic": topic})
    return plan


def turn_topic(sc: Dict[str, Any], number: int) -> str:
    """О чём спросить на этой реплике (пусто — реплика задана хардкодом)."""
    for step in turn_plan(sc):
        if step["n"] == number:
            return step["topic"]
    return ""


def is_trap(sc: Dict[str, Any], number: int) -> bool:
    """Ловушка ли этот шаг: вопрос, ответа на который в базе нет.

    Номер шага-ловушки задан СЦЕНАРИЕМ, а не текстом пункта: поведение «честно
    сказать, что данных нет» надо проверять по факту ответа (см.
    `looks_like_no_data`), а не по формулировке задания имитации.
    """
    try:
        return int(sc.get("trap_turn") or 0) == int(number or 0)
    except (TypeError, ValueError):
        return False


# Формулировки честного «в документах этого нет»: по ним КОД (а не судья)
# проверяет главное свойство ответа на вопрос-ловушку.
NO_DATA_MARKERS = (
    "в документах этого нет", "в документах нет", "в базе этого нет",
    "в базе нет", "нет в документ", "не найдено", "не нашлось", "не упомина",
    "нет данных", "ничего не сказано", "отсутствует", "не содержится",
    "не удалось найти",
)


def looks_like_no_data(answer: Any) -> bool:
    """Сказал ли ответ честно, что данных в документах нет.

    Проверка нужна тесту: на вопрос-ловушку верный ответ — именно это, а не
    рассказ по общим знаниям. Формулировку модель выбирает сама, поэтому ищем
    не одну фразу, а набор равнозначных (список — данные модуля, а не догадка
    вызывающего кода).
    """
    text = str(answer or "").lower()
    return any(marker in text for marker in NO_DATA_MARKERS)


def fallback_question(topic: Any) -> str:
    """Реплика пользователя из пункта плана — если имитация не ответила.

    Пункты сценария сформулированы как вопросы, поэтому сбой служебного вызова
    имитации НЕ превращается в пропуск шага: разговор продолжается по плану,
    просто реплика берётся из сценария дословно. Девять ответов агента из десяти
    — всё ещё проверка, а пропущенный шаг — нет.
    """
    text = " ".join(str(topic or "").split())
    return text[:QUESTION_LIMIT]


def goal_block(sc: Dict[str, Any]) -> str:
    """Цель и ограничения сценария текстом (для имитации и судьи)."""
    lines = ["ЧТО РАЗЫГРЫВАЕТСЯ: " + str(sc.get("battle") or ""),
             "ЦЕЛЬ РАЗГОВОРА (её держит агент): " + str(sc.get("goal") or "")]
    criteria = [str(item) for item in (sc.get("criteria") or [])]
    if criteria:
        lines.append("ЧТО ПРОВЕРЯЕТСЯ В КОНЦЕ:")
        lines.extend("  - " + item for item in criteria)
    return "\n".join(lines)


