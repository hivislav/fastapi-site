# ФРАЗА-ПЕРЕОПРЕДЕЛЕНИЕ: ею вариант «разложить на шаги» превращает прямой ответ в
# работу. Механизм тот же, что у вариантов пустого поиска (см. `GENERAL_CHOICE` в
# rag_search): вариант отправляет ГОТОВУЮ ФРАЗУ, сервер узнаёт по ней решение — и
# в тексте запроса оказывается признак работы, который видит гейт
# (`task_state.needs_plan`). Флаг в запросе тут не нужен, и это важно: вариант
# восстанавливается из журнала (в журнале хранятся только фраза и заголовок), а
# значит кнопка работает и после перезагрузки страницы.
PLAN_PHRASE = "разложи на шаги"


def plan_choice(question: Any) -> Dict[str, Any]:
    """Вариант «разложить работу на шаги» для ответа прямого пути.

    Это ВОССТАНОВЛЕНИЕ ПОСЛЕ ОШИБКИ ГЕЙТА: если код решил, что запрос — вопрос,
    а человек хотел работу, он получает план одним нажатием, не переписывая
    запрос и не переключая тип задачи.
    """
    text = " ".join(str(question or "").split())
    return {
        "title": "⚙ Разложить работу на шаги",
        "details": "план с подтверждением, шагами и проверкой результата — "
                   "тот же запрос, но как задача",
        "send": ("%s, %s" % (text, PLAN_PHRASE)).strip(", "),
    }


def history_text(messages: Any, limit: int = HISTORY_CHARS,
                 count: int = HISTORY_MESSAGES) -> str:
    """Хвост истории разговора текстом: «Пользователь: … / Агент: …».

    Берём ХВОСТ, а не начало: продолжить разговор можно только по последним
    репликам, а вся история целиком раздула бы каждый запрос мини-чата.
    """
    rows = [item for item in (messages or []) if isinstance(item, dict)]
    lines: List[str] = []
    total = 0
    for item in reversed(rows[-max(1, int(count or 1)):]):
        text = " ".join(str(item.get("content") or "").split())
        if not text:
            continue
        who = "Пользователь" if item.get("role") == "user" else "Агент"
        line = "%s: %s" % (who, text)
        if lines and total + len(line) > limit:
            break
        lines.append(line)
        total += len(line)
    return "\n".join(reversed(lines))


def answer_messages(memory_block: str, rag_block: str, history: str,
                    question: str, profile: str = "",
                    extra_blocks: Any = None) -> List[Dict[str, str]]:
    """Сообщения для вызова ответа: блоки + история + вопрос.

    Порядок — как у агента: профиль пользователя, ДОПОЛНИТЕЛЬНЫЕ БЛОКИ (правила
    проекта и данные внешних инструментов — их передаёт режим «AI-агент»,
    `extra_blocks`), память задачи, фрагменты документов (или честное «не
    нашлось»), история разговора, вопрос. Фрагменты идут ДО истории намеренно:
    это справочный материал по текущему вопросу, и путать его с репликами
    разговора нельзя.

    `extra_blocks` — блоки, которые движок сам не собирает: инварианты проекта
    (`invariants_store.block`) и данные MCP (`mcp_store.block`). Это и есть
    объединение «разговора» и «задачи»: источники у обоих путей ОДНИ, разница
    только в том, строятся ли шаги.
    """
    messages: List[Dict[str, str]] = [{"role": "system", "content": ANSWER_PROMPT}]
    if str(profile or "").strip():
        messages.append({"role": "system", "content": str(profile).strip()})
    for block in (extra_blocks or []):
        if str(block or "").strip():
            messages.append({"role": "system", "content": str(block).strip()})
    if str(memory_block or "").strip():
        messages.append({"role": "system", "content": str(memory_block).strip()})
    if str(rag_block or "").strip():
        messages.append({"role": "system", "content": str(rag_block).strip()})
    else:
        # Фрагментов нет вовсе (базы знаний не подключены) — правило цитирования
        # к такому ответу не относится, и модель обязана узнать об этом: иначе она
        # «ссылается» на несуществующие документы (см. NO_FRAGMENTS_NOTE).
        messages.append({"role": "system", "content": NO_FRAGMENTS_NOTE})
    if str(history or "").strip():
        messages.append({"role": "system", "content": (
            "ИСТОРИЯ РАЗГОВОРА (последние реплики, от старых к новым):\n"
            + str(history).strip())})
    messages.append({"role": "user", "content": str(question or "").strip()})
    return messages


