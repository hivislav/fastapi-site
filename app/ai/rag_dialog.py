def simulator_payload(sc: Dict[str, Any], number: int, history: str,
                      memory: Any = None) -> str:
    """Сообщение модели-«пользователю»: сценарий, пункт плана и разговор.

    Пункт плана («о чём спросить») задан СЦЕНАРИЕМ, а формулировка — моделью:
    так покрытие сценария не зависит от фантазии модели, но реплики остаются
    живыми и связанными с предыдущими ответами.
    """
    topic = turn_topic(sc, number) or "продолжи разговор по цели задачи"
    lines = [goal_block(sc), ""]
    lines.append("РЕПЛИКА № %d из %d." % (number, TURNS))
    lines.append("О ЧЁМ СПРОСИТЬ ЭТОЙ РЕПЛИКОЙ: " + topic)
    if memory is not None:
        if memory_store.has_content(memory):
            lines.append("")
            lines.append("ЧТО АГЕНТ УЖЕ ЗНАЕТ О ЗАДАЧЕ (память задачи): "
                         + memory_store.summary_line(memory))
    lines.append("")
    lines.append("РАЗГОВОР К ЭТОМУ МОМЕНТУ:")
    lines.append(history.strip() or "(разговор только начинается)")
    lines.append("")
    lines.append("Напиши ТОЛЬКО текст следующей реплики пользователя.")
    return "\n".join(lines)


def parse_user(content: Any, limit: int = QUESTION_LIMIT) -> str:
    """Реплика пользователя из ответа имитации: без кавычек и приписок.

    Модель иногда добавляет «Пользователь:» или оборачивает реплику в кавычки —
    это служебный мусор, он не должен попадать в диалог и в поиск по базе.
    """
    text = str(content or "").strip()
    if not text:
        return ""
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    if not lines:
        return ""
    value = lines[0]
    for prefix in ("Пользователь:", "Пользователь :", "Реплика:", "USER:",
                   "User:"):
        if value.startswith(prefix):
            value = value[len(prefix):].strip()
    value = " ".join(value.split())
    value = value.strip('"«»\u201c\u201d')
    if len(value) > limit:
        value = value[:limit].rstrip() + "…"
    return value


