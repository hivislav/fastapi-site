"""Точка входа приложения.

Здесь только собирается FastAPI-приложение из независимых модулей.
Вся логика вынесена в пакет app/: конфигурация, схемы, ИИ-слой, маршруты
и фронтенд. Этот файл однажды определяет app — запуск: uvicorn main:app.

Вместе с приложением поднимается ПЛАНИРОВЩИК ПЕРИОДИЧЕСКИХ ЗАДАЧ
(app/periodic_runner.py): он повторяет запросы задач с расписанием (кнопка
«Новая периодическая задача») и складывает результат в чат этих задач. Работает
в том же процессе и цикле событий, поэтому видит те же задачи, что и API;
выключается настройкой PERIODIC_ENABLED=0.

Перед запуском восстанавливается ВЫБРАННЫЙ ИСТОЧНИК ОТВЕТА (переключатель
«локальная / удалённая модель» в панели workspace, см. app/ai/local_llm.py):
выбор хранится в config.LLM_SOURCE_FILE и переживает перезапуск приложения.
Локальный сервер модели приложение само не поднимает — это делает
переключатель или tools/local_llm.sh, чтобы запуск веб-приложения не ждал
загрузки весов (гигабайты в память) и не решал за человека.

ДОСТУП ИЗ ВНЕШНЕЙ СЕТИ. Наружу приложение отдаётся пробросом порта на
роутере (внешний адрес → адрес мака в сети дома, порт 8000), поэтому перед всем
приложением
стоит ГЕЙТ ДОСТУПА: вход по паролю из .env (app/auth.py). Запуск «наружу» —
tools/serve.sh (обычный `uvicorn main:app` слушает только 127.0.0.1 и снаружи
недоступен). Без заданного пароля гейт не пускает наружу никого.
"""

from contextlib import asynccontextmanager

from fastapi import FastAPI
from fastapi.middleware.gzip import GZipMiddleware

from app import periodic_runner
from app.ai import local_llm
from app.auth import AuthGate
from app.routers import auth as auth_routes
from app.routers import chat, pages

# Источник ответа из файла настроек — ДО первого запроса к модели: иначе
# приложение начало бы работу на удалённой модели, хотя человек выбрал
# локальную (и наоборот).
local_llm.apply_saved_source()


@asynccontextmanager
async def lifespan(app: FastAPI):
    """Запуск и остановка фоновых служб приложения.

    Планировщик стартует ВМЕСТЕ с приложением (первый тик — с небольшой
    задержкой, см. PERIODIC_START_DELAY) и останавливается вместе с ним: без
    этого повтор задачи шёл бы в уже закрытом цикле событий.
    """
    periodic_runner.start()
    try:
        yield
    finally:
        await periodic_runner.stop()


app = FastAPI(title="Чат-бот на FastAPI", lifespan=lifespan)

# Сжатие ответов: страница чата и сохранённый диалог — крупные JSON/HTML
# (страница ~290 КБ, диалог с журналом до ~35 КБ), и они отдаются заново при
# каждом переключении задачи. С gzip это в 5–6 раз меньше трафика.
#
# НО ПОТОКИ СОБЫТИЙ СЖИМАТЬ НЕЛЬЗЯ — и это не оптимизация, а исправление
# живого дефекта (найден 03.10 замерами). `GZipMiddleware` из Starlette сжимает
# КАЖДЫЙ кусок потока через zlib, а zlib копит мелкие куски во внутреннем буфере
# и отдаёт их только когда наберётся блок: в браузере (он всегда присылает
# `Accept-Encoding: gzip`) ответ выглядел так, будто сервер молчит весь прогон, а
# в конце разом вываливает всё — жалоба была ровно на это («долгое ожидание и
# потом куча информации»). Замер одного и того же запроса: без gzip события
# приходили на 0,00 / 0,63 / 1,80 / 2,94 с, с gzip — ВСЕ на 2,40 с.
# Поэтому потоки (NDJSON чата агента, `/test_rag`, контрольных диалогов) идут
# МИМО сжатия: они и так отдаются по мере появления, а сжатие им ничего не даёт
# (объём небольшой, а задержка видна человеку).
_STREAM_PATHS = (
    "/api/agent/chat",
    "/api/agent/rag/test",
    "/api/agent/rag/dialog",
    "/api/agent/rag/dialog/test",
)


class GZipExceptStreams(GZipMiddleware):
    """GZip, но НЕ для потоковых маршрутов (`_STREAM_PATHS`).

    Список путей, а не признак ответа, намеренно: middleware видит запрос ДО
    маршрута и не знает, будет ли ответ потоком; зато пути потоков — часть
    контракта API (см. §5.7 в SESSION_PROMPT), и их немного. Новый потоковый
    маршрут обязан попасть в список: иначе он «замолчит» до конца ответа.
    """

    async def __call__(self, scope, receive, send):
        if scope.get("type") == "http" and scope.get("path") in _STREAM_PATHS:
            await self.app(scope, receive, send)
            return
        await super().__call__(scope, receive, send)


app.add_middleware(GZipExceptStreams, minimum_size=1024)

# ГЕЙТ ДОСТУПА (app/auth.py) — добавляется ПОСЛЕДНИМ, то есть оказывается самым
# внешним слоем: пока пароль не предъявлен, запрос не доходит ни до gzip, ни до
# маршрутов. Маршрутов пятьдесят восемь, и защита «в каждом маршруте» рано или
# поздно забылась бы на новом; здесь она одна и по умолчанию — на всём.
# Исключения (страница входа и маршруты входа/выхода) перечислены в
# auth.OPEN_PATHS. Локальный клиент (127.0.0.1) гейт пропускает без пароля —
# этого требуют живые проверки проекта, которые ходят по HTTP на 127.0.0.1.
app.add_middleware(AuthGate)

app.include_router(pages.router)
app.include_router(auth_routes.router)
app.include_router(chat.router)
